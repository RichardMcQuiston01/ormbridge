/** The name of a registered format. Valid names are whatever the registry currently holds. */
export type FormatName = string;

export const DEFAULT_APP_LABEL: string = 'app';

export interface SourceText {
  path: string;
  text: string;
  /** App label derived from the file location (Django input only). */
  appLabel?: string;
}

/** Options handed to every adapter. Each adapter reads only the fields that apply to it. */
export interface FormatOptions {
  /** "preserve" keeps existing database names; "normalize" applies a fresh-schema style. */
  naming: NamingMode;
  /**
   * Database provider. Prisma uses it for native column types such as @db.VarChar, Drizzle and GORM
   * for the dialect, and the SQL DDL emitter for the SQL it writes (postgresql, mysql, sqlite, sqlserver).
   * `cockroachdb` is written with PostgreSQL's types, replacing what CockroachDB lacks, and warns about
   * each difference. `mysql` also covers MySQL-compatible servers (MariaDB, Percona Server).
   */
  provider: PrismaProvider;
  /** Emit Prisma generator and datasource blocks, or the `// <auto-generated>` comment of EF Core and JPA files. */
  header: boolean;
  /** Prisma major version the generated header targets: 6 (default) or 7 (`prisma-client`, no datasource url). */
  prismaVersion?: 6 | 7;
  /** Overrides the Django app label (otherwise derived from the models.py directory). */
  appLabel?: string;
  /** Primary key type used for Django models without an explicit key. */
  autoField: 'int' | 'bigInt';
  /**
   * Namespace of the generated classes. PHP: Doctrine entities default to `App\Entity` (enums in the sibling
   * `Enum` namespace); Laravel models default to `App\Models` (enums in `App\Enums`). C#: the EF Core classes,
   * enums and context default to `App.Models`. Java: the package of the JPA entities, enums and converters
   * (default `app.models`).
   */
  namespace?: string;
  /** Go package name of the generated GORM models (default `models`); also the output directory. */
  goPackage?: string;
  /**
   * Layout of the output of the formats that have styles. SQLAlchemy: `sqlalchemy` (default; `DeclarativeBase`,
   * `Mapped[...]` and `mapped_column`) or `sqlmodel` (`SQLModel, table=True` classes with `Field` and
   * `Relationship`). Sequelize: `init` (default; TypeScript classes with `Model.init`), `define`
   * (the CommonJS files `sequelize-cli` generates), `v6` (the same as `init`) or `v7` (Sequelize 7 decorators). EF Core: `annotations` (default; data annotations on the entity
   * classes, the fluent API only where annotations cannot say it) or `fluent` (plain classes plus one
   * `IEntityTypeConfiguration<T>` per entity). Only the `sqlalchemy`, `sequelize` and `efcore` formats read it.
   */
  style?: OutputStyle;
  /**
   * How the JPA output writes a composite primary key: `idclass` (default; an `@IdClass` class) or `embedded` (an
   * `@Embeddable` key class with `@EmbeddedId`, and `@MapsId` on a relationship in the key). Only `jpa` reads it.
   */
  jpaKey?: JpaKeyMode;
  /**
   * How the JPA output writes a model whose primary key is its one-to-one relation to another model: `none` (default;
   * a derived identity, `@Id @OneToOne`) or `joined` (a subclass of the other model with `@Inheritance(strategy =
   * JOINED)`). Only `jpa` reads it.
   */
  jpaInheritance?: JpaInheritanceMode;
  /**
   * Write Lombok annotations (`@Getter`, `@Setter`, `@NoArgsConstructor`; `@EqualsAndHashCode` on key classes) in
   * the JPA output instead of hand-written accessors (default false). Only `jpa` reads it.
   */
  lombok?: boolean;
  /**
   * Write ormbridge's `x-` convention keywords (table names, keys, indexes, referential actions) into JSON Schema
   * output (default true). Turn it off for validators that reject unknown keywords. Only `json-schema` reads it.
   */
  conventions?: boolean;
}

/**
 * Output of an emitter that produces several files. `files` maps a relative
 * path (forward slashes, no leading slash, no `..`) to the file text. The
 * single-text form (`EmitOutput`) stays valid; no existing emitter changes.
 */
export interface MultiFileEmitOutput {
  files: Record<string, string>;
  warnings: string[];
  /** Absent in the multi-file form, which lets code tell the two forms apart. */
  text?: undefined;
}

/** What `FormatAdapter.emit` returns: one text, or a map of files. */
export type FormatEmitOutput = EmitOutput | MultiFileEmitOutput;

/** What a format reads from a directory. */
export interface FormatInput {
  /** Extensions of the source files, with the dot (`.kt`). */
  extensions: readonly string[];
  /** What the files are, for the message when none is found (`Kotlin (.kt) files with JPA entities`). */
  description: string;
  /** Directory names that are never searched (`build`, `node_modules`, ...). */
  skippedDirectories?: readonly string[];
  /** False when only the directories above are skipped, without the names every folder walk skips (`migrations`, `build`, `dist`, `env`). Default: true. */
  inheritSkippedDirectories?: boolean;
  /** Directories that are skipped by their name and the folder they are in (`bootstrap/cache`). */
  isSkippedDirectory?: (name: string, parent: string) => boolean;
  /** The folders to read when a directory is given (a project root holds the model folders). Default: the directory itself. */
  roots?: (directory: string) => Promise<readonly string[]>;
  /** True when the directory names above match in any letter case (`Bin`, `OBJ`). */
  skippedDirectoriesIgnoreCase?: boolean;
  /** Files with an accepted extension that are not part of the model (tests, generated code). */
  isSkippedFile?: (path: string) => boolean;
}

/**
 * One ORM format. An adapter that omits `parse` can only be written (output
 * only); one that omits `emit` can only be read (input only).
 */
export interface FormatAdapter {
  /** Unique identifier used by --from / --to and the programmatic API. */
  name: string;
  /**
   * Set on the stub of a format that moved into an addon package: the stub fails with a message that names the package,
   * and registering the real format under the same name replaces it.
   */
  movedTo?: { packageName: string };
  /** File extensions (with the leading dot) used to infer this format from a path. */
  extensions: string[];
  /** One-line, human-readable summary shown by `ormbridge formats`. */
  description: string;
  /**
   * Which files a directory input contributes. Without it a directory is searched the way Django models are (a
   * `models.py` file or a `models/` package), so a format added by an addon should say what it reads.
   */
  input?: FormatInput;
  /** Reads source text into the shared intermediate representation. */
  parse?: (
    sources: SourceText[],
    options: FormatOptions
  ) => Promise<Result<IrSchema>>;
  /**
   * Writes the intermediate representation as source text, or as several
   * files (`MultiFileEmitOutput`) when the format needs more than one.
   */
  emit?: (schema: IrSchema, options: FormatOptions) => Result<FormatEmitOutput>;
}

const adapters: Map<string, FormatAdapter> = new Map<string, FormatAdapter>();

/**
 * Adds an adapter to the registry. Fails when the name or an extension is already taken, except that the stub of a moved
 * format (`movedTo`) is replaced by the real format, in the same place of the list.
 */
export function registerFormat(adapter: FormatAdapter): Result<FormatAdapter> {
  if (adapter.name.trim() === '') {
    return err(
      'INVALID_OPTION',
      'A format adapter must have a non-empty name.'
    );
  }
  const existing: FormatAdapter | undefined = adapters.get(adapter.name);
  if (existing !== undefined && existing.movedTo === undefined) {
    return err(
      'INVALID_OPTION',
      `The format "${adapter.name}" is already registered.`
    );
  }
  for (const extension of adapter.extensions) {
    const owner: FormatAdapter | undefined = getFormatByExtension(extension);
    if (owner !== undefined) {
      return err(
        'INVALID_OPTION',
        `The extension "${extension}" cannot be used by the format "${adapter.name}" because it is already used by "${owner.name}".`
      );
    }
  }
  adapters.set(adapter.name, adapter);
  return ok(adapter);
}

/** Removes an adapter from the registry. Returns false when the name was not registered. */
export function unregisterFormat(name: string): boolean {
  return adapters.delete(name);
}

/** Looks up a format by name. Returns a descriptive error that lists the valid names. */
export function getFormat(name: string): Result<FormatAdapter> {
  const adapter: FormatAdapter | undefined = adapters.get(name);
  if (adapter === undefined) {
    return err(
      'UNSUPPORTED_CONVERSION',
      `Unknown format "${name}". Expected one of: ${listFormatNames().join(', ')}.`
    );
  }
  return ok(adapter);
}

/** Returns the adapter that owns a file extension (for example ".py"), or undefined. */
export function getFormatByExtension(
  extension: string
): FormatAdapter | undefined {
  for (const adapter of adapters.values()) {
    if (adapter.extensions.includes(extension)) {
      return adapter;
    }
  }
  return undefined;
}

/** Returns every registered adapter in registration order. */
export function listFormats(): FormatAdapter[] {
  return [...adapters.values()];
}

/** Returns every registered format name in registration order. */
export function listFormatNames(): string[] {
  return [...adapters.keys()];
}

/** Builds the text printed by the `formats` command: one line per registered format. */
export function describeFormats(adapters: FormatAdapter[]): string {
  const nameWidth: number = Math.max(
    ...adapters.map((adapter: FormatAdapter) => adapter.name.length)
  );
  const lines: string[] = adapters.map((adapter: FormatAdapter): string => {
    const abilities: string[] = [];
    if (adapter.parse !== undefined) {
      abilities.push('read');
    }
    if (adapter.emit !== undefined) {
      abilities.push('write');
    }
    return (
      `${adapter.name.padEnd(nameWidth)}  ` +
      `extensions: ${adapter.extensions.join(', ') || '(none)'}  ` +
      `${abilities.join(' + ') || 'no read/write support'}  ` +
      adapter.description
    );
  });
  return `${lines.join('\n')}\n`;
}

const djangoAdapter: FormatAdapter = {
  name: 'django',
  extensions: ['.py'],
  description: 'Django models (models.py or a models/ package)',
  parse: (
    sources: SourceText[],
    options: FormatOptions
  ): Promise<Result<IrSchema>> => {
    const djangoSources: DjangoSourceFile[] = sources.map(
      (source: SourceText) => ({
        path: source.path,
        text: source.text,
        appLabel: options.appLabel ?? source.appLabel ?? DEFAULT_APP_LABEL,
      })
    );
    return parseDjango(djangoSources, { autoField: options.autoField });
  },
  emit: (schema: IrSchema): Result<EmitOutput> => ok(emitDjango(schema)),
};

const prismaAdapter: FormatAdapter = {
  name: 'prisma',
  extensions: ['.prisma'],
  description: 'Prisma schema (schema.prisma)',
  parse: (
    sources: SourceText[],
    options: FormatOptions
  ): Promise<Result<IrSchema>> => {
    const prismaSources: PrismaSourceFile[] = sources.map(
      (source: SourceText) => ({
        path: source.path,
        text: source.text,
      })
    );
    return Promise.resolve(
      parsePrisma(prismaSources, {
        appLabel: options.appLabel ?? DEFAULT_APP_LABEL,
      })
    );
  },
  emit: (schema: IrSchema, options: FormatOptions): Result<EmitOutput> => {
    const prepared: IrSchema =
      options.naming === 'normalize'
        ? normalizeSchema(schema)
        : expandManyToMany(schema);
    return ok(
      emitPrisma(prepared, {
        provider: options.provider,
        header: options.header,
        camelFields: options.naming === 'normalize',
        ...(options.prismaVersion === undefined
          ? {}
          : { prismaVersion: options.prismaVersion }),
      })
    );
  },
};

