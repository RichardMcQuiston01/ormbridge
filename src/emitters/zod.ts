/** True when the database fills the column in itself, so a create payload must not carry it. */
function isGeneratedByDatabase(field: IrField): boolean {
  if (field.generated !== undefined || field.isAutoUpdated) {
    return true;
  }
  const fallback: IrField['default'] = field.default;
  if (fallback === undefined) {
    return false;
  }
  return (
    fallback.kind === 'autoIncrement' ||
    (fallback.kind === 'dbExpression' &&
      fallback.isFunction === true &&
      COUNTER_FUNCTIONS.has(fallback.expression))
  );
}

function buildForwardMembers(
  context: EmitContext,
  model: IrModel,
  reverseMembers: Map<string, RelationMember[]>
): { scalars: Scalar[]; relations: RelationMember[] } {
  const scalars: Scalar[] = [];
  const relations: RelationMember[] = [];
  const names: ModelNames = namesOf(context, model);

  for (const field of model.fields) {
    const label: string = `${model.name}.${field.name}`;
    const omitOnCreate: boolean = isGeneratedByDatabase(field);
    scalars.push({
      name: names.fields.get(field.name) ?? field.name,
      schema: fieldSchema(context, label, field, true),
      nullable: field.isNullable,
      omitOnCreate,
      optionalOnCreate:
        !omitOnCreate &&
        (field.isNullable ||
          field.default !== undefined ||
          field.isDbDefault === true),
    });
  }

  for (const relation of model.relations) {
    const label: string = `${model.name}.${relation.name}`;
    const target: IrModel | undefined = findModel(
      context.schema,
      relation.targetModel
    );
    if (target === undefined) {
      context.warnings.push(
        `${label}: target model "${relation.targetModel}" does not exist in the schema; the relation was skipped.`
      );
      continue;
    }
    const targetName: string = modelTypeName(context, target);
    const relationProp: string =
      names.relations.get(relation.name) ?? relation.name;
    const inverseProp: string =
      context.inverseNames.get(label) ?? toSnakeCase(model.name);

    if (relation.kind === 'manyToMany') {
      relations.push({
        name: relationProp,
        target: targetName,
        list: true,
        nullable: false,
      });
      addReverse(reverseMembers, target.name, {
        name: inverseProp,
        target: modelTypeName(context, model),
        list: true,
        nullable: false,
      });
      continue;
    }

    const scalarProp: string | undefined = names.scalars.get(relation.name);
    if (scalarProp !== undefined) {
      let keySchema: string | undefined = referencedSchema(
        context,
        target,
        relation.toField
      );
      if (keySchema === undefined) {
        context.warnings.push(
          `${label}: target model "${target.name}" has no single-column primary key to reference; the foreign key "${scalarProp}" is validated as unknown.`
        );
        keySchema = 'z.unknown()';
      }
      scalars.push({
        name: scalarProp,
        schema: keySchema,
        nullable: relation.isNullable && keySchema !== 'z.unknown()',
        omitOnCreate: false,
        optionalOnCreate: relation.isNullable,
      });
    }
    relations.push({
      name: relationProp,
      target: targetName,
      list: false,
      nullable: relation.isNullable,
    });
    addReverse(reverseMembers, target.name, {
      name: inverseProp,
      target: modelTypeName(context, model),
      list: relation.kind !== 'oneToOne',
      nullable: relation.kind === 'oneToOne',
    });
  }
  return { scalars, relations };
}

function addReverse(
  reverseMembers: Map<string, RelationMember[]>,
  targetName: string,
  member: RelationMember
): void {
  const existing: RelationMember[] = reverseMembers.get(targetName) ?? [];
  existing.push(member);
  reverseMembers.set(targetName, existing);
}

// ---------------------------------------------------------------------------
// Models
// ---------------------------------------------------------------------------

function scalarLine(scalar: Scalar): string {
  return `  ${memberKey(scalar.name)}: ${scalar.schema}${scalar.nullable ? '.nullable()' : ''},`;
}

/** Writes `{ a: true, b: true }` for the given property names. */
function mask(names: string[]): string {
  return `{ ${names.map((name: string) => `${memberKey(name)}: true`).join(', ')} }`;
}

function emitModel(
  context: EmitContext,
  model: IrModel,
  scalars: Scalar[],
  relations: RelationMember[]
): string {
  const name: string = modelTypeName(context, model);
  const lines: string[] = [`export const ${name}Schema = z.object({`];
  for (const scalar of scalars) {
    lines.push(scalarLine(scalar));
  }
  lines.push('});', `export type ${name} = z.infer<typeof ${name}Schema>;`);

  if (model.isView !== true) {
    const omitted: string[] = scalars
      .filter((scalar: Scalar) => scalar.omitOnCreate)
      .map((scalar: Scalar) => scalar.name);
    const optional: string[] = scalars
      .filter((scalar: Scalar) => scalar.optionalOnCreate)
      .map((scalar: Scalar) => scalar.name);
    const create: string = `${name}Schema${omitted.length === 0 ? '' : `.omit(${mask(omitted)})`}${optional.length === 0 ? '' : `.partial(${mask(optional)})`}`;
    lines.push(
      '',
      `export const ${name}CreateSchema = ${create};`,
      `export type ${name}Create = z.infer<typeof ${name}CreateSchema>;`,
      '',
      `export const ${name}UpdateSchema = ${name}CreateSchema.partial();`,
      `export type ${name}Update = z.infer<typeof ${name}UpdateSchema>;`
    );
  }

  if (relations.length > 0) {
    lines.push('', ...relationLines(name, relations));
  }
  return lines.join('\n');
}

/**
 * The `WithRelations` type is written out by hand and annotates the schema, because the
 * schemas refer to each other and TypeScript cannot infer a type that depends on itself.
 */
function relationLines(name: string, relations: RelationMember[]): string[] {
  const typeLines: string[] = [];
  const schemaLines: string[] = [];
  for (const relation of relations) {
    const key: string = memberKey(relation.name);
    const related: string = `${relation.target}WithRelations`;
    const typeText: string = `${related}${relation.list ? '[]' : ''}${relation.nullable ? ' | null' : ''}`;
    typeLines.push(`  ${key}?: ${typeText};`);
    const lazy: string = relation.list
      ? `z.array(z.lazy(() => ${related}Schema))`
      : `z.lazy(() => ${related}Schema)`;
    schemaLines.push(
      `  ${key}: ${lazy}${relation.nullable ? '.nullable()' : ''}.optional(),`
    );
  }
  return [
    `export type ${name}WithRelations = ${name} & {`,
    ...typeLines,
    '};',
    `export const ${name}WithRelationsSchema: z.ZodType<${name}WithRelations> = ${name}Schema.extend({`,
    ...schemaLines,
    '});',
  ];
}
