function dateSchema(context: EmitContext, type: 'date' | 'dateTime'): string {
  if (context.dates === 'coerce') {
    return 'z.coerce.date()';
  }
  return type === 'date' ? 'z.iso.date()' : 'z.iso.datetime({ offset: true })';
}

function bigIntSchema(context: EmitContext): string {
  return context.bigints === 'bigint'
    ? 'z.coerce.bigint()'
    : 'z.string().regex(/^-?\\d+$/)';
}

/** A string of digits that fits `DECIMAL(maxDigits, decimalPlaces)`; any decimal number when unsized. */
function decimalSchema(field: IrField | undefined): string {
  const digits: number | undefined = field?.maxDigits;
  if (digits === undefined) {
    return 'z.string().regex(/^-?\\d+(\\.\\d+)?$/)';
  }
  const places: number = field?.decimalPlaces ?? 0;
  const integerDigits: number = Math.max(digits - places, 1);
  const fraction: string = places > 0 ? `(\\.\\d{1,${places}})?` : '';
  return `z.string().regex(/^-?\\d{1,${integerDigits}}${fraction}$/)`;
}

function rangeBoundSchema(context: EmitContext, field: IrField): string {
  switch (field.rangeOf) {
    case 'int':
      return 'z.number().int()';
    case 'bigInt':
      return bigIntSchema(context);
    case 'decimal':
      return decimalSchema(undefined);
    case 'dateTime':
      return dateSchema(context, 'dateTime');
    case 'date':
      return dateSchema(context, 'date');
    default:
      return 'z.string()';
  }
}

/**
 * Returns the Zod expression of a scalar field, without `.nullable()`. Problems are only
 * reported when `report` is true, so a type that is looked up twice produces one warning.
 */
function fieldSchema(
  context: EmitContext,
  label: string,
  field: IrField,
  report: boolean
): string {
  const element: string = elementSchema(context, label, field, report);
  let result: string = element;
  for (let level: number = 0; level < (field.arrayDepth ?? 0); level += 1) {
    result = `z.array(${result})`;
  }
  return result;
}

function elementSchema(
  context: EmitContext,
  label: string,
  field: IrField,
  report: boolean
): string {
  if (field.enumName !== undefined) {
    const enumDefinition: IrEnum | undefined = context.schema.enums.find(
      (candidate: IrEnum) => candidate.name === field.enumName
    );
    if (enumDefinition !== undefined) {
      return `${enumTypeName(context, enumDefinition)}Schema`;
    }
    if (report) {
      context.warnings.push(
        `${label}: enum "${field.enumName}" does not exist in the schema; the property is validated as a string.`
      );
    }
    return 'z.string()';
  }

  switch (field.type) {
    case 'string':
    case 'text':
      return field.maxLength === undefined
        ? 'z.string()'
        : `z.string().max(${field.maxLength})`;
    case 'uuid':
      return 'z.uuid()';
    case 'time':
    case 'duration':
      return 'z.string()';
    case 'bytes':
      // Binary data travels as base64 text.
      return 'z.base64()';
    case 'bigInt':
      return bigIntSchema(context);
    case 'decimal':
      return decimalSchema(field);
    case 'int':
      return 'z.number().int()';
    case 'float':
      return 'z.number()';
    case 'boolean':
      return 'z.boolean()';
    case 'dateTime':
      return dateSchema(context, 'dateTime');
    case 'date':
      return dateSchema(context, 'date');
    case 'json':
      return 'z.unknown()';
    case 'ipAddress':
      return 'z.union([z.ipv4(), z.ipv6()])';
    case 'hstore':
      return 'z.record(z.string(), z.string().nullable())';
    case 'range': {
      const bound: string = rangeBoundSchema(context, field);
      return `z.object({ lower: ${bound}.nullable(), upper: ${bound}.nullable(), bounds: z.string().optional() })`;
    }
    default:
      if (report) {
        context.warnings.push(
          `${label}: unknown field type "${String(field.type)}"; the property is validated as unknown.`
        );
      }
      return 'z.unknown()';
  }
}

/** Resolves the schema of the column a relation points at (an explicit to_field, else the primary key). */
function referencedSchema(
  context: EmitContext,
  target: IrModel,
  toField: string | undefined,
  depth: number = 0
): string | undefined {
  if (depth > MAX_KEY_DEPTH) {
    return undefined;
  }
  const explicit: IrField | undefined =
    toField === undefined
      ? undefined
      : target.fields.find((field: IrField) => field.name === toField);
  const column: IrField | undefined =
    explicit ?? target.fields.find((field: IrField) => field.isPrimaryKey);
  if (column !== undefined) {
    return fieldSchema(context, `${target.name}.${column.name}`, column, false);
  }
  const primaryRelation: IrRelation | undefined = target.relations.find(
    (relation: IrRelation) => relation.isPrimaryKey === true
  );
  if (primaryRelation === undefined) {
    return undefined;
  }
  const chained: IrModel | undefined = findModel(
    context.schema,
    primaryRelation.targetModel
  );
  return chained === undefined
    ? undefined
    : referencedSchema(context, chained, primaryRelation.toField, depth + 1);
}

