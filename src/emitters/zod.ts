import { prismaOnlyWarnings } from '../prismaOnlyConstructs.js';
import type {
  IrEnum,
  IrEnumValue,
  IrField,
  IrModel,
  IrRelation,
  IrSchema,
} from '../ir.js';
import { findModel } from '../ir.js';
import { toCamelCase, toSnakeCase } from '../naming.js';
import type { EmitOutput } from './prisma.js';

/**
 * Zod emitter (Zod 4).
 *
 * The output is one `schemas.ts`-style file. Property names, enum names and the
 * handling of relations follow the TypeScript interfaces emitter, so both can
 * be generated from the same IR and used together. For every model it writes:
 *
 * - `<Model>Schema` / `<Model>`: the row as stored. Relation fields are not part of it;
 *   foreign-key scalars are.
 * - `<Model>CreateSchema` / `<Model>Create`: the row without database-generated columns;
 *   columns with a default, and nullable columns, become optional.
 * - `<Model>UpdateSchema` / `<Model>Update`: every property of the create schema, optional.
 * - `<Model>WithRelationsSchema` / `<Model>WithRelations` (only for models that take part in
 *   a relation): the row plus optional, lazily resolved related rows.
 */

/**
 * How date and date-time columns are validated. `coerce` (the default) writes
 * `z.coerce.date()`, which accepts a `Date` or anything `new Date(value)` understands and
 * produces a `Date`; it also accepts `null` and numbers, so a null in a required date column
 * is not rejected. `string` keeps ISO 8601 text (`z.iso.datetime` / `z.iso.date`) and rejects
 * everything else, which matches the TypeScript interfaces emitter's default.
 */
export type ZodDateMode = 'coerce' | 'string';

/**
 * How 64-bit integers are validated. `string` (the default) accepts a string of digits, like
 * the TypeScript interfaces emitter, because JSON cannot carry a bigint. `bigint` writes
 * `z.coerce.bigint()`, which produces a native `bigint`.
 */
export type ZodBigIntMode = 'string' | 'bigint';

export interface ZodEmitOptions {
  /** Use camelCase property names (the `normalize` naming mode). */
  camelFields: boolean;
  /** Validation of DateTime and Date columns. Defaults to "coerce". */
  dates?: ZodDateMode;
  /** Validation of BigInt columns. Defaults to "string". */
  bigints?: ZodBigIntMode;
}

interface ModelNames {
  fields: Map<string, string>;
  relations: Map<string, string>;
  /** Foreign-key scalar property per relation (absent when a field already provides it). */
  scalars: Map<string, string>;
  used: Set<string>;
}

/** A scalar property of a row. */
interface Scalar {
  name: string;
  /** Schema expression without `.nullable()`. */
  schema: string;
  nullable: boolean;
  /** True when the create schema leaves the property out (generated by the database). */
  omitOnCreate: boolean;
  /** True when the create schema allows the property to be missing. */
  optionalOnCreate: boolean;
}

/** A related row, only part of the `WithRelations` schema. */
interface RelationMember {
  name: string;
  /** The related model's TypeScript type name, without `WithRelations`. */
  target: string;
  list: boolean;
  nullable: boolean;
}

interface EmitContext {
  schema: IrSchema;
  options: ZodEmitOptions;
  dates: ZodDateMode;
  bigints: ZodBigIntMode;
  warnings: string[];
  names: Map<string, ModelNames>;
  /** "Model.relation" -> property name of the reverse side on the target model. */
  inverseNames: Map<string, string>;
  /** Type names that were actually written (after sanitizing), per enum and model. */
  typeNames: Map<string, string>;
}

const IDENTIFIER_PATTERN: RegExp = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const MAX_KEY_DEPTH: number = 5;

/** Prisma default functions that the database fills in from a counter. */
const COUNTER_FUNCTIONS: ReadonlySet<string> = new Set([
  'auto()',
  'sequence()',
]);

/** Suffixes of the names written for a model, besides the model's own type name. */
const MODEL_SUFFIXES: readonly string[] = [
  'Schema',
  'Create',
  'CreateSchema',
  'Update',
  'UpdateSchema',
  'WithRelations',
  'WithRelationsSchema',
];

export function emitZod(schema: IrSchema, options: ZodEmitOptions): EmitOutput {
  const context: EmitContext = {
    schema,
    options,
    dates: options.dates ?? 'coerce',
    bigints: options.bigints ?? 'string',
    warnings: prismaOnlyWarnings(schema, true),
    names: new Map<string, ModelNames>(),
    inverseNames: new Map<string, string>(),
    typeNames: new Map<string, string>(),
  };

  allocateTypeNames(context);
  allocateMemberNames(context);

  const reverseMembers: Map<string, RelationMember[]> = new Map<
    string,
    RelationMember[]
  >();
  const forward: Map<
    string,
    { scalars: Scalar[]; relations: RelationMember[] }
  > = new Map<string, { scalars: Scalar[]; relations: RelationMember[] }>();
  for (const model of schema.models) {
    forward.set(
      model.name,
      buildForwardMembers(context, model, reverseMembers)
    );
  }

  const blocks: string[] = [];
  for (const enumDefinition of schema.enums) {
    blocks.push(emitEnum(context, enumDefinition));
  }
  for (const model of schema.models) {
    const members: { scalars: Scalar[]; relations: RelationMember[] } =
      forward.get(model.name) ?? { scalars: [], relations: [] };
    blocks.push(
      emitModel(context, model, members.scalars, [
        ...members.relations,
        ...(reverseMembers.get(model.name) ?? []),
      ])
    );
  }

  if (blocks.length === 0) {
    return { text: '', warnings: context.warnings };
  }
  return {
    text: `import { z } from 'zod';\n\n${blocks.join('\n\n')}\n`,
    warnings: context.warnings,
  };
}

