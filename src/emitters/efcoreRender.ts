/** Turns the plan of the EF Core emitter into C# files. */

const INDENT: string = '    ';
const MAX_LINE_WIDTH: number = 100;

/** The namespaces the generated code can use, by what in the text asks for them. */
const USINGS: readonly [RegExp, string][] = [
  [
    /\b(Guid|DateTime|DateOnly|TimeOnly|TimeSpan|Array|ArgumentOutOfRangeException)\b/,
    'System',
  ],
  [/\b(ICollection|List|Dictionary)</, 'System.Collections.Generic'],
  [/\[(Key|MaxLength)\b/, 'System.ComponentModel.DataAnnotations'],
  [
    /\[(Table|Column|ForeignKey|InverseProperty|DatabaseGenerated)\b/,
    'System.ComponentModel.DataAnnotations.Schema',
  ],
  [/\bIPAddress\b/, 'System.Net'],
  [/\bCancellationToken\b/, 'System.Threading'],
  [/\bTask</, 'System.Threading.Tasks'],
  [
    /\[(Index|PrimaryKey|Precision|Keyless)\b|\b(DbContext|DbContextOptions|DbSet|ModelBuilder|DeleteBehavior|EntityState|IEntityTypeConfiguration)\b/,
    'Microsoft.EntityFrameworkCore',
  ],
  [/\bEntityTypeBuilder\b/, 'Microsoft.EntityFrameworkCore.Metadata.Builders'],
  [
    /\bValueConverter\b/,
    'Microsoft.EntityFrameworkCore.Storage.ValueConversion',
  ],
  [/\bPropertySaveBehavior\b/, 'Microsoft.EntityFrameworkCore.Metadata'],
  [/\bGuidValueGenerator\b/, 'Microsoft.EntityFrameworkCore.ValueGeneration'],
  [/\bNpgsqlRange\b/, 'NpgsqlTypes'],
];

function usingsOf(text: string): string[] {
  const code: string = text.replace(/"(?:[^"\\]|\\.)*"/g, '""');
  return USINGS.filter(([pattern]: [RegExp, string]) => pattern.test(code))
    .map(([, name]: [RegExp, string]) => name)
    .sort((first: string, second: string) => {
      const a: number = first.startsWith('System') ? 0 : 1;
      const b: number = second.startsWith('System') ? 0 : 1;
      return a !== b ? a - b : first < second ? -1 : first > second ? 1 : 0;
    });
}

function fileText(plan: Plan, body: string[]): string {
  const usings: string[] = usingsOf(body.join('\n'));
  const lines: string[] = [];
  if (plan.header) {
    lines.push(
      '// <auto-generated>',
      '// Generated by ormbridge. Review the output before use.',
      '// </auto-generated>'
    );
  }
  lines.push('#nullable enable');
  lines.push(...usings.map((name: string) => `using ${name};`));
  lines.push('', `namespace ${plan.namespace};`, '', ...body, '');
  return lines.join('\n');
}

function indent(lines: readonly string[], levels: number = 1): string[] {
  const prefix: string = INDENT.repeat(levels);
  return lines.map((line: string) => (line === '' ? line : `${prefix}${line}`));
}

/** Joins blocks of lines with a blank line between them. */
function separated(blocks: readonly (readonly string[])[]): string[] {
  const lines: string[] = [];
  for (const block of blocks) {
    if (block.length === 0) {
      continue;
    }
    if (lines.length > 0) {
      lines.push('');
    }
    lines.push(...block);
  }
  return lines;
}

/** `head.a().b();` on one line when it fits, otherwise one call per line. */
function chain(head: string, calls: readonly string[]): string[] {
  const single: string = `${head}${calls.map((call: string) => `.${call}`).join('')};`;
  if (
    calls.length <= 1 ||
    single.length + 3 * INDENT.length <= MAX_LINE_WIDTH
  ) {
    return [single];
  }
  return [
    head,
    ...calls.map(
      (call: string, position: number) =>
        `${INDENT}.${call}${position === calls.length - 1 ? ';' : ''}`
    ),
  ];
}

function nameofList(names: readonly string[]): string {
  return names.map((name: string) => `nameof(${name})`).join(', ');
}

