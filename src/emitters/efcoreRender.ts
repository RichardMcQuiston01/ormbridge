function classAttributes(plan: Plan, model: ModelPlan): string[] {
  if (plan.style !== 'annotations') {
    return [];
  }
  const attributes: string[] = [];
  if (!model.isView && (model.needsTable || model.schema !== undefined)) {
    attributes.push(
      model.schema === undefined
        ? `[Table(${csString(model.tableName)})]`
        : `[Table(${csString(model.tableName)}, Schema = ${csString(model.schema)})]`
    );
  }
  if (model.keyProps.length > 1) {
    attributes.push(`[PrimaryKey(${nameofList(model.keyProps)})]`);
  }
  if (model.keyless) {
    attributes.push('[Keyless]');
  }
  for (const index of model.indexes) {
    if (index.method === undefined) {
      attributes.push(indexAttribute(index));
    }
  }
  return attributes;
}

function entityFile(
  plan: Plan,
  model: ModelPlan,
  fluentNavs: ReadonlySet<string>
): string {
  const members: string[][] = [
    ...model.columns.map((member: ColumnMember) =>
      columnBlock(plan, model, member)
    ),
    ...model.navs.map((nav: NavMember) =>
      navBlock(plan, nav, fluentNavs, model.className)
    ),
  ];
  const body: string[] = [
    ...classAttributes(plan, model),
    `public class ${verbatim(model.className)}`,
    '{',
    ...indent(separated(members)),
    '}',
  ];
  return fileText(plan, body);
}

function enumFile(plan: Plan, enumPlan: EnumPlan): string {
  const values: readonly IrEnumValue[] = enumPlan.enumeration.values;
  const members: string[] = values.map((value: IrEnumValue) => {
    const name: string = verbatim(
      enumPlan.members.get(value.name) ?? value.name
    );
    return enumPlan.numeric
      ? `${name} = ${Number(value.dbValue)},`
      : `${name},`;
  });
  const body: string[] = [
    `public enum ${enumPlan.typeName}`,
    '{',
    ...indent(members),
    '}',
  ];
  if (enumPlan.converter !== undefined) {
    const type: string = enumPlan.typeName;
    const toDatabase: string[] = values.map(
      (value: IrEnumValue) =>
        `${type}.${verbatim(enumPlan.members.get(value.name) ?? value.name)} => ${csString(value.dbValue)},`
    );
    const fromDatabase: string[] = values.map(
      (value: IrEnumValue) =>
        `${csString(value.dbValue)} => ${type}.${verbatim(enumPlan.members.get(value.name) ?? value.name)},`
    );
    body.push(
      '',
      '/// <summary>Stores the enum as the values the schema was written with.</summary>',
      `public class ${enumPlan.converter} : ValueConverter<${type}, string>`,
      '{',
      ...indent([
        `public ${enumPlan.converter}()`,
        `${INDENT}: base(value => ToDatabase(value), value => FromDatabase(value))`,
        '{',
        '}',
        '',
        `private static string ToDatabase(${type} value) => value switch`,
        '{',
        ...indent(toDatabase),
        `${INDENT}_ => throw new ArgumentOutOfRangeException(nameof(value), value, null),`,
        '};',
        '',
        `private static ${type} FromDatabase(string value) => value switch`,
        '{',
        ...indent(fromDatabase),
        `${INDENT}_ => throw new ArgumentOutOfRangeException(nameof(value), value, null),`,
        '};',
      ]),
      '}'
    );
  }
  return fileText(plan, body);
}

function configurationFile(plan: Plan, model: ModelPlan): string {
  const statements: string[][] = entityStatements(plan, model, 'builder');
  const body: string[] = [
    `public class ${model.className}Configuration : IEntityTypeConfiguration<${model.className}>`,
    '{',
    ...indent([
      `public void Configure(EntityTypeBuilder<${model.className}> builder)`,
      '{',
      ...indent(statements.flat()),
      '}',
    ]),
    '}',
  ];
  return fileText(plan, body);
}

function autoUpdateMembers(plan: Plan): string[] {
  const updated: ModelPlan[] = plan.models.filter(
    (model: ModelPlan) => model.autoUpdated.length > 0
  );
  if (updated.length === 0) {
    return [];
  }
  const entries: string[] = updated.flatMap((model: ModelPlan) => [
    `foreach (var entry in ChangeTracker.Entries<${model.className}>())`,
    '{',
    ...indent([
      'if (entry.State is EntityState.Added or EntityState.Modified)',
      '{',
      ...indent(
        model.autoUpdated.map(
          (property: string) =>
            `entry.Property(e => e.${property}).CurrentValue = now;`
        )
      ),
      '}',
    ]),
    '}',
  ]);
  return [
    '',
    'public override int SaveChanges(bool acceptAllChangesOnSuccess)',
    '{',
    `${INDENT}ApplyAutoUpdatedColumns();`,
    `${INDENT}return base.SaveChanges(acceptAllChangesOnSuccess);`,
    '}',
    '',
    'public override Task<int> SaveChangesAsync(',
    `${INDENT}bool acceptAllChangesOnSuccess,`,
    `${INDENT}CancellationToken cancellationToken = default)`,
    '{',
    `${INDENT}ApplyAutoUpdatedColumns();`,
    `${INDENT}return base.SaveChangesAsync(acceptAllChangesOnSuccess, cancellationToken);`,
    '}',
    '',
    '// The database does not refresh these columns on its own: the context sets them when a row is added or changed.',
    'private void ApplyAutoUpdatedColumns()',
    '{',
    `${INDENT}var now = DateTime.UtcNow;`,
    ...indent(entries),
    '}',
  ];
}

function contextFile(plan: Plan): string {
  const sets: string[] = plan.models.flatMap(
    (model: ModelPlan, position: number) => [
      ...(position === 0 ? [] : ['']),
      `public DbSet<${model.className}> ${verbatim(model.dbSet)} => Set<${model.className}>();`,
    ]
  );
  const configure: string[] = [];
  if (plan.style === 'fluent') {
    for (const model of plan.models) {
      configure.push(
        `modelBuilder.ApplyConfiguration(new ${model.className}Configuration());`
      );
    }
  } else {
    for (const model of plan.models) {
      const statements: string[][] = entityStatements(plan, model, 'entity');
      if (statements.length === 0) {
        continue;
      }
      if (configure.length > 0) {
        configure.push('');
      }
      configure.push(
        `modelBuilder.Entity<${model.className}>(entity =>`,
        '{',
        ...indent(statements.flat()),
        '});'
      );
    }
  }
  const body: string[] = [
    'public class AppDbContext : DbContext',
    '{',
    ...indent([
      'public AppDbContext(DbContextOptions<AppDbContext> options)',
      `${INDENT}: base(options)`,
      '{',
      '}',
      '',
      ...sets,
      '',
      'protected override void OnModelCreating(ModelBuilder modelBuilder)',
      '{',
      `${INDENT}base.OnModelCreating(modelBuilder);`,
      ...(configure.length === 0 ? [] : ['', ...indent(configure)]),
      '}',
      ...autoUpdateMembers(plan),
    ]),
    '}',
  ];
  return fileText(plan, body);
}

export function renderFiles(plan: Plan): Record<string, string> {
  const files: Record<string, string> = {};
  const fluentNavs: Set<string> = fluentNavigations(plan);
  for (const enumPlan of plan.enums) {
    files[`Models/${enumPlan.typeName}.cs`] = enumFile(plan, enumPlan);
  }
  for (const model of plan.models) {
    files[`Models/${model.className}.cs`] = entityFile(plan, model, fluentNavs);
    if (plan.style === 'fluent') {
      files[`Configurations/${model.className}Configuration.cs`] =
        configurationFile(plan, model);
    }
  }
  files['AppDbContext.cs'] = contextFile(plan);
  return files;
}
