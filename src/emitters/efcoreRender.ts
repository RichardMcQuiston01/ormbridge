function lambdaOf(properties: readonly string[]): string {
  const first: string | undefined = properties[0];
  return properties.length === 1 && first !== undefined
    ? `e => e.${first}`
    : `e => new { ${properties.map((name: string) => `e.${name}`).join(', ')} }`;
}

function relationLambda(properties: readonly string[]): string {
  const first: string | undefined = properties[0];
  return properties.length === 1 && first !== undefined
    ? `r => r.${first}`
    : `r => new { ${properties.map((name: string) => `r.${name}`).join(', ')} }`;
}

/** True when data annotations cannot say everything about a relationship. */
function needsFluent(link: Link): boolean {
  return (
    link.behavior !== undefined ||
    link.principalKeys !== undefined ||
    link.constraintName !== undefined ||
    link.composite !== undefined
  );
}

function linkStatement(link: Link, receiver: string): string[] {
  const calls: string[] = [`HasOne(e => e.${link.nav})`];
  calls.push(
    link.inverse === undefined
      ? link.oneToOne
        ? 'WithOne()'
        : 'WithMany()'
      : `${link.oneToOne ? 'WithOne' : 'WithMany'}(r => r.${link.inverse})`
  );
  const typeArgument: string = link.oneToOne ? `<${link.owner.className}>` : '';
  calls.push(`HasForeignKey${typeArgument}(${lambdaOf(link.foreignKeys)})`);
  if (link.principalKeys !== undefined) {
    calls.push(
      `HasPrincipalKey${link.oneToOne ? `<${link.target.className}>` : ''}(${relationLambda(link.principalKeys)})`
    );
  }
  if (link.constraintName !== undefined) {
    calls.push(`HasConstraintName(${csString(link.constraintName)})`);
  }
  if (link.behavior !== undefined) {
    calls.push(`OnDelete(DeleteBehavior.${link.behavior})`);
  }
  return chain(receiver, calls);
}

function manyToManyStatement(join: ManyToManyLink, receiver: string): string[] {
  const schemaArgument: string =
    join.owner.schema === undefined ? '' : `, ${csString(join.owner.schema)}`;
  return [
    receiver,
    `${INDENT}.HasMany(e => e.${join.nav})`,
    `${INDENT}.WithMany(${join.inverse === undefined ? '' : `r => r.${join.inverse}`})`,
    `${INDENT}.UsingEntity<Dictionary<string, object>>(`,
    `${INDENT}${INDENT}${csString(join.joinTable)},`,
    `${INDENT}${INDENT}right => right.HasOne<${join.target.className}>().WithMany().HasForeignKey(${csString(join.targetColumn)}),`,
    `${INDENT}${INDENT}left => left.HasOne<${join.owner.className}>().WithMany().HasForeignKey(${csString(join.ownerColumn)}),`,
    `${INDENT}${INDENT}join => join.ToTable(${csString(join.joinTable)}${schemaArgument}));`,
  ];
}

function indexStatement(index: ConfigIndex, receiver: string): string[] {
  const calls: string[] = [`HasIndex(${lambdaOf(index.properties)})`];
  if (index.unique) {
    calls.push('IsUnique()');
  }
  if (index.name !== undefined) {
    calls.push(`HasDatabaseName(${csString(index.name)})`);
  }
  if (index.descending.some((flag: boolean) => flag)) {
    calls.push(`IsDescending(${index.descending.join(', ')})`);
  }
  if (index.method !== undefined) {
    calls.push(`HasMethod(${csString(index.method)})`);
  }
  return chain(receiver, calls);
}

function indexAttribute(index: ConfigIndex): string {
  const parts: string[] = [nameofList(index.properties)];
  if (index.unique) {
    parts.push('IsUnique = true');
  }
  if (index.name !== undefined) {
    parts.push(`Name = ${csString(index.name)}`);
  }
  if (index.descending.some((flag: boolean) => flag)) {
    parts.push(`IsDescending = new[] { ${index.descending.join(', ')} }`);
  }
  return `[Index(${parts.join(', ')})]`;
}

function tableCall(model: ModelPlan): string {
  const schema: string =
    model.schema === undefined ? '' : `, ${csString(model.schema)}`;
  return `${model.isView ? 'ToView' : 'ToTable'}(${csString(model.tableName)}${schema})`;
}

/**
 * The configuration statements of one entity. In the `fluent` style that is all of the mapping; in the
 * `annotations` style only what data annotations cannot say.
 */
function entityStatements(
  plan: Plan,
  model: ModelPlan,
  receiver: string
): string[][] {
  const fluent: boolean = plan.style === 'fluent';
  const statements: string[][] = [];

  if (
    fluent &&
    (model.needsTable || model.schema !== undefined || model.isView)
  ) {
    statements.push(chain(receiver, [tableCall(model)]));
  } else if (!fluent && model.isView) {
    statements.push(chain(receiver, [tableCall(model)]));
  }
  if (model.keyProps.length > 0) {
    const key: string[] = [`HasKey(${lambdaOf(model.keyProps)})`];
    if (model.keyName !== undefined) {
      key.push(`HasName(${csString(model.keyName)})`);
    }
    if (fluent || model.keyName !== undefined) {
      statements.push(chain(receiver, key));
    }
  } else if (fluent && model.keyless) {
    statements.push(chain(receiver, ['HasNoKey()']));
  }
  for (const key of model.alternateKeys) {
    statements.push(chain(receiver, [`HasAlternateKey(${lambdaOf(key)})`]));
  }
  for (const member of model.columns) {
    const calls: string[] = propertyCalls(member, !fluent);
    if (calls.length > 0) {
      statements.push(
        chain(receiver, [`Property(e => e.${member.property})`, ...calls])
      );
    }
    if (member.spec.autoUpdated) {
      // EF Core ignores a value the application sets for a column the database is expected to generate, unless
      // it is allowed to save it; SaveChanges of the context sets these columns.
      for (const behavior of [
        'SetBeforeSaveBehavior',
        'SetAfterSaveBehavior',
      ]) {
        statements.push(
          chain(receiver, [
            `Property(e => e.${member.property})`,
            `Metadata.${behavior}(PropertySaveBehavior.Save)`,
          ])
        );
      }
    }
  }
  for (const index of model.indexes) {
    if (fluent || index.method !== undefined) {
      statements.push(indexStatement(index, receiver));
    }
  }
  for (const link of model.links) {
    if (fluent || needsFluent(link)) {
      statements.push(linkStatement(link, receiver));
    }
  }
  for (const join of model.manyToMany) {
    statements.push(manyToManyStatement(join, receiver));
  }
  return statements;
}

/** The navigations (`Class.Property`) that a fluent relationship already describes. */
function fluentNavigations(plan: Plan): Set<string> {
  const names: Set<string> = new Set<string>();
  for (const model of plan.models) {
    for (const link of model.links) {
      if (plan.style === 'fluent' || needsFluent(link)) {
        names.add(`${link.owner.className}.${link.nav}`);
        if (link.inverse !== undefined) {
          names.add(`${link.target.className}.${link.inverse}`);
        }
      }
    }
  }
  return names;
}

