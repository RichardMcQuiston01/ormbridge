function isConventionalKey(model: ModelPlan, member: ColumnMember): boolean {
  return (
    member.relationName === undefined &&
    (member.property === 'Id' || member.property === `${model.className}Id`)
  );
}

/** The data annotations of a column. */
function columnAttributes(model: ModelPlan, member: ColumnMember): string[] {
  const spec: ColumnSpec = member.spec;
  const attributes: string[] = [];
  if (
    member.isKey &&
    model.keyProps.length === 1 &&
    !isConventionalKey(model, member)
  ) {
    attributes.push('[Key]');
  }
  if (spec.generated !== undefined) {
    attributes.push(
      `[DatabaseGenerated(DatabaseGeneratedOption.${spec.generated === 'identity' ? 'Identity' : 'None'})]`
    );
  }
  const renamed: boolean = spec.columnName !== member.property;
  if (renamed || spec.columnType !== undefined) {
    const parts: string[] = [];
    if (renamed) {
      parts.push(csString(spec.columnName));
    }
    if (spec.columnType !== undefined) {
      parts.push(`TypeName = ${csString(spec.columnType)}`);
    }
    attributes.push(`[Column(${parts.join(', ')})]`);
  }
  if (spec.maxLength !== undefined && spec.conversion === undefined) {
    attributes.push(`[MaxLength(${spec.maxLength})]`);
  }
  if (spec.precision !== undefined) {
    attributes.push(
      `[Precision(${spec.precision.precision}, ${spec.precision.scale})]`
    );
  }
  return attributes;
}

/**
 * The fluent calls on `Property(...)` for a column. With `onlyBeyondAnnotations` the calls that data annotations
 * already express (column name and type, length, precision, generation of keys) are left out.
 */
function propertyCalls(
  member: ColumnMember,
  onlyBeyondAnnotations: boolean
): string[] {
  const spec: ColumnSpec = member.spec;
  const calls: string[] = [];
  if (!onlyBeyondAnnotations) {
    if (spec.columnName !== member.property) {
      calls.push(`HasColumnName(${csString(spec.columnName)})`);
    }
    if (spec.columnType !== undefined) {
      calls.push(`HasColumnType(${csString(spec.columnType)})`);
    }
  }
  if (
    spec.maxLength !== undefined &&
    (!onlyBeyondAnnotations || spec.conversion !== undefined)
  ) {
    calls.push(`HasMaxLength(${spec.maxLength})`);
  }
  if (!onlyBeyondAnnotations && spec.precision !== undefined) {
    calls.push(
      `HasPrecision(${spec.precision.precision}, ${spec.precision.scale})`
    );
  }
  if (spec.conversion?.kind === 'string') {
    calls.push('HasConversion<string>()');
  } else if (spec.conversion?.kind === 'converter') {
    calls.push(`HasConversion(new ${spec.conversion.className}())`);
  }
  if (spec.computed !== undefined) {
    calls.push(
      `HasComputedColumnSql(${csString(spec.computed.sql)}, ${spec.computed.stored})`
    );
  }
  if (spec.defaultValue !== undefined) {
    calls.push(`HasDefaultValue(${spec.defaultValue})`);
  }
  if (spec.defaultSql !== undefined) {
    calls.push(`HasDefaultValueSql(${csString(spec.defaultSql)})`);
  }
  if (spec.autoUpdated) {
    calls.push('ValueGeneratedOnAddOrUpdate()');
  } else if (spec.clientGuid) {
    // EF Core only generates the values of keys by itself; any other column needs the generator named.
    calls.push(
      'ValueGeneratedOnAdd()',
      'HasValueGenerator<GuidValueGenerator>()'
    );
  }
  if (!onlyBeyondAnnotations && spec.generated !== undefined) {
    calls.push(
      spec.generated === 'identity'
        ? 'ValueGeneratedOnAdd()'
        : 'ValueGeneratedNever()'
    );
  }
  return calls;
}

function columnBlock(
  plan: Plan,
  model: ModelPlan,
  member: ColumnMember
): string[] {
  const spec: ColumnSpec = member.spec;
  const type: string = `${spec.clrType}${spec.nullable ? '?' : ''}`;
  const initializer: string =
    spec.initializer === undefined ? '' : ` = ${spec.initializer};`;
  return [
    ...(plan.style === 'annotations' ? columnAttributes(model, member) : []),
    `public ${type} ${verbatim(member.property)} { get; set; }${initializer}`,
  ];
}

function navBlock(
  plan: Plan,
  nav: NavMember,
  fluentNavs: ReadonlySet<string>,
  className: string
): string[] {
  const lines: string[] = [];
  if (
    plan.style === 'annotations' &&
    !fluentNavs.has(`${className}.${nav.property}`)
  ) {
    if (nav.foreignKeys !== undefined) {
      lines.push(
        `[ForeignKey(${
          nav.foreignKeys.length === 1
            ? nameofList(nav.foreignKeys)
            : csString(nav.foreignKeys.join(','))
        })]`
      );
    }
    if (nav.inverseOf !== undefined) {
      lines.push(
        `[InverseProperty(nameof(${nav.inverseOf.className}.${nav.inverseOf.property}))]`
      );
    }
  }
  if (nav.collection) {
    lines.push(
      `public ICollection<${nav.typeName}> ${verbatim(nav.property)} { get; set; } = new List<${nav.typeName}>();`
    );
  } else if (nav.nullable) {
    lines.push(
      `public ${nav.typeName}? ${verbatim(nav.property)} { get; set; }`
    );
  } else {
    lines.push(
      `public ${nav.typeName} ${verbatim(nav.property)} { get; set; } = null!;`
    );
  }
  return lines;
}

