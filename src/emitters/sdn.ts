function pattern(edge: GraphEdge): string {
  return `(:${edge.source.label})-[:${edge.type}]->(:${edge.target.label})`;
}

function edgeWarning(edge: GraphEdge): string {
  const where: string = `${edge.source.model.name}.${edge.name}`;
  switch (edge.kind) {
    case 'manyToMany':
      return `${where}: the many-to-many relation to ${edge.target.model.name} became the relationship ${pattern(edge)}; no join node is created.`;
    case 'join':
      return `${edge.join?.model.name ?? where}: the join table became the relationship ${pattern(edge)} instead of a node class.`;
    default: {
      const keys: string = (
        edge.composite?.fields ?? [edge.relation?.name ?? edge.name]
      )
        .map((name: string) => edge.source.keys.get(name) ?? name)
        .join(', ');
      const many: boolean = keys.includes(',');
      return `${where}: the foreign key to ${edge.target.model.name} became the relationship ${pattern(edge)}; Spring Data Neo4j does not enforce the on delete action (${edge.onDelete ?? 'noAction'}), and ${keys} ${many ? 'were kept as plain properties' : 'was kept as a plain property'} that nothing ties to the relationship.`;
    }
  }
}

function relationshipAnnotation(
  plan: ClassPlan,
  edge: GraphEdge,
  direction: 'OUTGOING' | 'INCOMING'
): AnnotationNode {
  const relationship: string = plan.imports.use(
    `${SCHEMA_PACKAGE}.Relationship`
  );
  return annotation(relationship, [
    ['type', javaString(edge.type)],
    ['direction', `${relationship}.Direction.${direction}`],
  ]);
}

/** Writes the `@RelationshipProperties` class that holds the columns of a join table, towards `target`. */
function propertiesClass(
  edge: GraphEdge,
  join: GraphJoin,
  target: NodePlan,
  typeNames: Set<string>,
  schema: IrSchema,
  enums: Map<string, EnumPlan>,
  warnings: string[]
): ClassPlan {
  const className: string = uniqueName(
    `${classNameOf(labelOf(join.model.name))}${target.className}`,
    typeNames
  );
  const plan: ClassPlan = {
    className,
    imports: new Imports('jakarta'),
    used: new Set<string>(),
    fields: [],
    doc: [
      `Properties of the relationship ${oneLine(edge.type)} that the join table ${oneLine(join.model.name)} stored, towards ${oneLine(target.node.label)}.`,
    ],
    annotations: [],
  };
  plan.annotations.push(
    annotation(plan.imports.use(`${SCHEMA_PACKAGE}.RelationshipProperties`))
  );
  const idName: string = claim(plan, 'id', `${join.model.name}.id`, warnings);
  plan.fields.push({
    name: idName,
    type: 'Long',
    annotations: [
      annotation(plan.imports.use(`${SCHEMA_PACKAGE}.RelationshipId`)),
    ],
  });
  for (const property of join.extras) {
    const name: string = claim(
      plan,
      property.key,
      `${join.model.name}.${property.irName}`,
      warnings
    );
    const column: FieldPlan = columnField(
      plan,
      schema,
      enums,
      join.model,
      property,
      name,
      warnings
    );
    column.annotations.push(...propertyAnnotation(plan, property.key, name));
    plan.fields.push(column);
  }
  const targetName: string = claim(
    plan,
    target.className.charAt(0).toLowerCase() + target.className.slice(1),
    `${join.model.name}.${target.className}`,
    warnings
  );
  plan.fields.push({
    name: targetName,
    type: target.className,
    annotations: [annotation(plan.imports.use(`${SCHEMA_PACKAGE}.TargetNode`))],
  });
  return plan;
}

function addEdge(
  edge: GraphEdge,
  byLabel: Map<string, NodePlan>,
  typeNames: Set<string>,
  extraClasses: ClassPlan[],
  schema: IrSchema,
  enums: Map<string, EnumPlan>,
  warnings: string[]
): void {
  const source: NodePlan | undefined = byLabel.get(edge.source.label);
  const target: NodePlan | undefined = byLabel.get(edge.target.label);
  if (source === undefined || target === undefined) {
    return;
  }
  warnings.push(edgeWarning(edge));
  let toTarget: string = target.className;
  let toSource: string = source.className;
  if (edge.join !== undefined && edge.properties.length > 0) {
    const forward: ClassPlan = propertiesClass(
      edge,
      edge.join,
      target,
      typeNames,
      schema,
      enums,
      warnings
    );
    const backward: ClassPlan = propertiesClass(
      edge,
      edge.join,
      source,
      typeNames,
      schema,
      enums,
      warnings
    );
    extraClasses.push(forward, backward);
    toTarget = forward.className;
    toSource = backward.className;
  }
  const addField = (
    plan: NodePlan,
    raw: string,
    elementType: string,
    many: boolean,
    direction: 'OUTGOING' | 'INCOMING'
  ): void => {
    const name: string = claim(
      plan,
      raw,
      `${plan.node.model.name}.${raw}`,
      warnings
    );
    const list: string = plan.imports.use('java.util.List');
    plan.fields.push({
      name,
      type: many ? `${list}<${elementType}>` : elementType,
      annotations: [relationshipAnnotation(plan, edge, direction)],
      ...(many
        ? { initializer: `new ${plan.imports.use('java.util.ArrayList')}<>()` }
        : {}),
    });
  };
  addField(
    source,
    edge.name,
    toTarget,
    edge.outgoing === 'zeroOrMore' || edge.outgoing === 'oneOrMore',
    'OUTGOING'
  );
  addField(
    target,
    edge.reverseName ?? defaultReverseName(edge),
    toSource,
    edge.incoming === 'zeroOrMore' || edge.incoming === 'oneOrMore',
    'INCOMING'
  );
}

