/**
 * Spring Data Neo4j writer (Java, SDN 7 with Spring Boot 3).
 *
 * Writes one `@Node("Label")` class per node label, a Java `enum` per enum (with a
 * `Neo4jPersistentPropertyConverter` when the stored values differ from the constant names), and a
 * `@RelationshipProperties` class for every direction of a join table that has extra columns. Properties
 * whose graph key differs from the Java name carry `@Property`. Relationships are `@Relationship` fields with
 * the type and the direction, a single value or a `List`. Labels and relationship types are the ones of the
 * Cypher writer, so the three Neo4j outputs agree. Foreign key columns stay as plain properties.
 *
 * The identifier follows the source key: a generated integer is Neo4j's internal id (`@GeneratedValue`), a
 * generated UUID a `UUIDStringGenerator` string, any other single column an assigned `@Id`; a composite or
 * missing key becomes a generated internal id `graphId` and the key columns are plain properties.
 */

export { isValidJavaPackage } from './jpaNames.js';
export const DEFAULT_SDN_PACKAGE: string = DEFAULT_JPA_PACKAGE;

export interface SdnEmitOptions {
  /** Use camelCase graph property keys (the `normalize` naming mode); otherwise the column names are kept. */
  camelFields: boolean;
  /** Java package of the generated classes; defaults to `app.models`. */
  packageName?: string;
  /** Write the `// <auto-generated>` comment at the top of every file (default true). */
  header?: boolean;
}

const INDENT: string = '  ';
const SCHEMA_PACKAGE: string = 'org.springframework.data.neo4j.core.schema';
const CONVERT_PACKAGE: string = 'org.springframework.data.neo4j.core.convert';

interface FieldPlan {
  name: string;
  /** The Java type as written. */
  type: string;
  annotations: AnnotationNode[];
  initializer?: string;
}

interface ClassPlan {
  className: string;
  imports: Imports;
  used: Set<string>;
  fields: FieldPlan[];
  /** Javadoc lines. */
  doc: string[];
  annotations: AnnotationNode[];
}

interface NodePlan extends ClassPlan {
  node: GraphNode;
  /** Field name by property key. */
  attributes: Map<string, string>;
}

type IdKind = 'internal' | 'uuid' | 'assigned' | 'synthetic';

export function emitSdn(
  schema: IrSchema,
  options: SdnEmitOptions
): MultiFileEmitOutput {
  const warnings: string[] = schemaWarnings(schema);
  if (schema.models.length === 0) {
    return { files: {}, warnings };
  }
  const graph: Graph = buildGraph(
    schema,
    {
      camelFields: options.camelFields,
      omitWarnings: { defaults: true, autoIncrement: true },
    },
    warnings
  );
  const edges: GraphEdge[] = collectEdges(schema, graph, warnings);
  const packageName: string = options.packageName ?? DEFAULT_SDN_PACKAGE;
  const files: Record<string, string> = {};
  const layout = { packageName, header: options.header !== false };

  const typeNames: Set<string> = new Set<string>([
    ...RESERVED_TYPE_NAMES,
    ...RESERVED_SDN_TYPES,
  ]);
  const enums: Map<string, EnumPlan> = planEnums(
    schema,
    typeNames,
    (message: string): void => {
      warnings.push(message);
    }
  );
  for (const plan of enums.values()) {
    if (plan.storage === 'ordinal') {
      // Neo4j has no ordinal mapping; the number is stored through a converter like any other value.
      plan.storage = 'converter';
      plan.converterName = uniqueName(`${plan.typeName}Converter`, typeNames);
    }
  }

  const nodes: NodePlan[] = graph.nodes.map((node: GraphNode): NodePlan => {
    const raw: string = classNameOf(node.label);
    const className: string = uniqueName(
      RESERVED_TYPE_NAMES.has(raw) || RESERVED_SDN_TYPES.includes(raw)
        ? `${raw}Entity`
        : raw,
      typeNames
    );
    if (className !== node.label) {
      warnings.push(
        `${node.model.name}: "${node.label}" is a name the generated code uses or another type has, so the class was named "${className}"; @Node keeps the label ${node.label}.`
      );
    }
    return {
      node,
      className,
      imports: new Imports('jakarta'),
      used: new Set<string>(),
      fields: [],
      doc: [],
      annotations: [],
      attributes: new Map<string, string>(),
    };
  });
  const byLabel: Map<string, NodePlan> = new Map<string, NodePlan>(
    nodes.map((plan: NodePlan): [string, NodePlan] => [plan.node.label, plan])
  );

  for (const plan of nodes) {
    addProperties(plan, schema, enums, warnings);
  }
  const extraClasses: ClassPlan[] = [];
  for (const edge of edges) {
    addEdge(edge, byLabel, typeNames, extraClasses, schema, enums, warnings);
  }

  for (const plan of [...nodes, ...extraClasses]) {
    files[pathOf(packageName, plan.className)] = renderClass(plan, layout);
  }
  for (const plan of enums.values()) {
    const body: string[] = renderEnumBody(plan);
    files[pathOf(packageName, plan.typeName)] = renderFile(
      layout,
      new Imports('jakarta'),
      body
    );
    if (plan.storage === 'converter') {
      files[pathOf(packageName, plan.converterName)] = renderFile(
        layout,
        ...converterFile(plan)
      );
    }
  }
  return { files, warnings: [...new Set(warnings)] };
}

function pathOf(packageName: string, className: string): string {
  return `${packageName.replace(/\./g, '/')}/${className}.java`;
}

function schemaWarnings(schema: IrSchema): string[] {
  const warnings: string[] = [];
  for (const enumDefinition of schema.enums) {
    if (enumDefinition.schema !== undefined) {
      warnings.push(
        `enum ${enumDefinition.name}: the database schema "${enumDefinition.schema}" (@@schema) was ignored.`
      );
    }
  }
  for (const model of schema.models) {
    if (model.isView === true) {
      warnings.push(
        `${model.name}: this is a database view; it was written as a node class like any other model.`
      );
    }
    if (model.schema !== undefined) {
      warnings.push(
        `${model.name}: the database schema "${model.schema}" (@@schema) was ignored.`
      );
    }
  }
  return warnings;
}

