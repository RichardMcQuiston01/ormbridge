function fieldOf(model: IrModel, property: GraphProperty): IrField | undefined {
  return model.fields.find(
    (candidate: IrField) => candidate.name === property.irName
  );
}

function resolveKeys(node: GraphNode, names: string[]): string[] | undefined {
  const keys: string[] = [];
  for (const name of names) {
    const key: string | undefined = node.keys.get(name);
    if (key === undefined) {
      return undefined;
    }
    keys.push(key);
  }
  return keys;
}

/** How the identifier is written, from the primary key of the model. */
function planId(
  node: GraphNode,
  warnings: string[]
): { kind: IdKind; property?: GraphProperty } {
  const model: IrModel = node.model;
  const names: string[] = primaryKeyNamesOf(model);
  const keys: string[] | undefined = resolveKeys(node, names);
  const where: string = model.name;
  if (names.length === 0 || keys === undefined) {
    if (names.length > 0) {
      warnings.push(
        `${where}: the primary key (${names.join(', ')}) names a column that does not exist, so it was dropped.`
      );
    }
    warnings.push(
      `${where}: the model has no usable primary key; the node has a generated internal id (graphId) and no identifier property of the source.`
    );
    return { kind: 'synthetic' };
  }
  if (keys.length > 1) {
    warnings.push(
      `${where}: Spring Data Neo4j has no composite identifier, so the composite primary key (${keys.join(', ')}) was written as plain properties and the node has a generated internal id (graphId).`
    );
    return { kind: 'synthetic' };
  }
  const property: GraphProperty | undefined = node.properties.find(
    (candidate: GraphProperty) => candidate.key === keys[0]
  );
  const field: IrField | undefined =
    property === undefined ? undefined : fieldOf(model, property);
  if (property === undefined || field === undefined) {
    warnings.push(
      `${where}: the primary key is a relationship, which Spring Data Neo4j cannot use as an identifier; the node has a generated internal id (graphId).`
    );
    return { kind: 'synthetic' };
  }
  if (
    field.default?.kind === 'autoIncrement' &&
    (field.type === 'int' || field.type === 'bigInt')
  ) {
    warnings.push(
      `${where}.${field.name}: the generated integer key became Neo4j's internal node id (@Id @GeneratedValue Long); it is not stored as a property named ${property.key}, so data loaded with that property is not found by it, and the internal id can change when the database is rebuilt. Spring Data Neo4j 7 also logs a deprecation warning for internal Long ids; a UUID key (UUIDStringGenerator) avoids all of this.`
    );
    return { kind: 'internal', property };
  }
  if (field.type === 'uuid' && field.default?.kind === 'uuid') {
    return { kind: 'uuid', property };
  }
  return { kind: 'assigned', property };
}

function describeDefaultDrop(
  warnings: string[],
  label: string,
  what: string
): void {
  warnings.push(
    `${label}: ${what} has no Spring Data Neo4j equivalent and was dropped; set the value when you create the node.`
  );
}

/** A Java initializer for the defaults a field can carry, or undefined (with a warning) when there is none. */
function initializerOf(
  field: IrField,
  type: string,
  enumPlan: EnumPlan | undefined,
  label: string,
  warnings: string[]
): string | undefined {
  const value: IrField['default'] = field.default;
  if (value === undefined) {
    return undefined;
  }
  switch (value.kind) {
    case 'literal': {
      if (field.arrayDepth !== undefined) {
        describeDefaultDrop(warnings, label, 'the default of an array');
        return undefined;
      }
      const literal: string | number | boolean = value.value;
      if (type === 'String' && typeof literal !== 'boolean') {
        return javaString(String(literal));
      }
      if (type === 'Boolean' && typeof literal === 'boolean') {
        return literal ? 'true' : 'false';
      }
      if (type === 'Integer' && Number.isInteger(literal)) {
        return String(literal);
      }
      if (type === 'Long' && Number.isInteger(literal)) {
        return `${String(literal)}L`;
      }
      if (type === 'Double' && typeof literal === 'number') {
        return /^-?\d+$/.test(String(literal))
          ? `${String(literal)}.0`
          : String(literal);
      }
      describeDefaultDrop(
        warnings,
        label,
        `the default ${JSON.stringify(literal)}`
      );
      return undefined;
    }
    case 'enumValue': {
      const member: string | undefined = enumPlan?.members.get(value.value);
      if (enumPlan !== undefined && member !== undefined) {
        return `${enumPlan.typeName}.${member}`;
      }
      describeDefaultDrop(warnings, label, `the default "${value.value}"`);
      return undefined;
    }
    case 'autoIncrement':
      warnings.push(
        `${label}: auto-increment has no Spring Data Neo4j equivalent; supply the value yourself (a UUID key with UUIDStringGenerator needs none).`
      );
      return undefined;
    case 'now':
      describeDefaultDrop(warnings, label, 'the default of the current time');
      return undefined;
    case 'uuid':
      describeDefaultDrop(warnings, label, 'the default of a generated UUID');
      return undefined;
    case 'clientGenerated':
      describeDefaultDrop(warnings, label, `the ${value.generator}() default`);
      return undefined;
    case 'dbExpression':
      describeDefaultDrop(
        warnings,
        label,
        `the database default ${oneLine(value.expression)}`
      );
      return undefined;
  }
}

/** The Java type, converter annotation and initializer of a column property. */
function columnField(
  plan: ClassPlan,
  schema: IrSchema,
  enums: Map<string, EnumPlan>,
  model: IrModel,
  property: GraphProperty,
  name: string,
  warnings: string[],
  skipDefault: boolean = false
): FieldPlan {
  const field: IrField | undefined = fieldOf(model, property);
  const label: string = `${model.name}.${property.irName}`;
  const annotations: AnnotationNode[] = [];
  let type: string;
  let enumPlan: EnumPlan | undefined;
  if (field === undefined) {
    // A foreign key column: typed like the column it references.
    const relation = model.relations.find(
      (candidate) => candidate.name === property.irName
    );
    const referenced: IrField | undefined =
      relation === undefined ? undefined : referencedField(schema, relation);
    type = javaTypeOf(
      referenced === undefined
        ? {
            name: 'key',
            columnName: 'key',
            type: 'int',
            isPrimaryKey: false,
            isUnique: false,
            isNullable: false,
            isAutoUpdated: false,
          }
        : { ...referenced, arrayDepth: undefined, enumName: undefined },
      plan.imports
    );
  } else {
    enumPlan =
      field.enumName === undefined ? undefined : enums.get(field.enumName);
    if (enumPlan !== undefined) {
      const isArray: boolean = field.arrayDepth !== undefined;
      if (enumPlan.storage === 'converter' && isArray) {
        warnings.push(
          `${label}: Spring Data Neo4j converts a whole property, not the items of a list, so the array of enum ${enumPlan.typeName} values is a List<String> of the stored values.`
        );
        type = `${plan.imports.use('java.util.List')}<String>`;
        enumPlan = undefined;
      } else {
        type = isArray
          ? `${plan.imports.use('java.util.List')}<${enumPlan.typeName}>`
          : enumPlan.typeName;
        if (enumPlan.storage === 'converter' && !isArray) {
          annotations.push(
            annotation(plan.imports.use(`${CONVERT_PACKAGE}.ConvertWith`), [
              ['converter', `${enumPlan.converterName}.class`],
            ])
          );
        }
      }
    } else {
      type = javaTypeOf(field, plan.imports);
    }
  }
  const initializer: string | undefined =
    field === undefined || skipDefault
      ? undefined
      : initializerOf(field, type, enumPlan, label, warnings);
  return {
    name,
    type,
    annotations,
    ...(initializer === undefined ? {} : { initializer }),
  };
}

function propertyAnnotation(
  plan: ClassPlan,
  key: string,
  name: string
): AnnotationNode[] {
  return key === name
    ? []
    : [
        annotation(plan.imports.use(`${SCHEMA_PACKAGE}.Property`), [
          [undefined, javaString(key)],
        ]),
      ];
}

function claim(
  plan: ClassPlan,
  raw: string,
  where: string,
  warnings: string[]
): string {
  const wanted: string = attributeNameOf(raw);
  const name: string = uniqueName(wanted, plan.used);
  if (name !== wanted) {
    warnings.push(
      `${where}: "${wanted}" is taken in ${plan.className}, so the field was named "${name}".`
    );
  }
  return name;
}

function addProperties(
  plan: NodePlan,
  schema: IrSchema,
  enums: Map<string, EnumPlan>,
  warnings: string[]
): void {
  const node: GraphNode = plan.node;
  const model: IrModel = node.model;
  const id = planId(node, warnings);
  plan.annotations.push(
    annotation(plan.imports.use(`${SCHEMA_PACKAGE}.Node`), [
      [undefined, javaString(node.label)],
    ])
  );
  const doc: string[] = [
    `Model ${oneLine(model.name)} (table ${oneLine(model.tableName)}), the node label ${oneLine(node.label)}.`,
  ];
  const required: string[] = [];
  const constraints: string[] = [];
  const keysOfIndexes: string[] = [];
  for (const field of model.fields) {
    const key: string | undefined = node.keys.get(field.name);
    if (field.isUnique && key !== undefined) {
      constraints.push(key);
    }
  }
  for (const relation of model.relations) {
    const key: string | undefined = node.keys.get(relation.name);
    if (relation.kind === 'oneToOne' && key !== undefined) {
      constraints.push(key);
    }
  }
  const keyNames: string[] = primaryKeyNamesOf(model);
  if (keyNames.length > 0 && id.kind !== 'internal') {
    const keys: string[] | undefined = resolveKeys(node, keyNames);
    if (keys !== undefined) {
      constraints.unshift(keys.join(' + '));
    }
  }
  for (const index of model.indexes) {
    const keys: string[] | undefined = resolveKeys(node, index.fields);
    if (keys === undefined || keys.length === 0) {
      warnings.push(
        `${model.name} index (${index.fields.join(', ')}): it names a column that does not exist and was dropped.`
      );
      continue;
    }
    if (index.method !== undefined && index.method.toLowerCase() !== 'btree') {
      warnings.push(
        `${model.name} index (${index.fields.join(', ')}): Neo4j has no ${index.method} index method; the index was dropped.`
      );
      continue;
    }
    if (index.isUnique && index.kind !== 'fulltext') {
      constraints.push(keys.join(' + '));
    } else {
      keysOfIndexes.push(keys.join(' + '));
    }
  }

  if (id.kind === 'synthetic') {
    const name: string = claim(
      plan,
      'graphId',
      `${model.name}.graphId`,
      warnings
    );
    plan.fields.push({
      name,
      type: 'Long',
      annotations: [
        annotation(plan.imports.use(`${SCHEMA_PACKAGE}.Id`)),
        annotation(plan.imports.use(`${SCHEMA_PACKAGE}.GeneratedValue`)),
      ],
    });
  }
  for (const property of node.properties) {
    const name: string = claim(
      plan,
      property.key,
      `${model.name}.${property.irName}`,
      warnings
    );
    plan.attributes.set(property.key, name);
    const column: FieldPlan = columnField(
      plan,
      schema,
      enums,
      model,
      property,
      name,
      warnings,
      id.property === property
    );
    const isId: boolean = id.property === property;
    if (isId) {
      column.annotations.unshift(
        annotation(plan.imports.use(`${SCHEMA_PACKAGE}.Id`))
      );
      if (id.kind === 'internal') {
        column.type = 'Long';
        delete column.initializer;
        column.annotations.push(
          annotation(plan.imports.use(`${SCHEMA_PACKAGE}.GeneratedValue`))
        );
      } else if (id.kind === 'uuid') {
        column.type = 'String';
        column.annotations.push(
          annotation(plan.imports.use(`${SCHEMA_PACKAGE}.GeneratedValue`), [
            [
              undefined,
              `${plan.imports.use('org.springframework.data.neo4j.core.support.UUIDStringGenerator')}.class`,
            ],
          ])
        );
      }
    }
    if (isId && id.kind === 'internal') {
      // The key is Neo4j's internal id: it is not a stored property, so there is no @Property.
    } else {
      column.annotations.push(...propertyAnnotation(plan, property.key, name));
    }
    if (property.required && !isId) {
      required.push(property.key);
    }
    plan.fields.push(column);
  }
  if (required.length > 0) {
    doc.push(`Required properties: ${required.join(', ')}.`);
  }
  if (constraints.length > 0 || keysOfIndexes.length > 0) {
    const parts: string[] = [];
    if (constraints.length > 0) {
      parts.push(`unique (${[...new Set(constraints)].join('; ')})`);
    }
    if (keysOfIndexes.length > 0) {
      parts.push(`indexed (${[...new Set(keysOfIndexes)].join('; ')})`);
    }
    doc.push(
      `Spring Data Neo4j creates no constraints or indexes; create them with the Cypher writer (--to neo4j). Declared in the source: ${parts.join(' and ')}.`
    );
    warnings.push(
      `${model.name}: Spring Data Neo4j creates no constraints or indexes, so the constraints and indexes of the source (${parts.join(' and ')}) were not written; create them with --to neo4j.`
    );
  }
  plan.doc = doc;
}

