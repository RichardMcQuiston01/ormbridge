function converterFile(plan: EnumPlan): [Imports, string[]] {
  const imports: Imports = new Imports('jakarta');
  const base: string = imports.use(
    `${CONVERT_PACKAGE}.Neo4jPersistentPropertyConverter`
  );
  const value: string = imports.use('org.neo4j.driver.Value');
  const values: string = imports.use('org.neo4j.driver.Values');
  const type: string = plan.typeName;
  const read: string = plan.numeric ? 'source.asInt()' : 'source.asString()';
  const compare: string = plan.numeric
    ? 'item.getValue() == stored'
    : 'item.getValue().equals(stored)';
  const stored: string = plan.numeric ? 'int' : 'String';
  const lines: string[] = [
    `public class ${plan.converterName} implements ${base}<${type}> {`,
    '  @Override',
    `  public ${value} write(${type} source) {`,
    `    return source == null ? ${values}.NULL : ${values}.value(source.getValue());`,
    '  }',
    '',
    '  @Override',
    `  public ${type} read(${value} source) {`,
    '    if (source == null || source.isNull()) {',
    '      return null;',
    '    }',
    `    ${stored} stored = ${read};`,
    `    for (${type} item : ${type}.values()) {`,
    `      if (${compare}) {`,
    '        return item;',
    '      }',
    '    }',
    `    throw new IllegalArgumentException("Unknown ${type} value: " + stored);`,
    '  }',
    '}',
  ];
  return [imports, lines];
}

function accessors(field: FieldPlan): string[] {
  return [
    `${INDENT}public ${field.type} get${capitalize(field.name)}() {`,
    `${INDENT}${INDENT}return ${field.name};`,
    `${INDENT}}`,
    '',
    `${INDENT}public void set${capitalize(field.name)}(${field.type} ${field.name}) {`,
    `${INDENT}${INDENT}this.${field.name} = ${field.name};`,
    `${INDENT}}`,
  ];
}

function renderClass(
  plan: ClassPlan,
  layout: { packageName: string; header: boolean }
): string {
  const body: string[] = [];
  if (plan.doc.length > 0) {
    body.push('/**');
    for (const line of plan.doc) {
      body.push(` * ${line.replace(/\*\//g, '* /')}`);
    }
    body.push(' */');
  }
  for (const node of plan.annotations) {
    body.push(...formatAnnotation(node, 0));
  }
  body.push(`public class ${plan.className} {`);
  plan.fields.forEach((field: FieldPlan, position: number): void => {
    if (position > 0) {
      body.push('');
    }
    for (const node of field.annotations) {
      body.push(...formatAnnotation(node, INDENT.length));
    }
    body.push(
      `${INDENT}private ${field.type} ${field.name}${field.initializer === undefined ? '' : ` = ${field.initializer}`};`
    );
  });
  for (const field of plan.fields) {
    body.push('', ...accessors(field));
  }
  body.push('}');
  return renderFile(layout, plan.imports, body);
}
