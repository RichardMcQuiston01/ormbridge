/**
 * Writes Hibernate / JPA entities (Java): one `@Entity` class per model, a Java `enum` per enum (with an
 * `AttributeConverter` when the stored values differ from the constant names) and an `@IdClass` class for every
 * composite primary key. Two styles choose the persistence API: `jakarta` (the default; `jakarta.persistence`,
 * Hibernate 6, Spring Boot 3) and `javax` (`javax.persistence`, Hibernate 5, Spring Boot 2).
 *
 * Every table, column, key, index and foreign key is written explicitly (`@Table`, `@Column`, `@JoinColumn`), so
 * the output creates the schema of the IR whatever naming strategy the application uses, and the JPA reader reads
 * it back.
 */

export { DEFAULT_JPA_PACKAGE, isValidJavaPackage } from './jpaNames.js';
export type { JpaKeyMode, JpaStyle } from './jpaTypes.js';

export const JPA_STYLES: readonly JpaStyle[] = ['jakarta', 'javax'];

/** The ways to write a composite primary key: an `@IdClass` class (default) or an `@Embeddable` with `@EmbeddedId`. */
export const JPA_KEY_MODES: readonly JpaKeyMode[] = ['idclass', 'embedded'];

/** True when a value is one of the JPA key modes (`--jpa-key`). */
export function isJpaKeyMode(value: string): value is JpaKeyMode {
  return (JPA_KEY_MODES as readonly string[]).includes(value);
}

/** True when a value is one of the JPA `--style` values. */
export function isJpaStyle(value: string): value is JpaStyle {
  return (JPA_STYLES as readonly string[]).includes(value);
}

export interface JpaEmitOptions {
  /** Database provider; picks the column types and the SQL of defaults. */
  provider: PrismaProvider;
  /**
   * "preserve" keeps the database names of the source. "normalize" applies the fresh-schema style of the other
   * emitters (singular snake_case tables, UUID keys, `created_at` / `updated_at`).
   */
  naming: NamingMode;
  /** The persistence API; defaults to `jakarta`. */
  style?: JpaStyle;
  /**
   * How a composite primary key is written: `idclass` (default; `@IdClass` and `@Id` on each key attribute) or
   * `embedded` (an `@Embeddable` key class and one `@EmbeddedId`; a relationship in the key gets `@MapsId`).
   * A single-column key is always an `@Id`.
   */
  keyMode?: JpaKeyMode;
  /**
   * Write Lombok annotations (`@Getter`, `@Setter`, `@NoArgsConstructor`; `@EqualsAndHashCode` on key classes)
   * in place of hand-written accessors (default false).
   */
  lombok?: boolean;
  /** Java package of the generated classes; defaults to `app.models`. */
  packageName?: string;
  /** Write the `// <auto-generated>` comment at the top of every file (default true). */
  header?: boolean;
}

// ---------------------------------------------------------------------------
// Entry point
// ---------------------------------------------------------------------------

export function emitJpa(
  schema: IrSchema,
  options: JpaEmitOptions
): MultiFileEmitOutput {
  const prepared: IrSchema =
    options.naming === 'normalize' ? normalizeSchema(schema) : schema;
  const warnings: string[] = prismaOnlyWarnings(prepared, true).filter(
    isUnhandledWarning
  );
  if (options.provider === 'mongodb') {
    warnings.push(
      'Provider "mongodb": JPA is relational (Hibernate OGM and Spring Data MongoDB are separate projects); PostgreSQL column types were written.'
    );
  }
  if (prepared.models.length === 0) {
    return { files: {}, warnings };
  }
  const style: JpaStyle = options.style ?? 'jakarta';
  if (isCockroach(options.provider)) {
    warnings.push(
      `${COCKROACH_PREFIX} the entities use the PostgreSQL column types; set hibernate.dialect to ${style === 'jakarta' ? 'org.hibernate.dialect.CockroachDialect (Hibernate 6)' : 'org.hibernate.dialect.CockroachDB201Dialect (Hibernate 5)'} and keep the PostgreSQL JDBC driver. hstore and range types (which CockroachDB lacks) are written as JSON or large text.`
    );
  }
  const layout: FileLayout = {
    packageName: options.packageName ?? DEFAULT_JPA_PACKAGE,
    header: options.header !== false,
    lombok: options.lombok === true,
  };
  const files: Record<string, string> = {};
  planAndRender(prepared, options, style, layout, files, warnings);
  return { files, warnings: [...new Set(warnings)] };
}

/** Drops the Prisma-only notes for things this emitter writes (schemas, views, defaults, composite keys, indexes). */
function isUnhandledWarning(warning: string): boolean {
  if (warning.includes('the database default expression')) {
    return false;
  }
  if (warning.includes('(Prisma Unsupported)')) {
    return false;
  }
  if (warning.includes('is generated by Prisma Client and was dropped')) {
    return false;
  }
  if (warning.includes('has no equivalent here; the relation was dropped')) {
    return false;
  }
  if (warning.includes('the index type, clustering, sort order')) {
    return false;
  }
  if (warning.includes('full-text indexes are not supported here')) {
    return false;
  }
  if (warning.includes('is not supported by this format and was ignored')) {
    return false;
  }
  return !(
    warning.includes('(@@schema) was ignored') && !warning.startsWith('enum ')
  );
}

