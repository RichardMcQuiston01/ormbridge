function pathOf(packageName: string, className: string): string {
  return `${packageName.replace(/\./g, '/')}/${className}.java`;
}

function planAndRender(
  schema: IrSchema,
  options: JpaEmitOptions,
  style: JpaStyle,
  layout: FileLayout,
  files: Record<string, string>,
  warnings: string[]
): void {
  const warn = (message: string): void => {
    warnings.push(message);
  };
  const sequentialKeys: string[] = [];
  const typeNames: Set<string> = new Set<string>(RESERVED_TYPE_NAMES);
  const enums: Map<string, EnumPlan> = planEnums(schema, typeNames, warn);
  const plans: Map<string, ModelPlan> = new Map<string, ModelPlan>();
  for (const model of schema.models) {
    const raw: string = classNameOf(model.name);
    const className: string = uniqueName(
      RESERVED_TYPE_NAMES.has(raw) ? `${raw}Entity` : raw,
      typeNames
    );
    if (className !== raw) {
      warn(
        `${model.name}: "${raw}" is a name the generated code uses or another type has, so the class was named "${className}".`
      );
    }
    plans.set(model.name, {
      model,
      className,
      fieldNames: new Map<string, string>(),
      relationNames: new Map<string, string>(),
      used: new Set<string>(),
      attributes: [],
      classAnnotations: [],
      imports: new Imports(style),
      dynamicInsert: false,
    });
  }
  const keys: Map<string, KeyInfo> = new Map<string, KeyInfo>();
  for (const model of schema.models) {
    keys.set(model.name, keyOf(model, warn));
  }

  // Columns ------------------------------------------------------------------------------------
  const context: ColumnContext = {
    style,
    provider: options.provider,
    enums,
    warn,
    ...(isCockroach(options.provider) ? { sequentialKeys } : {}),
  };
  const built: Map<IrField, BuiltColumn> = new Map<IrField, BuiltColumn>();
  for (const model of schema.models) {
    const plan: ModelPlan = planFor(plans, model);
    const info: KeyInfo = keys.get(model.name) ?? {
      parts: [],
      synthesized: false,
    };
    for (const field of model.fields) {
      const wanted: string = attributeNameOf(field.name);
      const name: string = uniqueName(wanted, plan.used);
      if (name !== wanted) {
        warn(
          `${model.name}.${field.name}: "${wanted}" is taken in ${plan.className}, so the attribute was named "${name}".`
        );
      }
      plan.fieldNames.set(field.name, name);
      const isKey: boolean = info.parts.some(
        (part: KeyPart) => part.kind === 'field' && part.field === field
      );
      const column: BuiltColumn = buildColumn(
        context,
        `${model.name}.${field.name}`,
        field,
        name,
        { isKey, singleKey: info.parts.length === 1 }
      );
      built.set(field, column);
      plan.attributes.push(column.attribute);
      plan.dynamicInsert ||= column.dynamicInsert;
    }
  }

  if (sequentialKeys.length > 0) {
    warn(
      cockroachSequentialWarning(
        sequentialKeys,
        'GenerationType.IDENTITY relies on a SERIAL-style column, which is unique_rowid() on CockroachDB (64-bit and not consecutive), so the key is a Long'
      )
    );
  }

  // Relations ----------------------------------------------------------------------------------
  const keyTypes: Map<string, { type: string; imports: Imports }> = new Map();
  const typeOfKey = (
    model: IrModel,
    depth: number
  ): { type: string; imports: Imports } | undefined => {
    const info: KeyInfo | undefined = keys.get(model.name);
    const part: KeyPart | undefined =
      info?.parts.length === 1 ? info.parts[0] : undefined;
    if (part === undefined || depth > 6) {
      return undefined;
    }
    if (part.kind === 'field') {
      const column: BuiltColumn | undefined = built.get(part.field);
      return column === undefined
        ? undefined
        : { type: column.boxedType, imports: column.attribute.imports };
    }
    const target: IrModel | undefined = schema.models.find(
      (candidate: IrModel) => candidate.name === part.relation.targetModel
    );
    return target === undefined ? undefined : typeOfKey(target, depth + 1);
  };
  for (const model of schema.models) {
    const found = typeOfKey(model, 0);
    if (found !== undefined) {
      keyTypes.set(model.name, found);
    }
  }
  const keyMode: JpaKeyMode = options.keyMode ?? 'idclass';
  const relationContext: RelationContext = {
    style,
    keyMode,
    schema,
    plans,
    keys,
    keyTypes,
    inverses: [] as InverseLink[],
    warn,
  };
  const keyRelations: Map<string, Map<IrRelation, KeyRelation>> = new Map();
  for (const model of schema.models) {
    keyRelations.set(
      model.name,
      addOwningRelations(relationContext, planFor(plans, model))
    );
  }
  addInverseRelations(relationContext);

  // Classes -----------------------------------------------------------------------------------
  for (const model of schema.models) {
    const plan: ModelPlan = planFor(plans, model);
    const info: KeyInfo = keys.get(model.name) ?? {
      parts: [],
      synthesized: false,
    };
    const imports: Imports = plan.imports;
    plan.classAnnotations.push(
      annotation(imports.persistence('Entity')),
      tableAnnotation({ model, imports, warn })
    );
    if (info.parts.length > 1) {
      const embedded: boolean = keyMode === 'embedded';
      const parts: IdPart[] = [];
      const moved: Attribute[] = [];
      for (const part of info.parts) {
        if (part.kind === 'field') {
          const column: BuiltColumn | undefined = built.get(part.field);
          const name: string | undefined = plan.fieldNames.get(part.field.name);
          if (column !== undefined && name !== undefined) {
            parts.push({
              name,
              type: column.boxedType,
              imports: column.attribute.imports,
              ...(embedded
                ? {
                    // The key class holds the column; the @Id of the entity attribute is not needed there.
                    annotations: column.attribute.annotations.filter(
                      (node: AnnotationNode) => node.name !== 'Id'
                    ),
                  }
                : {}),
            });
            moved.push(column.attribute);
          }
        } else {
          const found: KeyRelation | undefined = keyRelations
            .get(model.name)
            ?.get(part.relation);
          if (found === undefined) {
            warn(
              `${model.name}.${part.relation.name}: the relation is part of the composite primary key but could not be written, so it is missing from the key.`
            );
          } else {
            // The imports of the target's key are shared, so the key class gets a set of its own.
            const partImports: Imports = new Imports(style);
            partImports.merge(found.imports);
            parts.push({
              name: found.attribute,
              type: found.type,
              imports: partImports,
              ...(embedded
                ? {
                    annotations: [
                      annotation(partImports.persistence('Column'), [
                        ['name', javaString(found.column)],
                      ]),
                    ],
                  }
                : {}),
            });
          }
        }
      }
      const idName: string = uniqueName(`${plan.className}Id`, typeNames);
      plan.idClass = { name: idName, parts };
      const idImports: Imports = plan.imports;
      if (embedded) {
        // The key attributes move into the @Embeddable class; one @EmbeddedId attribute takes their place.
        const firstAt: number = Math.max(
          0,
          Math.min(
            ...moved.map((attribute: Attribute) =>
              plan.attributes.indexOf(attribute)
            )
          )
        );
        plan.attributes = plan.attributes.filter(
          (attribute: Attribute) => !moved.includes(attribute)
        );
        const idAttribute: string = uniqueName('id', plan.used);
        plan.attributes.splice(moved.length === 0 ? 0 : firstAt, 0, {
          name: idAttribute,
          type: idName,
          annotations: [annotation(idImports.persistence('EmbeddedId'))],
          imports: new Imports(style),
        });
      } else {
        plan.classAnnotations.push(
          annotation(idImports.persistence('IdClass'), [
            [undefined, `${idName}.class`],
          ])
        );
      }
      const rendered = renderKeyClass(idName, parts, style, {
        embeddable: embedded,
        lombok: layout.lombok === true,
      });
      files[pathOf(layout.packageName, idName)] = renderFile(
        layout,
        rendered.imports,
        rendered.lines
      );
    }
    if (info.parts.length === 1 && info.parts[0]?.kind === 'relation') {
      plan.serializable = true;
      // The entity is Serializable only because Hibernate 5 asks for it; its relationship attributes are not.
      plan.classAnnotations.push(
        annotation('SuppressWarnings', [[undefined, '"serial"']])
      );
    }
    if (plan.dynamicInsert) {
      plan.classAnnotations.push(
        annotation(imports.hibernate('DynamicInsert'))
      );
    }
    if (model.isView === true) {
      plan.classAnnotations.push(annotation(imports.hibernate('Immutable')));
      warn(
        `${model.name}: the table "${model.tableName}" is a database view; the class is @Immutable, but Hibernate would create a table of that name if it manages the schema (turn schema generation off for it).`
      );
    }
    files[pathOf(layout.packageName, plan.className)] = renderEntity(
      plan,
      layout
    );
  }

  // Enums and converters --------------------------------------------------------------------------
  for (const plan of enums.values()) {
    const body: string[] = renderEnumBody(plan);
    files[pathOf(layout.packageName, plan.typeName)] = renderFile(
      layout,
      new Imports(style),
      body
    );
    if (plan.storage === 'converter') {
      const converter = renderConverterBody(plan, style);
      files[pathOf(layout.packageName, plan.converterName)] = renderFile(
        layout,
        converter.imports,
        converter.lines
      );
    }
  }
}

function planFor(
  plans: ReadonlyMap<string, ModelPlan>,
  model: IrModel
): ModelPlan {
  const plan: ModelPlan | undefined = plans.get(model.name);
  if (plan === undefined) {
    throw new Error(`No plan exists for the model "${model.name}".`);
  }
  return plan;
}
