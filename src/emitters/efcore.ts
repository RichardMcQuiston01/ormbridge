// Entry point
// ---------------------------------------------------------------------------

export function emitEfcore(
  schema: IrSchema,
  options: EfcoreEmitOptions
): MultiFileEmitOutput {
  const prepared: IrSchema =
    options.naming === 'normalize' ? normalizeSchema(schema) : schema;
  const warnings: string[] = prismaOnlyWarnings(prepared, true).filter(
    isUnhandledWarning
  );
  if (options.provider === 'mongodb') {
    warnings.push(
      'Provider "mongodb": EF Core is relational (use the MongoDB EF Core provider by hand); PostgreSQL column types were written.'
    );
  }
  if (prepared.models.length === 0) {
    return { files: {}, warnings };
  }
  const plan: Plan = planSchema(prepared, options, warnings);
  return { files: renderFiles(plan), warnings: dedupe(warnings) };
}

function dedupe(values: readonly string[]): string[] {
  return [...new Set(values)];
}

/** Drops the Prisma-only notes for things this emitter writes (schemas, views, defaults, composite keys, index details). */
function isUnhandledWarning(warning: string): boolean {
  if (warning.includes('the database default expression')) {
    return false;
  }
  if (warning.includes('(Prisma Unsupported)')) {
    return false;
  }
  if (warning.includes('is generated by Prisma Client and was dropped')) {
    return false;
  }
  if (warning.includes('has no equivalent here; the relation was dropped')) {
    return false;
  }
  if (warning.includes('the index type, clustering, sort order')) {
    return false;
  }
  return !(
    warning.includes('(@@schema) was ignored') && !warning.startsWith('enum ')
  );
}

