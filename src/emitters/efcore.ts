/**
 * Writes Entity Framework Core 8 models (C#, `#nullable enable`): one entity class per model, a C# enum per
 * enum, and an `AppDbContext` with a `DbSet<T>` for every entity. Two styles:
 *
 * - `annotations` (the default) puts what data annotations can say on the classes (`[Table]`, `[Column]`,
 *   `[Key]`, `[MaxLength]`, `[Precision]`, `[Index]`, `[ForeignKey]`, `[InverseProperty]`, `[DatabaseGenerated]`)
 *   and writes the rest (defaults, enum conversions, delete behaviors, many-to-many join tables) with the fluent
 *   API in `OnModelCreating`.
 * - `fluent` writes plain classes and one `IEntityTypeConfiguration<T>` per entity that holds all of the mapping.
 *
 * Every table, column, key, index and foreign key is written explicitly, so the output creates the schema of the
 * IR and the EF Core reader reads it back.
 */

export {
  DEFAULT_EFCORE_NAMESPACE,
  isValidCsharpNamespace,
} from './efcoreNames.js';
export type { EfcoreStyle } from './efcoreTypes.js';

export const EFCORE_STYLES: readonly EfcoreStyle[] = ['annotations', 'fluent'];

/** True when a value is one of the EF Core `--style` values. */
export function isEfcoreStyle(value: string): value is EfcoreStyle {
  return (EFCORE_STYLES as readonly string[]).includes(value);
}

export interface EfcoreEmitOptions {
  /** Database provider; picks the column types and the SQL of defaults. */
  provider: PrismaProvider;
  /**
   * "preserve" keeps the database names of the source (every table and column that differs from what EF Core
   * would pick is written with `[Table]` / `[Column]` or `ToTable` / `HasColumnName`). "normalize" applies the
   * fresh-schema style of the other emitters (singular snake_case tables, UUID keys, `created_at` / `updated_at`).
   */
  naming: NamingMode;
  /** Output layout; defaults to `annotations`. */
  style?: EfcoreStyle;
  /** Namespace of the generated classes; defaults to `App.Models`. */
  namespace?: string;
  /** Write the `// <auto-generated>` comment at the top of every file (default true). */
  header?: boolean;
}

