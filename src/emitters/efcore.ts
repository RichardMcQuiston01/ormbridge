const DELETE_BEHAVIORS: Readonly<Record<IrOnDelete, string>> = {
  cascade: 'Cascade',
  setNull: 'SetNull',
  restrict: 'Restrict',
  noAction: 'NoAction',
  setDefault: 'NoAction',
};

function planSchema(
  schema: IrSchema,
  options: EfcoreEmitOptions,
  warnings: string[]
): Plan {
  const style: EfcoreStyle = options.style ?? 'annotations';
  const typeNames: Set<string> = new Set<string>(RESERVED_TYPE_NAMES);
  typeNames.add('AppDbContext');
  const warn = (message: string): void => {
    warnings.push(message);
  };

  const enums: Map<string, EnumPlan> = planEnums(schema, typeNames, warn);
  const plans: Map<string, ModelPlan> = new Map<string, ModelPlan>();
  const dbSets: Set<string> = new Set<string>(DBCONTEXT_MEMBER_NAMES);

  for (const model of schema.models) {
    const rawClass: string = /^[A-Z][A-Za-z0-9]*$/.test(model.name)
      ? model.name
      : (pascalIdentifier(model.name) ?? repairedIdentifier(model.name));
    const reserved: boolean = typeNames.has(rawClass);
    const className: string = uniqueName(
      reserved ? `${rawClass}Entity` : rawClass,
      typeNames
    );
    if (className !== rawClass) {
      warn(
        `${model.name}: "${rawClass}" is a name the generated code uses or another type has, so the class was named "${className}".`
      );
    }
    const conventional: boolean =
      /^[A-Z][A-Za-z0-9]*$/.test(model.tableName) &&
      model.tableName !== className &&
      !dbSets.has(model.tableName);
    const dbSet: string = uniqueName(
      conventional ? model.tableName : pluralize(className),
      dbSets
    );
    plans.set(model.name, {
      model,
      className,
      dbSet,
      tableName: model.tableName,
      needsTable: model.tableName !== dbSet,
      schema: model.schema,
      used: new Set<string>([className, ...RESERVED_MEMBER_NAMES]),
      fieldProps: new Map<string, string>(),
      relationFks: new Map<string, string>(),
      relationNavs: new Map<string, string>(),
      columns: [],
      navs: [],
      keyProps: [],
      keyless: false,
      isView: model.isView === true,
      keyName: model.primaryKeyName,
      alternateKeys: [],
      indexes: [],
      links: [],
      manyToMany: [],
      autoUpdated: [],
    });
  }

  // Property and navigation names ----------------------------------------------------------------
  for (const model of schema.models) {
    nameMembers(planOf(plans, model), warn);
  }
  const links: Link[] = [];
  const manyToMany: ManyToManyLink[] = [];
  for (const model of schema.models) {
    planRelations(schema, plans, planOf(plans, model), links, manyToMany, warn);
  }
  for (const link of links) {
    link.owner.links.push(link);
  }
  for (const join of manyToMany) {
    join.owner.manyToMany.push(join);
  }

  // Keys, columns and indexes ----------------------------------------------------------------------
  const context: ColumnContext = { provider: options.provider, enums, warn };
  for (const model of schema.models) {
    planAlternateKeys(schema, planOf(plans, model));
  }
  for (const model of schema.models) {
    planColumns(planOf(plans, model), context);
  }
  for (const model of schema.models) {
    planIndexes(planOf(plans, model), options.provider, warn);
  }

  return {
    schema,
    style,
    namespace: options.namespace ?? DEFAULT_EFCORE_NAMESPACE,
    header: options.header !== false,
    provider: options.provider,
    models: schema.models.map((model: IrModel) => planOf(plans, model)),
    enums: [...enums.values()],
  };
}

function planOf(
  plans: ReadonlyMap<string, ModelPlan>,
  model: IrModel
): ModelPlan {
  const plan: ModelPlan | undefined = plans.get(model.name);
  if (plan === undefined) {
    throw new Error(`No plan exists for the model "${model.name}".`);
  }
  return plan;
}

/** Writes each IR enum as a C# enum and decides how its stored values are mapped. */
function planEnums(
  schema: IrSchema,
  typeNames: Set<string>,
  warn: (message: string) => void
): Map<string, EnumPlan> {
  const plans: Map<string, EnumPlan> = new Map<string, EnumPlan>();
  for (const enumeration of schema.enums) {
    const raw: string = /^[A-Z][A-Za-z0-9]*$/.test(enumeration.name)
      ? enumeration.name
      : (pascalIdentifier(enumeration.name) ??
        repairedIdentifier(enumeration.name));
    const typeName: string = uniqueName(
      typeNames.has(raw) ? `${raw}Enum` : raw,
      typeNames
    );
    if (typeName !== raw) {
      warn(
        `enum ${enumeration.name}: "${raw}" is a name the generated code uses or another type has, so the enum was named "${typeName}".`
      );
    }
    const used: Set<string> = new Set<string>();
    const members: Map<string, string> = new Map<string, string>();
    for (const value of enumeration.values) {
      const name: string = uniqueName(repairedIdentifier(value.name), used);
      if (name !== value.name) {
        warn(
          `enum ${enumeration.name}: the member "${value.name}" was written as "${name}".`
        );
      }
      members.set(value.name, name);
    }
    const numeric: boolean =
      enumeration.values.length > 0 &&
      enumeration.values.every((value: IrEnumValue) =>
        /^-?\d+$/.test(value.dbValue)
      );
    const namesMatch: boolean = enumeration.values.every(
      (value: IrEnumValue) => members.get(value.name) === value.dbValue
    );
    plans.set(enumeration.name, {
      enumeration,
      typeName,
      members,
      numeric,
      namesMatch,
      converterName: () => uniqueName(`${typeName}Converter`, typeNames),
    });
  }
  return plans;
}

/** Gives every field and relation of a model its C# names. */
function nameMembers(plan: ModelPlan, warn: (message: string) => void): void {
  const model: IrModel = plan.model;
  for (const field of model.fields) {
    const base: string =
      pascalIdentifier(field.name) ?? repairedIdentifier(field.name);
    const name: string = uniqueName(
      RESERVED_MEMBER_NAMES.has(base) || base === plan.className
        ? `${base}Value`
        : base,
      plan.used
    );
    if (name !== base) {
      warn(
        `${model.name}.${field.name}: "${base}" cannot be a property of ${plan.className}, so the property was named "${name}".`
      );
    }
    plan.fieldProps.set(field.name, name);
  }
  for (const relation of model.relations) {
    if (relation.kind === 'manyToMany') {
      continue;
    }
    const nav: string = navigationName(navBase(relation.name, plan), plan.used);
    plan.relationNavs.set(relation.name, nav);
    plan.relationFks.set(relation.name, uniqueName(`${nav}Id`, plan.used));
  }
  for (const key of model.compositeForeignKeys ?? []) {
    plan.relationNavs.set(
      `composite:${key.name}`,
      navigationName(navBase(key.name, plan), plan.used)
    );
  }
  for (const relation of model.relations) {
    if (relation.kind === 'manyToMany') {
      plan.relationNavs.set(
        relation.name,
        navigationName(navBase(relation.name, plan), plan.used)
      );
    }
  }
}

function navBase(name: string, plan: ModelPlan): string {
  const base: string = pascalIdentifier(name) ?? repairedIdentifier(name);
  return RESERVED_MEMBER_NAMES.has(base) || base === plan.className
    ? `${base}Ref`
    : base;
}

/** The field a foreign key copies its type from: the referenced column, or the single primary key. */
function referencedField(
  schema: IrSchema,
  target: IrModel,
  toField: string | undefined,
  depth: number = 0
): IrField | undefined {
  if (depth > 5) {
    return undefined;
  }
  const explicit: IrField | undefined =
    toField === undefined
      ? undefined
      : target.fields.find(
          (field: IrField) =>
            field.name === toField || field.columnName === toField
        );
  if (explicit !== undefined) {
    return explicit;
  }
  if (target.compositePrimaryKey !== undefined) {
    const only: string | undefined =
      target.compositePrimaryKey.length === 1
        ? target.compositePrimaryKey[0]
        : undefined;
    return target.fields.find((field: IrField) => field.name === only);
  }
  const key: IrField | undefined = target.fields.find(
    (field: IrField) => field.isPrimaryKey
  );
  if (key !== undefined) {
    return key;
  }
  const primary: IrRelation | undefined = target.relations.find(
    (relation: IrRelation) => relation.isPrimaryKey === true
  );
  const chained: IrModel | undefined =
    primary === undefined ? undefined : findModel(schema, primary.targetModel);
  return primary === undefined || chained === undefined
    ? undefined
    : referencedField(schema, chained, primary.toField, depth + 1);
}

/** True when the model has a single-column primary key. */
function hasSingleKey(model: IrModel): boolean {
  if (model.compositePrimaryKey !== undefined) {
    return model.compositePrimaryKey.length === 1;
  }
  return (
    model.fields.filter((field: IrField) => field.isPrimaryKey).length +
      model.relations.filter(
        (relation: IrRelation) => relation.isPrimaryKey === true
      ).length ===
    1
  );
}

function planRelations(
  schema: IrSchema,
  plans: ReadonlyMap<string, ModelPlan>,
  plan: ModelPlan,
  links: Link[],
  manyToMany: ManyToManyLink[],
  warn: (message: string) => void
): void {
  const model: IrModel = plan.model;
  for (const relation of model.relations) {
    const label: string = `${model.name}.${relation.name}`;
    const target: IrModel | undefined = findModel(schema, relation.targetModel);
    const targetPlan: ModelPlan | undefined = plans.get(relation.targetModel);
    if (target === undefined || targetPlan === undefined) {
      warn(
        `${label}: the model ${relation.targetModel} is not in the input, so the relation was skipped${relation.kind === 'manyToMany' ? '' : ' and its column left out'}.`
      );
      plan.relationFks.delete(relation.name);
      plan.relationNavs.delete(relation.name);
      continue;
    }
    if (relation.kind === 'manyToMany') {
      planManyToMany(plan, targetPlan, relation, manyToMany, warn);
      continue;
    }
    const key: IrField | undefined = referencedField(
      schema,
      target,
      relation.toField
    );
    const nav: string | undefined = plan.relationNavs.get(relation.name);
    const foreignKey: string | undefined = plan.relationFks.get(relation.name);
    if (key === undefined || nav === undefined || foreignKey === undefined) {
      warn(
        `${label}: ${relation.targetModel} has no single-column key to reference, so the relation was skipped and its column left out.`
      );
      plan.relationFks.delete(relation.name);
      plan.relationNavs.delete(relation.name);
      continue;
    }
    const oneToOne: boolean = relation.kind === 'oneToOne';
    const inverse: string | undefined =
      relation.relatedName === undefined
        ? undefined
        : inverseName(targetPlan, relation.relatedName);
    const behavior: string = DELETE_BEHAVIORS[relation.onDelete];
    if (relation.onDelete === 'setDefault') {
      warn(
        `${label}: EF Core has no SET DEFAULT delete behavior; NO ACTION was written.`
      );
    }
    const required: boolean = !relation.isNullable;
    if (required && relation.onDelete === 'setNull') {
      warn(
        `${label}: SET NULL on a required relation; the column is NOT NULL, so deleting a ${relation.targetModel} that is referenced fails.`
      );
    }
    const isDefault: boolean = required
      ? relation.onDelete === 'cascade'
      : relation.onDelete === 'noAction';
    const toKey: IrField | undefined =
      relation.toField === undefined
        ? undefined
        : target.fields.find(
            (field: IrField) =>
              field.name === relation.toField ||
              field.columnName === relation.toField
          );
    links.push({
      owner: plan,
      target: targetPlan,
      relationName: relation.name,
      relation,
      nav,
      inverse,
      oneToOne,
      foreignKeys: [foreignKey],
      principalKeys:
        toKey !== undefined && !toKey.isPrimaryKey
          ? [targetPlan.fieldProps.get(toKey.name) ?? toKey.name]
          : undefined,
      behavior: isDefault ? undefined : behavior,
      required,
      constraintName: relation.constraintName,
      keyField: key,
    });
    if (inverse !== undefined) {
      targetPlan.navs.push({
        property: inverse,
        typeName: plan.className,
        collection: !oneToOne,
        nullable: oneToOne,
        inverseOf: { className: plan.className, property: nav },
      });
    }
  }
  for (const key of model.compositeForeignKeys ?? []) {
    planCompositeKey(schema, plans, plan, key, links, warn);
  }
}

function inverseName(target: ModelPlan, relatedName: string): string {
  const base: string =
    pascalIdentifier(relatedName) ?? repairedIdentifier(relatedName);
  const safe: string =
    RESERVED_MEMBER_NAMES.has(base) || base === target.className
      ? `${base}Ref`
      : base;
  return navigationName(safe, target.used);
}

function planCompositeKey(
  schema: IrSchema,
  plans: ReadonlyMap<string, ModelPlan>,
  plan: ModelPlan,
  key: IrCompositeForeignKey,
  links: Link[],
  warn: (message: string) => void
): void {
  const label: string = `${plan.model.name}.${key.name}`;
  const target: IrModel | undefined = findModel(schema, key.targetModel);
  const targetPlan: ModelPlan | undefined = plans.get(key.targetModel);
  const nav: string | undefined = plan.relationNavs.get(
    `composite:${key.name}`
  );
  if (target === undefined || targetPlan === undefined || nav === undefined) {
    warn(
      `${label}: the model ${key.targetModel} is not in the input, so the composite foreign key was skipped.`
    );
    return;
  }
  const localProps: (string | undefined)[] = key.fields.map((name: string) =>
    plan.fieldProps.get(name)
  );
  const principalProps: (string | undefined)[] = key.references.map(
    (name: string) => targetPlan.fieldProps.get(name)
  );
  if (
    localProps.some((name) => name === undefined) ||
    principalProps.some((name) => name === undefined)
  ) {
    warn(
      `${label}: a column of the composite foreign key is not a field of the models, so it was skipped.`
    );
    return;
  }
  const locals: string[] = localProps.filter(
    (name): name is string => name !== undefined
  );
  const principals: string[] = principalProps.filter(
    (name): name is string => name !== undefined
  );
  const oneToOne: boolean = key.kind === 'oneToOne';
  const inverse: string | undefined =
    key.relatedName === undefined
      ? undefined
      : inverseName(targetPlan, key.relatedName);
  const required: boolean = !key.isNullable;
  if (required && key.onDelete === 'setNull') {
    warn(
      `${label}: SET NULL on a required relation; the columns are NOT NULL, so deleting a ${key.targetModel} that is referenced fails.`
    );
  }
  const isPrimary: boolean = sameList(
    key.references,
    target.compositePrimaryKey ?? []
  );
  links.push({
    owner: plan,
    target: targetPlan,
    relationName: key.name,
    composite: key,
    nav,
    inverse,
    oneToOne,
    foreignKeys: locals,
    principalKeys: isPrimary ? undefined : principals,
    behavior: DELETE_BEHAVIORS[key.onDelete],
    required,
    constraintName: key.constraintName,
    keyField: undefined,
  });
  if (key.onDelete === 'setDefault') {
    warn(
      `${label}: EF Core has no SET DEFAULT delete behavior; NO ACTION was written.`
    );
  }
  if (key.onUpdate !== undefined) {
    warn(
      `${label}: the onUpdate action "${key.onUpdate}" is not supported by this format and was ignored.`
    );
  }
  if (inverse !== undefined) {
    targetPlan.navs.push({
      property: inverse,
      typeName: plan.className,
      collection: !oneToOne,
      nullable: oneToOne,
      inverseOf: { className: plan.className, property: nav },
    });
  }
}

function sameList(
  first: readonly string[],
  second: readonly string[]
): boolean {
  return (
    first.length === second.length &&
    first.every((value: string, index: number) => value === second[index])
  );
}

function planManyToMany(
  plan: ModelPlan,
  targetPlan: ModelPlan,
  relation: IrRelation,
  manyToMany: ManyToManyLink[],
  warn: (message: string) => void
): void {
  const label: string = `${plan.model.name}.${relation.name}`;
  const nav: string | undefined = plan.relationNavs.get(relation.name);
  if (
    nav === undefined ||
    !hasSingleKey(plan.model) ||
    !hasSingleKey(targetPlan.model)
  ) {
    warn(
      `${label}: a many-to-many relation needs a single-column key on both models; the relation was skipped.`
    );
    plan.relationNavs.delete(relation.name);
    return;
  }
  const isSelf: boolean = plan.model.name === relation.targetModel;
  const owner: string = toSnakeCase(plan.model.name);
  const other: string = toSnakeCase(relation.targetModel);
  const inverse: string | undefined =
    relation.relatedName === undefined
      ? undefined
      : inverseName(targetPlan, relation.relatedName);
  manyToMany.push({
    owner: plan,
    target: targetPlan,
    relationName: relation.name,
    nav,
    inverse,
    joinTable: `${plan.model.tableName}_${relation.name}`,
    ownerColumn: `${isSelf ? 'from_' : ''}${owner}_id`,
    targetColumn: `${isSelf ? 'to_' : ''}${other}_id`,
  });
  plan.navs.push({
    property: nav,
    typeName: targetPlan.className,
    collection: true,
    nullable: false,
  });
  if (inverse !== undefined) {
    targetPlan.navs.push({
      property: inverse,
      typeName: plan.className,
      collection: true,
      nullable: false,
    });
  }
}

/** Fields that another model's foreign key points at (`toField`) need an alternate key, not an index. */
function planAlternateKeys(schema: IrSchema, plan: ModelPlan): void {
  const model: IrModel = plan.model;
  for (const other of schema.models) {
    for (const relation of other.relations) {
      if (
        relation.targetModel !== model.name ||
        relation.toField === undefined
      ) {
        continue;
      }
      const field: IrField | undefined = model.fields.find(
        (candidate: IrField) =>
          candidate.name === relation.toField ||
          candidate.columnName === relation.toField
      );
      const property: string | undefined =
        field === undefined || field.isPrimaryKey
          ? undefined
          : plan.fieldProps.get(field.name);
      if (
        property !== undefined &&
        !plan.alternateKeys.some((key: string[]) => sameList(key, [property]))
      ) {
        plan.alternateKeys.push([property]);
      }
    }
  }
  for (const other of schema.models) {
    for (const key of other.compositeForeignKeys ?? []) {
      if (key.targetModel !== model.name) {
        continue;
      }
      if (sameList(key.references, model.compositePrimaryKey ?? [])) {
        continue;
      }
      const properties: string[] = key.references
        .map((name: string) => plan.fieldProps.get(name))
        .filter((name): name is string => name !== undefined);
      if (
        properties.length === key.references.length &&
        !plan.alternateKeys.some((existing: string[]) =>
          sameList(existing, properties)
        )
      ) {
        plan.alternateKeys.push(properties);
      }
    }
  }
}

/** Builds the columns of a model: its fields, then the foreign key column of every relation. */
function planColumns(plan: ModelPlan, context: ColumnContext): void {
  const model: IrModel = plan.model;
  const keyNames: string[] = model.compositePrimaryKey ?? [
    ...model.fields
      .filter((field: IrField) => field.isPrimaryKey)
      .map((field: IrField) => field.name),
    ...model.relations
      .filter((relation: IrRelation) => relation.isPrimaryKey === true)
      .map((relation: IrRelation) => relation.name),
  ];
  const keyProps: string[] = [];
  for (const name of keyNames) {
    const property: string | undefined =
      plan.fieldProps.get(name) ?? plan.relationFks.get(name);
    if (property === undefined) {
      context.warn(
        `${model.name}: the primary key member "${name}" is not a field or relation of the model and was left out of the key.`
      );
    } else {
      keyProps.push(property);
    }
  }
  plan.keyProps = keyProps;
  const singleKey: boolean = keyProps.length === 1;
  plan.keyless = keyProps.length === 0;
  if (plan.keyless && !plan.isView) {
    context.warn(
      `${model.name}: the model has no primary key; EF Core needs a key, so the class was written as keyless ([Keyless]).`
    );
    // EF Core maps a keyless entity to no table unless the table is named explicitly.
    plan.needsTable = true;
  }

  const columns: ColumnMember[] = [];
  for (const field of model.fields) {
    const property: string = plan.fieldProps.get(field.name) ?? field.name;
    const isKey: boolean = keyProps.includes(property);
    const spec: ColumnSpec = buildColumn(
      context,
      `${model.name}.${field.name}`,
      isKey && keyProps.length > 1 ? { ...field, isUnique: false } : field,
      { propertyName: property, isKey, singleKey }
    );
    columns.push({ property, spec, isKey, fieldName: field.name });
    if (spec.autoUpdated) {
      plan.autoUpdated.push(property);
    }
  }
  for (const link of plan.links) {
    if (link.relation === undefined) {
      continue;
    }
    const relation: IrRelation = link.relation;
    const key: IrField | undefined = link.keyField;
    const property: string | undefined = link.foreignKeys[0];
    if (key === undefined || property === undefined) {
      continue;
    }
    const isKey: boolean = keyProps.includes(property);
    // The column copies the type of the key it references, without the key's own default or flags.
    const column: IrField = {
      name: relation.name,
      columnName: relation.columnName,
      type: key.type,
      isPrimaryKey: false,
      isUnique: false,
      isNullable: relation.isNullable,
      isAutoUpdated: false,
      ...(key.maxLength === undefined ? {} : { maxLength: key.maxLength }),
      ...(key.maxDigits === undefined ? {} : { maxDigits: key.maxDigits }),
      ...(key.decimalPlaces === undefined
        ? {}
        : { decimalPlaces: key.decimalPlaces }),
      ...(key.enumName === undefined ? {} : { enumName: key.enumName }),
    };
    const spec: ColumnSpec = buildColumn(
      context,
      `${model.name}.${relation.name}`,
      column,
      { propertyName: property, isKey, singleKey }
    );
    columns.push({ property, spec, isKey, relationName: relation.name });
  }
  plan.columns = columns;

  // Navigations in declaration order: the references of this model, then its collections.
  const references: NavMember[] = plan.links.map((link: Link): NavMember => {
    const target: ModelPlan = link.target;
    return {
      property: link.nav,
      typeName: target.className,
      collection: false,
      nullable: !link.required,
      foreignKeys: link.foreignKeys,
      ...(link.inverse === undefined
        ? {}
        : {
            inverseOf: { className: target.className, property: link.inverse },
          }),
    };
  });
  plan.navs = [...references, ...plan.navs];
}

/** Collects the indexes of a model: unique fields, one-to-one keys and the declared indexes. */
function planIndexes(
  plan: ModelPlan,
  provider: PrismaProvider,
  warn: (message: string) => void
): void {
  const model: IrModel = plan.model;
  const indexes: ConfigIndex[] = [];
  const seen: Set<string> = new Set<string>();
  const alternate: Set<string> = new Set(
    plan.alternateKeys.map((key: string[]) => key.join(','))
  );
  const add = (index: ConfigIndex): void => {
    const signature: string = `${index.unique ? 'u' : 'i'}|${index.properties.join(',')}|${index.name ?? ''}`;
    if (seen.has(signature)) {
      return;
    }
    seen.add(signature);
    indexes.push(index);
  };
  const isKey = (properties: readonly string[]): boolean =>
    sameList(properties, plan.keyProps);
  const covered = (properties: readonly string[]): boolean =>
    indexes.some(
      (index: ConfigIndex) =>
        index.unique && sameList(index.properties, properties)
    );

  for (const field of model.fields) {
    const property: string | undefined = plan.fieldProps.get(field.name);
    if (
      property === undefined ||
      !field.isUnique ||
      field.isPrimaryKey ||
      isKey([property])
    ) {
      continue;
    }
    if (alternate.has(property)) {
      continue;
    }
    add({
      properties: [property],
      unique: true,
      descending: [],
      ...(field.uniqueName === undefined ? {} : { name: field.uniqueName }),
    });
  }
  for (const link of plan.links) {
    if (
      link.relation?.kind === 'oneToOne' &&
      link.relation.isPrimaryKey !== true &&
      !covered(link.foreignKeys)
    ) {
      add({
        properties: link.foreignKeys,
        unique: true,
        descending: [],
      });
    }
  }
  for (const index of model.indexes) {
    const properties: string[] = [];
    let skip: boolean = false;
    for (const name of index.fields) {
      const property: string | undefined =
        plan.fieldProps.get(name) ?? plan.relationFks.get(name);
      if (property === undefined) {
        warn(
          `${model.name}: the index (${index.fields.join(', ')}) refers to "${name}", which is not a field or relation of the model; the index was skipped.`
        );
        skip = true;
        break;
      }
      properties.push(property);
    }
    if (skip) {
      continue;
    }
    if (
      index.isUnique &&
      index.name === undefined &&
      alternate.has(properties.join(','))
    ) {
      continue;
    }
    add(indexOf(model, index, properties, provider, warn));
  }
  plan.indexes = indexes;
}

function indexOf(
  model: IrModel,
  index: IrIndex,
  properties: string[],
  provider: PrismaProvider,
  warn: (message: string) => void
): ConfigIndex {
  const label: string = `${model.name} index (${index.fields.join(', ')})`;
  const descending: boolean[] = index.fields.map(
    (name: string) => index.fieldOptions?.[name]?.sort === 'desc'
  );
  let method: string | undefined;
  if (index.method !== undefined) {
    if (isPostgres(provider)) {
      method = index.method.toLowerCase();
    } else {
      warn(
        `${label}: the ${index.method} index method only exists in PostgreSQL (Npgsql); it was dropped.`
      );
    }
  }
  const unsupported: string[] = [];
  for (const options of Object.values(index.fieldOptions ?? {})) {
    if (options.length !== undefined) {
      unsupported.push('prefix length');
    }
    if (options.ops !== undefined) {
      unsupported.push('operator class');
    }
  }
  if (index.clustered !== undefined) {
    unsupported.push('clustering');
  }
  if (unsupported.length > 0) {
    warn(
      `${label}: the ${[...new Set(unsupported)].join(' and ')} option has no EF Core equivalent and was dropped.`
    );
  }
  return {
    properties,
    unique: index.isUnique,
    descending: descending.some((flag: boolean) => flag) ? descending : [],
    ...(index.name === undefined ? {} : { name: index.name }),
    ...(method === undefined ? {} : { method }),
  };
}
