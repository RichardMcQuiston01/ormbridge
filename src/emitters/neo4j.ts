const RULE: string = `// ${'-'.repeat(75)}`;

function banner(title: string): string[] {
  return [RULE, `// ${title}`, RULE];
}

function headerLines(graph: Graph, style: Neo4jStyle): string[] {
  const lines: string[] = [
    '// Neo4j schema (Cypher, Neo4j 5) generated by ormbridge.',
    style === 'enterprise'
      ? '// Style: enterprise. Needs Neo4j Enterprise Edition 5.9 or later (IS NOT NULL, NODE KEY and type constraints).'
      : '// Style: community. IS NOT NULL, NODE KEY and type constraints need Enterprise Edition; use --style enterprise to add them.',
    '// Every statement uses IF NOT EXISTS, so the script can run again (cypher-shell -f schema.cypher).',
    '//',
    '// The graph model is derived: each model is a node label and each foreign key or join table is',
    '// documented below as a relationship. Neo4j keeps no relationship schema, so the foreign key',
    '// columns stay as plain properties. Load the nodes first, then create the relationships with the',
    '// MATCH ... MERGE queries in the relationship comments.',
  ];
  const foreignKeys: string[] = graph.nodes.flatMap((node: GraphNode) =>
    node.foreignKeys.map(
      (property: GraphProperty) => `${node.label}.${property.key}`
    )
  );
  if (foreignKeys.length > 0) {
    lines.push(
      '//',
      `// Foreign key properties kept: ${foreignKeys.join(', ')}`
    );
  }
  return lines;
}

function describeProperty(property: GraphProperty): string {
  const notes: string[] = [
    property.required ? 'required' : 'optional',
    ...property.notes,
  ];
  return `//   ${quoteIdentifier(property.key)}: ${property.type.name} (${notes.join('; ')})`;
}

// ---------------------------------------------------------------------------
// One node label
// ---------------------------------------------------------------------------

function resolveKeys(node: GraphNode, names: string[]): string[] | undefined {
  const keys: string[] = [];
  for (const name of names) {
    const key: string | undefined = node.keys.get(name);
    if (key === undefined) {
      return undefined;
    }
    keys.push(key);
  }
  return keys;
}

function pushAll(target: string[], statement: string | undefined): void {
  if (statement !== undefined) {
    target.push(statement);
  }
}

function nodeSection(
  node: GraphNode,
  writer: StatementWriter,
  warnings: string[]
): string[] {
  const model: IrModel = node.model;
  const target: SchemaTarget = nodeTarget(node.label);
  const lines: string[] = banner(
    `:${quoteIdentifier(node.label)} (model ${oneLine(model.name)}, table ${oneLine(model.tableName)})`
  );
  const constraints: string[] = [];
  const typing: string[] = [];
  const indexes: string[] = [];
  const notes: string[] = [];
  const keyed: Set<string> = new Set<string>();

  // Primary key.
  const keyNames: string[] = primaryKeyNamesOf(model);
  const keyProperties: string[] | undefined = resolveKeys(node, keyNames);
  if (keyNames.length > 0 && keyProperties === undefined) {
    warnings.push(
      `${model.name}: the primary key (${keyNames.join(', ')}) names a column that does not exist, so it was dropped.`
    );
  } else if (keyProperties !== undefined && keyProperties.length === 1) {
    pushAll(constraints, writer.unique(target, keyProperties));
  } else if (keyProperties !== undefined && keyProperties.length > 1) {
    if (writer.style === 'enterprise') {
      pushAll(constraints, writer.nodeKey(target, keyProperties));
      keyProperties.forEach((key: string) => keyed.add(key));
    } else {
      constraints.push(
        `// Composite primary key (${keyProperties.join(', ')}): NODE KEY needs Enterprise Edition, so a uniqueness constraint is used.`
      );
      pushAll(constraints, writer.unique(target, keyProperties));
    }
  }

  // Unique columns and one-to-one foreign keys.
  for (const field of model.fields) {
    const key: string | undefined = node.keys.get(field.name);
    if (field.isUnique && key !== undefined) {
      pushAll(constraints, writer.unique(target, [key]));
    }
  }
  for (const relation of model.relations) {
    const key: string | undefined = node.keys.get(relation.name);
    if (relation.kind === 'oneToOne' && key !== undefined) {
      pushAll(constraints, writer.unique(target, [key]));
    }
  }

  // Indexes. Uniqueness constraints go first: Neo4j refuses one when a plain index over the same
  // properties already exists.
  const ordered: IrIndex[] = [
    ...model.indexes.filter(isUniqueIndex),
    ...model.indexes.filter((index: IrIndex) => !isUniqueIndex(index)),
  ];
  for (const index of ordered) {
    writeIndex(node, index, writer, target, constraints, indexes, warnings);
  }

  // Enterprise: existence and type constraints.
  const required: string[] = [];
  for (const property of node.properties) {
    if (property.required && !keyed.has(property.key)) {
      required.push(property.key);
    }
  }
  if (writer.style === 'enterprise') {
    for (const key of required) {
      pushAll(constraints, writer.required(target, key));
    }
    for (const property of node.properties) {
      if (property.type.constrainable) {
        pushAll(typing, writer.typed(target, property.key, property.type));
      }
    }
  } else if (required.length > 0) {
    notes.push(
      `// Required properties (IS NOT NULL needs Enterprise Edition): ${required.join(', ')}`
    );
  }

  lines.push(...constraints, ...typing, ...indexes, ...notes);
  lines.push(
    '//',
    `// Properties of :${quoteIdentifier(node.label)} and their Neo4j types:`
  );
  lines.push(...node.properties.map(describeProperty));
  return lines;
}

function isUniqueIndex(index: IrIndex): boolean {
  return index.isUnique && index.kind !== 'fulltext';
}

/** Writes one IR index as a constraint or an index, or drops it with a warning. */
function writeIndex(
  node: GraphNode,
  index: IrIndex,
  writer: StatementWriter,
  target: SchemaTarget,
  constraints: string[],
  indexes: string[],
  warnings: string[]
): void {
  const label: string = `${node.model.name} index (${index.fields.join(', ')})`;
  const keys: string[] | undefined = resolveKeys(node, index.fields);
  if (keys === undefined || keys.length === 0) {
    warnings.push(
      `${label}: it names a column that does not exist and was dropped.`
    );
    return;
  }
  if (index.method !== undefined && index.method.toLowerCase() !== 'btree') {
    warnings.push(
      `${label}: Neo4j has no ${index.method} index method; the index was dropped.`
    );
    return;
  }
  const hasOptions: boolean =
    index.clustered !== undefined ||
    (index.fieldOptions !== undefined &&
      Object.keys(index.fieldOptions).length > 0);
  if (hasOptions) {
    warnings.push(
      `${label}: clustering, sort order, prefix length and operator class options have no Neo4j equivalent and were dropped.`
    );
  }
  if (index.kind === 'fulltext') {
    pushAll(indexes, writer.fulltext(target, keys));
  } else if (index.isUnique) {
    pushAll(constraints, writer.unique(target, keys));
  } else {
    pushAll(indexes, writer.index(target, keys));
  }
}
