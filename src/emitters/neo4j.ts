/**
 * Neo4j (Cypher) writer.
 *
 * Writes ONE script of schema statements and comments, no data. Each model is a node label, its
 * columns are properties, and the primary key, unique columns and unique indexes become uniqueness
 * constraints, the other indexes range indexes (full-text indexes stay full-text). Cypher has no
 * relationship schema, so foreign keys, relations and join tables are written as comment blocks, and the
 * foreign key columns stay as plain properties so data can be loaded first and the relationships
 * created afterwards with `MATCH ... MERGE`. A pure join table becomes one relationship.
 *
 * The `community` style (default) writes only what Neo4j Community Edition accepts. The
 * `enterprise` style adds `IS NOT NULL` constraints, `IS NODE KEY` for composite primary keys and
 * property type constraints (Neo4j 5.9 or later). Every statement uses `IF NOT EXISTS`, so the
 * script can run again.
 */

export interface Neo4jEmitOptions {
  /** Use camelCase property keys (the `normalize` naming mode); otherwise the column names are kept. */
  camelFields: boolean;
  /** `community` (default) or `enterprise`. */
  style?: Neo4jStyle;
  /** Write the comment block at the top of the script (default true). */
  header?: boolean;
}

export function emitNeo4j(
  schema: IrSchema,
  options: Neo4jEmitOptions
): EmitOutput {
  const style: Neo4jStyle = options.style ?? 'community';
  const warnings: string[] = schemaWarnings(schema);
  if (schema.models.length === 0) {
    return { text: '', warnings };
  }
  const graph: Graph = buildGraph(
    schema,
    { camelFields: options.camelFields },
    warnings
  );
  const writer: StatementWriter = new StatementWriter(style);

  const sections: string[][] = [];
  if (options.header !== false) {
    sections.push(headerLines(graph, style));
  }
  for (const node of graph.nodes) {
    sections.push(nodeSection(node, writer, warnings));
  }
  const relationships = writeRelationships(schema, graph, writer, warnings);
  if (relationships.lines.length > 0) {
    sections.push([
      ...banner(
        'Relationships (documentation; Neo4j keeps no relationship schema)'
      ),
      ...relationships.lines,
    ]);
  }
  return {
    text: `${sections.map((lines: string[]) => lines.join('\n')).join('\n\n')}\n`,
    warnings,
  };
}

// ---------------------------------------------------------------------------
// Warnings for constructs Neo4j has no place for
// ---------------------------------------------------------------------------

function schemaWarnings(schema: IrSchema): string[] {
  const warnings: string[] = [];
  for (const enumDefinition of schema.enums) {
    if (enumDefinition.schema !== undefined) {
      warnings.push(
        `enum ${enumDefinition.name}: the database schema "${enumDefinition.schema}" (@@schema) was ignored.`
      );
    }
  }
  for (const model of schema.models) {
    if (model.isView === true) {
      warnings.push(
        `${model.name}: this is a database view; it was written as a node label like any other model.`
      );
    }
    if (model.schema !== undefined) {
      warnings.push(
        `${model.name}: the database schema "${model.schema}" (@@schema) was ignored.`
      );
    }
  }
  return warnings;
}

