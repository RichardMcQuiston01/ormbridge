function buildRelationCall(
  context: EmitContext,
  model: IrModel,
  relation: IrRelation
): string {
  const targetLiteral: string = pyString(relation.targetModel);
  const args: string[] = [targetLiteral];

  if (relation.kind === 'manyToMany') {
    if (
      relation.relatedName !== undefined &&
      IDENTIFIER_PATTERN.test(relation.relatedName)
    ) {
      args.push(`related_name=${pyString(relation.relatedName)}`);
    }
    args.push('blank=True');
    return `models.ManyToManyField(${args.join(', ')})`;
  }

  let onDelete: IrOnDelete = relation.onDelete;
  if (onDelete === 'setNull' && !relation.isNullable) {
    context.warnings.push(
      `${model.name}.${relation.name}: onDelete SetNull requires a nullable relation in Django; it was converted to PROTECT.`
    );
    onDelete = 'restrict';
  }
  if (onDelete === 'setDefault') {
    context.warnings.push(
      `${model.name}.${relation.name}: Django's SET_DEFAULT needs a default= value on the field; add one manually.`
    );
  }
  args.push(`on_delete=${ON_DELETE_NAMES[onDelete]}`);

  if (relation.isNullable) {
    args.push('null=True', 'blank=True');
  }
  if (
    relation.relatedName !== undefined &&
    IDENTIFIER_PATTERN.test(relation.relatedName)
  ) {
    args.push(`related_name=${pyString(relation.relatedName)}`);
  }
  if (relation.columnName !== `${relation.name}_id`) {
    args.push(`db_column=${pyString(relation.columnName)}`);
  }
  if (relation.toField !== undefined) {
    args.push(`to_field=${pyString(relation.toField)}`);
  }
  if (relation.isPrimaryKey === true) {
    args.push('primary_key=True');
  }
  const className: string =
    relation.kind === 'oneToOne' ? 'OneToOneField' : 'ForeignKey';
  return `models.${className}(${args.join(', ')})`;
}
