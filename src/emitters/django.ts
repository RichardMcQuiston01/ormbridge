function djangoFieldClass(field: IrField): string {
  const isAutoKey: boolean =
    field.isPrimaryKey &&
    field.default !== undefined &&
    field.default.kind === 'autoIncrement';
  switch (field.type) {
    case 'string':
      return 'CharField';
    case 'text':
      return 'TextField';
    case 'int':
      return isAutoKey ? 'AutoField' : 'IntegerField';
    case 'bigInt':
      return isAutoKey ? 'BigAutoField' : 'BigIntegerField';
    case 'float':
      return 'FloatField';
    case 'decimal':
      return 'DecimalField';
    case 'boolean':
      return 'BooleanField';
    case 'dateTime':
      return 'DateTimeField';
    case 'date':
      return 'DateField';
    case 'time':
      return 'TimeField';
    case 'uuid':
      return 'UUIDField';
    case 'json':
      return 'JSONField';
    case 'bytes':
      return 'BinaryField';
    case 'duration':
      return 'DurationField';
    case 'ipAddress':
      return 'GenericIPAddressField';
    case 'hstore':
      return 'HStoreField';
    case 'range':
      return RANGE_FIELD_CLASSES[field.rangeOf ?? 'int'];
    default:
      return 'CharField';
  }
}

/** True for the field types that live in django.contrib.postgres. */
function isPostgresOnly(field: IrField): boolean {
  return (
    (field.arrayDepth ?? 0) > 0 ||
    field.type === 'hstore' ||
    field.type === 'range'
  );
}

/**
 * Writes the column type with its type-specific arguments (length, precision, choices,
 * array element), without constraints such as null or unique.
 */
function buildTypeCall(
  context: EmitContext,
  model: IrModel,
  field: IrField
): string {
  const label: string = `${model.name}.${field.name}`;
  const depth: number = field.arrayDepth ?? 0;
  if (depth > 0) {
    const element: IrField = {
      ...field,
      arrayDepth: depth - 1 > 0 ? depth - 1 : undefined,
      isPrimaryKey: false,
      isUnique: false,
      isNullable: false,
      isAutoUpdated: false,
      default: undefined,
      generated: undefined,
      isDbDefault: undefined,
    };
    context.postgresFields.add('ArrayField');
    return `ArrayField(${buildTypeCall(context, model, element)})`;
  }

  const className: string = djangoFieldClass(field);
  const args: string[] = [];
  if (field.enumName !== undefined) {
    const enumDefinition: IrEnum | undefined = context.schema.enums.find(
      (candidate: IrEnum) => candidate.name === field.enumName
    );
    const longestValue: number = Math.max(
      32,
      ...(enumDefinition?.values ?? []).map((value) => value.dbValue.length)
    );
    args.push(
      `max_length=${longestValue}`,
      `choices=${field.enumName}.choices`
    );
  } else if (className === 'CharField') {
    args.push(`max_length=${field.maxLength ?? 255}`);
  } else if (className === 'DecimalField') {
    args.push(
      `max_digits=${field.maxDigits ?? 65}`,
      `decimal_places=${field.decimalPlaces ?? 30}`
    );
  }

  if (field.type === 'hstore' || field.type === 'range') {
    context.postgresFields.add(className);
    if (field.type === 'range' && field.rangeOf === undefined) {
      context.warnings.push(
        `${label}: the range field has no element type; it was written as IntegerRangeField.`
      );
    }
    return `${className}(${args.join(', ')})`;
  }
  return `models.${className}(${args.join(', ')})`;
}

function buildFieldCall(
  context: EmitContext,
  model: IrModel,
  field: IrField
): string {
  if (field.generated !== undefined) {
    return buildGeneratedCall(context, model, field, field.generated);
  }

  const typeCall: string = buildTypeCall(context, model, field);
  const args: string[] = [];
  const openIndex: number = typeCall.indexOf('(');
  const innerArgs: string = typeCall.slice(openIndex + 1, -1);
  if (innerArgs.length > 0) {
    args.push(innerArgs);
  }

  if (field.isPrimaryKey) {
    args.push('primary_key=True');
  }
  if (field.isUnique && !field.isPrimaryKey) {
    args.push('unique=True');
  }
  if (field.isNullable) {
    args.push('null=True', 'blank=True');
  }
  if (field.columnName !== field.name) {
    args.push(`db_column=${pyString(field.columnName)}`);
  }
  if (field.isAutoUpdated) {
    args.push('auto_now=True');
  } else {
    const defaultArgument: string | undefined = defaultArgumentOf(
      context,
      model,
      field
    );
    if (defaultArgument !== undefined) {
      args.push(defaultArgument);
    }
  }
  if (
    field.isPrimaryKey &&
    field.default !== undefined &&
    field.default.kind === 'uuid'
  ) {
    args.push('editable=False');
  }
  return `${typeCall.slice(0, openIndex)}(${args.join(', ')})`;
}

function buildGeneratedCall(
  context: EmitContext,
  model: IrModel,
  field: IrField,
  generated: IrGenerated
): string {
  const output: IrField = {
    ...field,
    columnName: field.name,
    isPrimaryKey: false,
    isUnique: false,
    isAutoUpdated: false,
    default: undefined,
    generated: undefined,
    isDbDefault: undefined,
  };
  context.expressions.push(generated.expression);
  const args: string[] = [
    `expression=${generated.expression}`,
    `output_field=${buildFieldCall(context, model, output)}`,
    `db_persist=${generated.isStored ? 'True' : 'False'}`,
  ];
  if (field.columnName !== field.name) {
    args.push(`db_column=${pyString(field.columnName)}`);
  }
  if (field.isUnique) {
    args.push('unique=True');
  }
  return `models.GeneratedField(${args.join(', ')})`;
}

function defaultArgumentOf(
  context: EmitContext,
  model: IrModel,
  field: IrField
): string | undefined {
  const argument: string | undefined = plainDefaultArgumentOf(
    context,
    model,
    field
  );
  if (argument === undefined || field.isDbDefault !== true) {
    return argument;
  }
  if (argument === 'default=timezone.now') {
    return 'db_default=Now()';
  }
  if (argument === 'default=uuid.uuid4') {
    return 'db_default=RandomUUID()';
  }
  if (argument === 'default=list' || argument === 'default=dict') {
    // db_default takes SQL expressions, which have no empty list or dict shorthand.
    return argument;
  }
  return argument.replace(/^default=/, 'db_default=');
}

function plainDefaultArgumentOf(
  context: EmitContext,
  model: IrModel,
  field: IrField
): string | undefined {
  const defaultValue: IrDefault | undefined = field.default;
  if (defaultValue === undefined) {
    return undefined;
  }
  switch (defaultValue.kind) {
    case 'autoIncrement':
      return undefined;
    case 'now':
      return 'default=timezone.now';
    case 'uuid':
      return 'default=uuid.uuid4';
    case 'enumValue':
      return field.enumName === undefined
        ? undefined
        : `default=${field.enumName}.${defaultValue.value}`;
    case 'literal': {
      const literal: string | number | boolean = defaultValue.value;
      if (typeof literal === 'boolean') {
        return `default=${literal ? 'True' : 'False'}`;
      }
      if (typeof literal === 'number') {
        return `default=${String(literal)}`;
      }
      if (
        (field.type === 'json' || (field.arrayDepth ?? 0) > 0) &&
        literal === '[]'
      ) {
        return 'default=list';
      }
      if (
        (field.type === 'json' || field.type === 'hstore') &&
        literal === '{}'
      ) {
        return 'default=dict';
      }
      if (field.type === 'json') {
        context.warnings.push(
          `${model.name}.${field.name}: the JSON default ${pyString(literal)} was emitted as a string; adjust it if a dict or list was intended.`
        );
      }
      return `default=${pyString(literal)}`;
    }
    default:
      return undefined;
  }
}

