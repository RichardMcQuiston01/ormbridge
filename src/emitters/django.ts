function djangoFieldClass(field: IrField): string {
  const isAutoKey: boolean =
    field.isPrimaryKey &&
    field.default !== undefined &&
    field.default.kind === 'autoIncrement';
  switch (field.type) {
    case 'string':
      return 'CharField';
    case 'text':
      return 'TextField';
    case 'int':
      return isAutoKey ? 'AutoField' : 'IntegerField';
    case 'bigInt':
      return isAutoKey ? 'BigAutoField' : 'BigIntegerField';
    case 'float':
      return 'FloatField';
    case 'decimal':
      return 'DecimalField';
    case 'boolean':
      return 'BooleanField';
    case 'dateTime':
      return 'DateTimeField';
    case 'date':
      return 'DateField';
    case 'time':
      return 'TimeField';
    case 'uuid':
      return 'UUIDField';
    case 'json':
      return 'JSONField';
    case 'bytes':
      return 'BinaryField';
    default:
      return 'CharField';
  }
}

function buildFieldCall(
  context: EmitContext,
  model: IrModel,
  field: IrField
): string {
  const className: string = djangoFieldClass(field);
  const args: string[] = [];

  if (field.enumName !== undefined) {
    const enumDefinition: IrEnum | undefined = context.schema.enums.find(
      (candidate: IrEnum) => candidate.name === field.enumName
    );
    const longestValue: number = Math.max(
      32,
      ...(enumDefinition?.values ?? []).map((value) => value.dbValue.length)
    );
    args.push(
      `max_length=${longestValue}`,
      `choices=${field.enumName}.choices`
    );
  } else if (className === 'CharField') {
    args.push(`max_length=${field.maxLength ?? 255}`);
  } else if (className === 'DecimalField') {
    args.push(
      `max_digits=${field.maxDigits ?? 65}`,
      `decimal_places=${field.decimalPlaces ?? 30}`
    );
  }

  if (field.isPrimaryKey) {
    args.push('primary_key=True');
  }
  if (field.isUnique && !field.isPrimaryKey) {
    args.push('unique=True');
  }
  if (field.isNullable) {
    args.push('null=True', 'blank=True');
  }
  if (field.columnName !== field.name) {
    args.push(`db_column=${pyString(field.columnName)}`);
  }
  if (field.isAutoUpdated) {
    args.push('auto_now=True');
  } else {
    const defaultArgument: string | undefined = defaultArgumentOf(
      context,
      model,
      field
    );
    if (defaultArgument !== undefined) {
      args.push(defaultArgument);
    }
  }
  if (
    field.isPrimaryKey &&
    field.default !== undefined &&
    field.default.kind === 'uuid'
  ) {
    args.push('editable=False');
  }
  return `models.${className}(${args.join(', ')})`;
}

function defaultArgumentOf(
  context: EmitContext,
  model: IrModel,
  field: IrField
): string | undefined {
  const defaultValue: IrDefault | undefined = field.default;
  if (defaultValue === undefined) {
    return undefined;
  }
  switch (defaultValue.kind) {
    case 'autoIncrement':
      return undefined;
    case 'now':
      return 'default=timezone.now';
    case 'uuid':
      return 'default=uuid.uuid4';
    case 'enumValue':
      return field.enumName === undefined
        ? undefined
        : `default=${field.enumName}.${defaultValue.value}`;
    case 'literal': {
      const literal: string | number | boolean = defaultValue.value;
      if (typeof literal === 'boolean') {
        return `default=${literal ? 'True' : 'False'}`;
      }
      if (typeof literal === 'number') {
        return `default=${String(literal)}`;
      }
      if (field.type === 'json' && literal === '[]') {
        return 'default=list';
      }
      if (field.type === 'json' && literal === '{}') {
        return 'default=dict';
      }
      if (field.type === 'json') {
        context.warnings.push(
          `${model.name}.${field.name}: the JSON default ${pyString(literal)} was emitted as a string; adjust it if a dict or list was intended.`
        );
      }
      return `default=${pyString(literal)}`;
    }
    default:
      return undefined;
  }
}

// ---------------------------------------------------------------------------
// Relations
// ---------------------------------------------------------------------------

function buildRelationCall(
  context: EmitContext,
  model: IrModel,
  relation: IrRelation
): string {
  const targetLiteral: string = pyString(relation.targetModel);
  const args: string[] = [targetLiteral];

  if (relation.kind === 'manyToMany') {
    if (
      relation.relatedName !== undefined &&
      IDENTIFIER_PATTERN.test(relation.relatedName)
    ) {
      args.push(`related_name=${pyString(relation.relatedName)}`);
    }
    args.push('blank=True');
    return `models.ManyToManyField(${args.join(', ')})`;
  }

  let onDelete: IrOnDelete = relation.onDelete;
  if (onDelete === 'setNull' && !relation.isNullable) {
    context.warnings.push(
      `${model.name}.${relation.name}: onDelete SetNull requires a nullable relation in Django; it was converted to PROTECT.`
    );
    onDelete = 'restrict';
  }
  if (onDelete === 'setDefault') {
    context.warnings.push(
      `${model.name}.${relation.name}: Django's SET_DEFAULT needs a default= value on the field; add one manually.`
    );
  }
  args.push(`on_delete=${ON_DELETE_NAMES[onDelete]}`);

  if (relation.isNullable) {
    args.push('null=True', 'blank=True');
  }
  if (
    relation.relatedName !== undefined &&
    IDENTIFIER_PATTERN.test(relation.relatedName)
  ) {
    args.push(`related_name=${pyString(relation.relatedName)}`);
  }
  if (relation.columnName !== `${relation.name}_id`) {
    args.push(`db_column=${pyString(relation.columnName)}`);
  }
  if (relation.toField !== undefined) {
    args.push(`to_field=${pyString(relation.toField)}`);
  }
  if (relation.isPrimaryKey === true) {
    args.push('primary_key=True');
  }
  const className: string =
    relation.kind === 'oneToOne' ? 'OneToOneField' : 'ForeignKey';
  return `models.${className}(${args.join(', ')})`;
}
