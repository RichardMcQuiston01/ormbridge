/**
 * ClickHouse dialect of the SQL DDL writer (`--to sql --provider clickhouse`).
 *
 * One `CREATE TABLE ... ENGINE = MergeTree() ORDER BY (...)` per model, in the order of the schema
 * (there are no foreign keys, so no dependency order). The sorting key is the primary key of the
 * model (`tuple()` when it has none, with a warning). ClickHouse has no enforced foreign keys, unique
 * constraints or auto-increment: relations become plain columns of the referenced type, and each
 * dropped construct is named in a warning. Identifiers are quoted with backticks, only when needed.
 */

interface ChColumn {
  name: string;
  /** The type as written, with `Nullable(...)` when the column is nullable. */
  sqlType: string;
  type: ChType;
  nullable: boolean;
  defaultSql?: string;
  /** `MATERIALIZED` / `ALIAS` expression of a generated column. */
  generatedSql?: { kind: 'MATERIALIZED' | 'ALIAS'; expression: string };
  comment?: string;
}

export interface ChTable {
  model: IrModel;
  columns: ChColumn[];
  primaryKey: string[];
  indexes: string[];
}

export interface ChEmitContext extends ChTypeContext {
  schema: IrSchema;
  /** Fields refreshed by the ORM on update, which the DDL cannot express. */
  unexpressedAutoUpdates: string[];
}

export function chQuote(name: string): string {
  return quoteIdentifier('mysql', name);
}

export function emitClickhouseDdl(
  schema: IrSchema,
  naming: NamingMode
): EmitOutput {
  const expanded: IrSchema = expandManyToMany(schema);
  const prepared: IrSchema =
    naming === 'normalize' ? normalizeSchema(expanded) : expanded;
  const context: ChEmitContext = {
    schema: prepared,
    warnings: [],
    enums: new Map<string, IrEnum>(),
    unexpressedAutoUpdates: [],
  };
  for (const definition of prepared.enums) {
    if (definition.values.length === 0) {
      context.warnings.push(
        `enum ${definition.name}: an enum without values cannot be written; columns that use it became plain strings.`
      );
    } else {
      context.enums.set(definition.name, definition);
    }
  }

  const tables: ChTable[] = [];
  const views: IrModel[] = [];
  for (const model of prepared.models) {
    if (model.isView === true) {
      views.push(model);
    } else {
      tables.push(buildTable(context, model));
    }
  }
  for (const table of tables) {
    table.indexes = buildClickhouseIndexes(context, table);
  }
  for (const view of views) {
    context.warnings.push(
      `${view.name}: this is a database view; the schema has no SQL definition for it, so only a commented placeholder was written.`
    );
  }
  if (context.unexpressedAutoUpdates.length > 0) {
    context.warnings.push(
      `ClickHouse cannot refresh a column on update from the DDL (${context.unexpressedAutoUpdates.join(', ')}); the application has to set it.`
    );
  }
  // A schema of the source (Prisma @@schema) is a ClickHouse database, created before its tables.
  const databases: string[] = [
    ...new Set(
      tables
        .map((table: ChTable) => table.model.schema)
        .filter(
          (name: string | undefined): name is string => name !== undefined
        )
    ),
  ];
  const blocks: string[] = [
    '-- SQL DDL for ClickHouse, generated by ormbridge.',
    ...databases.map(
      (name: string) => `CREATE DATABASE IF NOT EXISTS ${chQuote(name)};`
    ),
    ...tables.map((table: ChTable) => renderTable(table)),
    ...views.map((view: IrModel) => renderView(view)),
  ];
  return { text: `${blocks.join('\n\n')}\n`, warnings: context.warnings };
}

/** The name of a table, with its database when the model has one (`db.table`). */
export function chTableName(model: IrModel): string {
  return model.schema === undefined
    ? chQuote(model.tableName)
    : `${chQuote(model.schema)}.${chQuote(model.tableName)}`;
}

// ---------------------------------------------------------------------------
// Tables
// ---------------------------------------------------------------------------

function primaryKeyOf(model: IrModel): string[] {
  const composite: string[] = (model.compositePrimaryKey ?? [])
    .map((name: string) => columnNameOf(model, name))
    .filter((name: string | undefined): name is string => name !== undefined);
  if (composite.length > 0) {
    return composite;
  }
  return [
    ...model.fields
      .filter((field: IrField) => field.isPrimaryKey)
      .map((field: IrField) => field.columnName),
    ...model.relations
      .filter(
        (relation: IrRelation) =>
          relation.kind !== 'manyToMany' && relation.isPrimaryKey === true
      )
      .map((relation: IrRelation) => relation.columnName),
  ];
}

function buildTable(context: ChEmitContext, model: IrModel): ChTable {
  const primaryKey: string[] = primaryKeyOf(model);
  const columns: ChColumn[] = [];
  const known: Set<string> = new Set<string>();

  for (const field of model.fields) {
    known.add(field.columnName);
    columns.push(
      buildColumn(
        context,
        model,
        `${model.name}.${field.name}`,
        field,
        primaryKey.includes(field.columnName)
      )
    );
    if (field.isUnique && !primaryKey.includes(field.columnName)) {
      context.warnings.push(
        `${model.name}.${field.name}: ClickHouse has no unique constraints; the unique constraint on "${field.columnName}" was dropped (a ReplacingMergeTree with that column in its ORDER BY can deduplicate rows).`
      );
    }
  }

  for (const relation of model.relations) {
    if (relation.kind === 'manyToMany') {
      continue;
    }
    const label: string = `${model.name}.${relation.name}`;
    const target: IrModel | undefined = findModel(
      context.schema,
      relation.targetModel
    );
    if (target === undefined) {
      context.warnings.push(
        `${label}: target model "${relation.targetModel}" does not exist in the schema; the relation was skipped.`
      );
      continue;
    }
    if (target.isView === true) {
      context.warnings.push(
        `${label}: target "${target.name}" is a view, which a relation cannot reference; the relation was skipped.`
      );
      continue;
    }
    const referenced: ResolvedTarget | undefined = resolveTarget(
      context,
      target,
      relation.toField
    );
    if (referenced === undefined) {
      context.warnings.push(
        `${label}: target model "${target.name}" has no single column to reference (a composite or missing key); the relation was skipped.`
      );
      continue;
    }
    context.warnings.push(
      `${label}: ClickHouse has no foreign keys; the relation to ${target.name} was written as the plain column "${relation.columnName}" (no constraint, no ON DELETE action).`
    );
    if (
      relation.kind === 'oneToOne' &&
      !primaryKey.includes(relation.columnName)
    ) {
      context.warnings.push(
        `${label}: ClickHouse has no unique constraints; the one-to-one uniqueness of "${relation.columnName}" was dropped.`
      );
    }
    if (known.has(relation.columnName)) {
      continue;
    }
    known.add(relation.columnName);
    const asField: IrField = {
      ...referenced.field,
      name: relation.name,
      columnName: relation.columnName,
      isPrimaryKey: false,
      isUnique: false,
      isNullable: relation.isNullable,
      isAutoUpdated: false,
      default: undefined,
      generated: undefined,
    };
    columns.push(
      buildColumn(
        context,
        model,
        label,
        asField,
        primaryKey.includes(relation.columnName)
      )
    );
  }

  for (const key of model.compositeForeignKeys ?? []) {
    context.warnings.push(
      `${model.name}.${key.name}: ClickHouse has no foreign keys; the composite key to ${key.targetModel} (${key.fields.join(', ')}) was dropped and its columns stay plain columns.`
    );
  }

  if (primaryKey.length === 0) {
    context.warnings.push(
      `${model.name}: the model has no primary key, so ORDER BY tuple() was written (no sorting key); choose a sorting key for query performance.`
    );
  }
  return { model, columns, primaryKey, indexes: [] };
}

