/** Translates a simple Django expression (`F("a") + F("b") * 2`) into SQL, or undefined. */
function generatedExpression(
  model: IrModel,
  expression: string
): string | undefined {
  let unknownColumn: boolean = false;
  const columns: string[] = [];
  // Columns become placeholders first, so that what is left can be checked as plain arithmetic.
  const skeleton: string = expression.replace(
    /\bF\(\s*(["'])([^"']+)\1\s*\)/g,
    (_match: string, _quote: string, name: string): string => {
      const column: string | undefined = columnNameOf(model, name);
      unknownColumn = unknownColumn || column === undefined;
      columns.push(chQuote(column ?? name));
      return `@${columns.length - 1}@`;
    }
  );
  const arithmetic: string = skeleton.replace(/@\d+@/g, '');
  if (
    unknownColumn ||
    columns.length === 0 ||
    !/^[\s\d+\-*/().%]*$/.test(arithmetic)
  ) {
    return undefined;
  }
  return skeleton.replace(
    /@(\d+)@/g,
    (_match: string, position: string): string =>
      columns[Number(position)] ?? ''
  );
}

function buildColumn(
  context: ChEmitContext,
  model: IrModel,
  label: string,
  field: IrField,
  inKey: boolean
): ChColumn {
  const type: ChType = clickhouseType(context, label, field);
  // A column of the sorting key cannot be Nullable.
  const nullable: boolean = field.isNullable && !inKey;
  if (field.isNullable && !type.nullable) {
    context.warnings.push(
      `${label}: ClickHouse cannot make ${type.kind === 'map' ? 'a Map' : 'an Array'} column Nullable; the column was written as ${type.sql} (empty stands in for NULL).`
    );
  }
  const column: ChColumn = {
    name: field.columnName,
    sqlType: withNullability(type, nullable),
    type,
    nullable: nullable && type.nullable,
  };
  const notes: string[] = type.comment === undefined ? [] : [type.comment];

  if (field.generated !== undefined) {
    const expression: string | undefined = generatedExpression(
      model,
      field.generated.expression
    );
    if (expression === undefined) {
      context.warnings.push(
        `${label}: the generated column expression ${field.generated.expression} is not SQL; the column was written as a regular column.`
      );
      notes.push('generated column written as a regular column');
    } else {
      column.generatedSql = {
        kind: field.generated.isStored ? 'MATERIALIZED' : 'ALIAS',
        expression,
      };
    }
  }

  if (field.default !== undefined && column.generatedSql === undefined) {
    const result: DefaultResult = clickhouseDefault(
      context,
      label,
      field,
      type,
      field.default
    );
    if (result.dropped !== undefined) {
      context.warnings.push(`${label}: ${result.dropped}.`);
    } else if (result.sql !== undefined) {
      column.defaultSql = result.sql;
    }
  }
  if (field.isAutoUpdated) {
    context.unexpressedAutoUpdates.push(label);
  }
  if (notes.length > 0) {
    column.comment = notes.join('; ');
  }
  return column;
}

// ---------------------------------------------------------------------------
// Rendering
// ---------------------------------------------------------------------------

function columnLine(column: ChColumn): string {
  const parts: string[] = [chQuote(column.name), column.sqlType];
  if (column.generatedSql !== undefined) {
    parts.push(`${column.generatedSql.kind} ${column.generatedSql.expression}`);
  } else if (column.defaultSql !== undefined) {
    parts.push(`DEFAULT ${column.defaultSql}`);
  }
  if (column.comment !== undefined) {
    parts.push(`COMMENT ${chString(column.comment)}`);
  }
  return parts.join(' ');
}

function renderTable(table: ChTable): string {
  const items: string[] = [
    ...table.columns.map((column: ChColumn) => columnLine(column)),
    ...table.indexes,
  ];
  const key: string =
    table.primaryKey.length === 0
      ? 'tuple()'
      : `(${table.primaryKey.map(chQuote).join(', ')})`;
  const lines: string[] = [
    `CREATE TABLE ${chTableName(table.model)} (`,
    items.map((item: string) => `  ${item}`).join(',\n'),
    ')',
    'ENGINE = MergeTree()',
    `ORDER BY ${key}`,
  ];
  if (table.primaryKey.length > 0) {
    lines.push(`PRIMARY KEY ${key}`);
  }
  if (table.model.isJoinTable === true) {
    lines.push(`COMMENT ${chString('many-to-many join table')}`);
  }
  lines[lines.length - 1] = `${lines[lines.length - 1] ?? ''};`;
  return lines.join('\n');
}

function renderView(view: IrModel): string {
  const columns: string = [
    ...view.fields.map((field: IrField) => field.columnName),
    ...view.relations
      .filter((relation: IrRelation) => relation.kind !== 'manyToMany')
      .map((relation: IrRelation) => relation.columnName),
  ]
    .join(', ')
    .replace(/\s+/g, ' ');
  return [
    `-- View ${chTableName(view)}: the schema has no SQL definition for it, so no statement was written.`,
    `-- Columns: ${columns}`,
    `-- CREATE VIEW ${chTableName(view)} AS SELECT ... ;`,
  ].join('\n');
}
