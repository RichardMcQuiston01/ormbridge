/** The first matching rule wins; a rule without a replacement keeps the word as it is. */
function applyRules(word: string, rules: readonly Rule[]): string {
  if (UNCOUNTABLE_WORDS.has(word.toLowerCase())) {
    return word;
  }
  for (const [pattern, replacement] of rules) {
    if (pattern.test(word)) {
      return replacement === undefined
        ? word
        : word.replace(pattern, replacement);
    }
  }
  return word;
}

/** `Utils.pluralize`: `Category` becomes `Categories`. */
export function pluralize(word: string): string {
  return applyRules(word, PLURAL_RULES);
}

/** `Utils.singularize`: `Categories` becomes `Category`. */
export function singularize(word: string): string {
  return applyRules(word, SINGULAR_RULES);
}

/** `Utils.underscore`: `createdAt` becomes `created_at` (every capital starts a new word). */
export function underscore(word: string): string {
  return word
    .replace(/([A-Z])/g, '_$1')
    .replace(/^_/, '')
    .toLowerCase();
}

/** `Utils.camelize`: separators are dropped and the letter after each is capitalised (`user_id` -> `userId`). */
export function camelize(word: string): string {
  return word
    .trim()
    .replace(/[-_\s]+(.)?/g, (_match: string, next: string | undefined) =>
      next === undefined ? '' : next.toUpperCase()
    );
}
