import {
  emitJpa,
  Imports,
  type AnnotationNode,
  type JpaAttribute,
  type JpaEmitOptions,
  type JpaEnumPlan,
  type JpaFileLayout,
  type JpaIdPart,
  type JpaModelPlan,
  type JpaPlanned,
  type JpaRenderer,
  type JpaStyle,
  type MultiFileEmitOutput,
} from 'ormbridge';
import { formatKotlinAnnotation } from './kotlinAnnotations.js';
import {
  declaresNotNull,
  isCollection,
  isPrimitive,
  KOTLIN_BUILT_IN_IMPORTS,
  kotlinInitializer,
  kotlinType,
  primitiveDefault,
} from './kotlinTypes.js';

/** Options of the Kotlin writer: those of the JPA writer, without the Java-only ones. */
export type KotlinEmitOptions = Omit<JpaEmitOptions, 'extension' | 'lombok'> & {
  /** Lombok has no use in Kotlin; asking for it only adds a warning. */
  lombok?: boolean;
  /** Changes the plans like the Spring Data addon does, in addition to the language. */
  adjust?: (planned: JpaPlanned) => Record<string, string>;
};

const INDENT: string = '    ';

const HARD_KEYWORDS: ReadonlySet<string> = new Set<string>([
  'as',
  'break',
  'class',
  'continue',
  'do',
  'else',
  'false',
  'for',
  'fun',
  'if',
  'in',
  'interface',
  'is',
  'null',
  'object',
  'package',
  'return',
  'super',
  'this',
  'throw',
  'true',
  'try',
  'typealias',
  'typeof',
  'val',
  'var',
  'when',
  'while',
]);

/** A property name, in backticks when it is a Kotlin keyword. */
function kotlinName(name: string): string {
  return HARD_KEYWORDS.has(name) ? `\`${name}\`` : name;
}

/** Types that Kotlin does not allow `lateinit` for: the ones the JVM represents as primitives. */
const NO_LATEINIT: ReadonlySet<string> = new Set<string>([
  'Int',
  'Long',
  'Short',
  'Byte',
  'Boolean',
  'Double',
  'Float',
  'Char',
]);

function importLines(imports: Imports, body: string): string[] {
  imports.prune(body);
  return imports
    .lines()
    .map((line: string): string => line.replace(/;$/, ''))
    .filter(
      (line: string): boolean =>
        !KOTLIN_BUILT_IN_IMPORTS.has(line.replace(/^import /, ''))
    );
}

function fileText(
  layout: JpaFileLayout,
  imports: Imports,
  body: readonly string[]
): string {
  const text: string = body.join('\n');
  const lines: string[] = [];
  if (layout.header) {
    lines.push(
      '// <auto-generated>',
      '// Generated by ormbridge. Review the output before use.',
      '// </auto-generated>'
    );
  }
  lines.push(`package ${layout.packageName}`, '');
  const written: string[] = importLines(imports, text);
  if (written.length > 0) {
    lines.push(...written, '');
  }
  lines.push(...body);
  return `${lines.join('\n')}\n`;
}

function annotationLines(
  annotations: readonly AnnotationNode[],
  indent: number
): string[] {
  return annotations.flatMap((node: AnnotationNode): string[] =>
    formatKotlinAnnotation(node, indent)
  );
}

/** The declaration of one property, the way a Kotlin entity holds it: a `var` with its initial value. */
function declaration(attribute: JpaAttribute): string {
  const name: string = kotlinName(attribute.name);
  const type: string = kotlinType(attribute.type);
  if (isPrimitive(attribute.type)) {
    const initial: string =
      attribute.initializer === undefined
        ? primitiveDefault(attribute.type)
        : kotlinInitializer(attribute.initializer);
    return `var ${name}: ${type} = ${initial}`;
  }
  if (attribute.initializer !== undefined) {
    const initial: string = kotlinInitializer(attribute.initializer);
    const nullable: boolean =
      !isCollection(attribute.type) && !declaresNotNull(attribute.annotations);
    return `var ${name}: ${type}${nullable ? '?' : ''} = ${initial}`;
  }
  if (
    declaresNotNull(attribute.annotations) &&
    !isCollection(attribute.type) &&
    !NO_LATEINIT.has(type)
  ) {
    return `lateinit var ${name}: ${type}`;
  }
  return `var ${name}: ${type}? = null`;
}

function propertyLines(attribute: JpaAttribute): string[] {
  return [
    ...annotationLines(attribute.annotations, INDENT.length),
    `${INDENT}${declaration(attribute)}`,
  ];
}

const SERIAL_VERSION: string[] = [
  `${INDENT}companion object {`,
  `${INDENT}${INDENT}private const val serialVersionUID: Long = 1L`,
  `${INDENT}}`,
];

function renderEntity(
  plan: JpaModelPlan,
  layout: JpaFileLayout,
  extended: ReadonlySet<string>
): string {
  const imports: Imports = new Imports('jakarta');
  imports.merge(plan.imports);
  for (const attribute of plan.attributes) {
    imports.merge(attribute.imports);
  }
  if (plan.serializable === true) {
    imports.use('java.io.Serializable');
  }
  const body: string[] = annotationLines(plan.classAnnotations, 0);
  const parents: string[] = [];
  if (plan.extendsClass !== undefined) {
    parents.push(`${plan.extendsClass}()`);
  }
  if (plan.serializable === true) {
    parents.push('Serializable');
  }
  const modifier: string =
    plan.isAbstract === true
      ? 'abstract '
      : extended.has(plan.className)
        ? 'open '
        : '';
  const header: string = `${modifier}class ${plan.className}${parents.length === 0 ? '' : ` : ${parents.join(', ')}`}`;
  if (plan.attributes.length === 0 && plan.serializable !== true) {
    body.push(header);
    return fileText(layout, imports, body);
  }
  body.push(`${header} {`);
  plan.attributes.forEach((attribute: JpaAttribute, position: number) => {
    if (position > 0) {
      body.push('');
    }
    body.push(...propertyLines(attribute));
  });
  if (plan.serializable === true) {
    if (plan.attributes.length > 0) {
      body.push('');
    }
    body.push(...SERIAL_VERSION);
  }
  body.push('}');
  return fileText(layout, imports, body);
}

function constant(plan: JpaEnumPlan, name: string, dbValue: string): string {
  const written: string = plan.members.get(name) ?? name;
  if (plan.storage !== 'converter') {
    return written;
  }
  const stored: string = plan.numeric
    ? dbValue
    : `"${dbValue.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$')}"`;
  return `${written}(${stored})`;
}

function renderEnumeration(plan: JpaEnumPlan, layout: JpaFileLayout): string {
  const constants: string[] = plan.enumeration.values.map(
    (value: { name: string; dbValue: string }): string =>
      constant(plan, value.name, value.dbValue)
  );
  const body: string[] = [];
  const stored: string = plan.numeric ? 'Int' : 'String';
  const header: string =
    plan.storage === 'converter'
      ? `enum class ${plan.typeName}(val value: ${stored})`
      : `enum class ${plan.typeName}`;
  if (constants.length === 0) {
    body.push(`${header} {`, '}');
  } else {
    body.push(
      `${header} {`,
      ...constants.map(
        (item: string, position: number): string =>
          `${INDENT}${item}${position === constants.length - 1 ? '' : ','}`
      ),
      '}'
    );
  }
  return fileText(layout, new Imports('jakarta'), body);
}

function renderConverter(
  plan: JpaEnumPlan,
  layout: JpaFileLayout,
  style: JpaStyle
): string {
  const imports: Imports = new Imports(style);
  const converter: string = imports.persistence('Converter');
  const base: string = imports.persistence('AttributeConverter');
  const stored: string = plan.numeric ? 'Int' : 'String';
  const type: string = plan.typeName;
  const body: string[] = [
    `@${converter}`,
    `class ${plan.converterName} : ${base}<${type}, ${stored}> {`,
    `${INDENT}override fun convertToDatabaseColumn(attribute: ${type}?): ${stored}? = attribute?.value`,
    '',
    `${INDENT}override fun convertToEntityAttribute(dbData: ${stored}?): ${type}? =`,
    `${INDENT}${INDENT}dbData?.let { stored ->`,
    `${INDENT}${INDENT}${INDENT}${type}.values().firstOrNull { it.value == stored }`,
    `${INDENT}${INDENT}${INDENT}${INDENT}?: throw IllegalArgumentException("Unknown ${type} value: $stored")`,
    `${INDENT}${INDENT}}`,
    '}',
  ];
  return fileText(layout, imports, body);
}

function renderKeyClass(
  name: string,
  parts: readonly JpaIdPart[],
  layout: JpaFileLayout,
  options: { embeddable: boolean; style: JpaStyle }
): string {
  const imports: Imports = new Imports(options.style);
  imports.use('java.io.Serializable');
  for (const part of parts) {
    imports.merge(part.imports);
  }
  const body: string[] = [];
  if (options.embeddable) {
    body.push(`@${imports.persistence('Embeddable')}`);
  }
  body.push(`data class ${name}(`);
  for (const part of parts) {
    body.push(
      ...annotationLines(part.annotations ?? [], INDENT.length),
      `${INDENT}var ${kotlinName(part.name)}: ${kotlinType(part.type)}? = null,`
    );
  }
  body.push(') : Serializable');
  return fileText(layout, imports, body);
}

/** The renderer of Kotlin files; `extended` holds the classes another entity extends, which Kotlin needs to be `open`. */
export function kotlinRenderer(extended: ReadonlySet<string>): JpaRenderer {
  return {
    extension: '.kt',
    entity: (plan: JpaModelPlan, layout: JpaFileLayout): string =>
      renderEntity(plan, layout, extended),
    enumeration: renderEnumeration,
    converter: renderConverter,
    keyClass: renderKeyClass,
  };
}

/**
 * Writes Kotlin entities: the same classes, tables and mapping as the JPA writer, with Kotlin syntax. A property is a
 * `var` with an initial value (the collections `mutableSetOf()`, a non-null property without one `lateinit`), so the
 * classes have the no-argument constructor JPA needs; Kotlin classes are final, so the project should apply the
 * `kotlin-jpa` and `kotlin-allopen` Gradle plugins (Spring Initializr does) for lazy proxies.
 */
export function emitKotlin(
  schema: Parameters<typeof emitJpa>[0],
  options: KotlinEmitOptions
): MultiFileEmitOutput {
  const extended: Set<string> = new Set<string>();
  const { adjust, lombok, ...rest } = options;
  const result: MultiFileEmitOutput = emitJpa(schema, {
    ...rest,
    extension: {
      renderer: kotlinRenderer(extended),
      adjust: (planned: JpaPlanned): Record<string, string> => {
        const added: Record<string, string> =
          adjust === undefined ? {} : adjust(planned);
        for (const plan of planned.plans) {
          if (plan.extendsClass !== undefined) {
            extended.add(plan.extendsClass);
          }
        }
        return added;
      },
    },
  });
  if (lombok === true) {
    result.warnings.push(
      'Lombok has no use in Kotlin, so --lombok was ignored; the properties are plain Kotlin properties.'
    );
  }
  return result;
}
