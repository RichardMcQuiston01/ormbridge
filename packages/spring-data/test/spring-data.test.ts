import { afterEach, describe, expect, it } from 'vitest';
import { emitJpa, type JpaEmitOptions } from '../../../src/emitters/jpa.js';
import { runCli } from '../../../src/cliRunner.js';
import { getFormat, unregisterFormat } from '../../../src/formats.js';
import type { IrSchema } from '../../../src/ir.js';
import { parseJpa } from '../../../src/parsers/jpa.js';
import { registerPlugin } from '../../../src/plugins.js';
import { expectOk } from '../../../test/helpers.js';
import { compareIr, formatDifference } from '../../../test/irCompare.js';
import { parseJpaExtra } from '../../../test/jpaSupport.js';
import { SUBJECTS } from '../../kotlin/test/subjects.js';
import { emitSpringData, emitSpringDataKotlin } from '../src/index.js';
import plugin from '../src/index.js';
import { parseKotlin } from '../../kotlin/src/index.js';

const OPTIONS: JpaEmitOptions = {
  provider: 'postgresql',
  naming: 'preserve',
  header: false,
};

function sorted(
  files: Record<string, string>
): { path: string; text: string }[] {
  return Object.entries(files)
    .sort(([first], [second]) => (first < second ? -1 : 1))
    .map(([path, text]) => ({ path, text }));
}

async function blog(): Promise<IrSchema> {
  return parseJpaExtra('many-to-many');
}

describe('emitSpringData', () => {
  it('writes the Spring auditing annotations in place of the Hibernate ones', async () => {
    const schema: IrSchema = await SUBJECTS[0]!.build();
    const files = emitSpringData(schema, OPTIONS).files;
    const account: string = files['app/models/Account.java'] ?? '';
    expect(account).toContain('@CreatedDate');
    expect(account).toContain('@LastModifiedDate');
    expect(account).toContain(
      'import org.springframework.data.annotation.CreatedDate;'
    );
    expect(account).toContain('@EntityListeners(AuditingEntityListener.class)');
    expect(account).toContain('import jakarta.persistence.EntityListeners;');
    expect(account).not.toContain('CreationTimestamp');
    expect(account).not.toContain('UpdateTimestamp');
  });

  it('leaves an entity without timestamps alone', async () => {
    const schema: IrSchema = await blog();
    const plain: Record<string, string> = emitJpa(
      structuredClone(schema),
      OPTIONS
    ).files;
    const spring: Record<string, string> = emitSpringData(
      structuredClone(schema),
      OPTIONS
    ).files;
    for (const [path, text] of Object.entries(plain)) {
      expect(spring[path], path).toBe(text);
    }
  });

  it('writes a repository per entity with the type of its identifier', async () => {
    const schema: IrSchema = await SUBJECTS[0]!.build();
    const files = emitSpringData(schema, OPTIONS).files;
    expect(files['app/models/repository/SessionRepository.java']).toContain(
      'extends JpaRepository<Session, UUID>'
    );
    expect(files['app/models/repository/SessionRepository.java']).toContain(
      'import java.util.UUID;'
    );
    expect(files['app/models/repository/AccountRepository.java']).toMatch(
      /extends JpaRepository<Account, (Integer|Long)>/
    );
  });

  it('uses the key class as the identifier of a composite key', async () => {
    const schema: IrSchema = await SUBJECTS[2]!.build();
    const files = emitSpringData(schema, OPTIONS).files;
    const repository: string =
      Object.entries(files).find(([path]) =>
        path.endsWith('EnrollmentRepository.java')
      )?.[1] ?? '';
    expect(repository).toMatch(/import app\.models\.EnrollmentId;/);
  });

  it('writes the auditing configuration once, only when something is audited', async () => {
    const audited = emitSpringData(await SUBJECTS[0]!.build(), OPTIONS).files;
    expect(audited['app/models/JpaAuditingConfig.java']).toContain(
      '@EnableJpaAuditing'
    );
    const plain = emitSpringData(await blog(), OPTIONS).files;
    expect(plain['app/models/JpaAuditingConfig.java']).toBeUndefined();
  });

  it('follows the namespace, the style and the header', async () => {
    const files = emitSpringData(await SUBJECTS[0]!.build(), {
      ...OPTIONS,
      header: true,
      style: 'javax',
      packageName: 'com.example.shop',
    }).files;
    const repository: string =
      files['com/example/shop/repository/AccountRepository.java'] ?? '';
    expect(repository.startsWith('// <auto-generated>')).toBe(true);
    expect(repository).toContain('package com.example.shop.repository;');
    expect(files['com/example/shop/Account.java']).toContain(
      'import javax.persistence.EntityListeners;'
    );
  });
});

describe('emitSpringDataKotlin', () => {
  it('writes Kotlin entities, repositories and the auditing configuration', async () => {
    const files = emitSpringDataKotlin(
      await SUBJECTS[0]!.build(),
      OPTIONS
    ).files;
    expect(Object.keys(files).every((path) => path.endsWith('.kt'))).toBe(true);
    expect(files['app/models/Account.kt']).toContain(
      '@EntityListeners(AuditingEntityListener::class)'
    );
    expect(files['app/models/Account.kt']).toContain('@CreatedDate');
    expect(files['app/models/repository/SessionRepository.kt']).toContain(
      'interface SessionRepository : JpaRepository<Session, UUID>'
    );
    expect(files['app/models/JpaAuditingConfig.kt']).toContain(
      'class JpaAuditingConfig'
    );
  });
});

describe('reading Spring Data entities', () => {
  it.each(SUBJECTS.map((subject) => [subject.label, subject] as const))(
    'reads back the schema of the JPA output (%s)',
    async (_label, subject) => {
      const schema: IrSchema = await subject.build();
      const options: JpaEmitOptions = { ...OPTIONS, ...subject.options };
      const jpa: IrSchema = expectOk(
        await parseJpa(
          sorted(emitJpa(structuredClone(schema), options).files),
          { appLabel: 'app' }
        )
      );
      const java: IrSchema = expectOk(
        await parseJpa(
          sorted(emitSpringData(structuredClone(schema), options).files),
          { appLabel: 'app' }
        )
      );
      const kotlin: IrSchema = expectOk(
        await parseKotlin(
          sorted(emitSpringDataKotlin(structuredClone(schema), options).files),
          { appLabel: 'app' }
        )
      );
      // The audited timestamps are read as the same defaults and auto-updated columns as the Hibernate ones.
      expect(compareIr(jpa, java).map(formatDifference)).toEqual([]);
      expect(compareIr(jpa, kotlin).map(formatDifference)).toEqual([]);
    }
  );
});

describe('the plugin', () => {
  afterEach(() => {
    unregisterFormat('spring-data');
    unregisterFormat('spring-data-kotlin');
  });

  it('adds the spring-data and spring-data-kotlin formats', () => {
    expect(registerPlugin(plugin).ok).toBe(true);
    expect(getFormat('spring-data').ok).toBe(true);
    expect(getFormat('spring-data-kotlin').ok).toBe(true);
  });

  it('rejects a bad option the way the jpa format does', () => {
    registerPlugin(plugin);
    const adapter = expectOk(getFormat('spring-data'));
    const result = adapter.emit?.(
      { models: [], enums: [], warnings: [] },
      {
        naming: 'preserve',
        provider: 'postgresql',
        header: true,
        autoField: 'int',
        namespace: 'not a package',
      }
    );
    expect(result?.ok).toBe(false);
    if (result !== undefined && !result.ok) {
      expect(result.error.message).toContain('Invalid namespace');
    }
  });

  it('converts a directory of Kotlin entities with --from spring-data-kotlin', async () => {
    registerPlugin(plugin);
    let stdout: string = '';
    let stderr: string = '';
    const code: number = await runCli(
      [
        'convert',
        '-i',
        'packages/kotlin/test/fixtures/spring',
        '--from',
        'spring-data-kotlin',
        '--to',
        'prisma',
        '--no-config',
      ],
      {
        cwd: process.cwd(),
        stdout: (text: string): void => {
          stdout += text;
        },
        stderr: (text: string): void => {
          stderr += text;
        },
      }
    );
    expect(stderr).not.toContain('error');
    expect(code).toBe(0);
    expect(stdout).toContain('model PurchaseOrder');
  });
});
