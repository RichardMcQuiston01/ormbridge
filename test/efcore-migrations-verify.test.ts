import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { beforeAll, describe, expect, it } from 'vitest';
import type { IrSchema } from '../src/ir.js';
import { parseEfcore } from '../src/parsers/efcore.js';
import { probeDotnet } from './efcoreSupport.js';
import {
  compareWithModel,
  filesUpTo,
  MIGRATION_FIXTURES,
  readScenarios,
  runMigrationsTool,
  type MigrationScenarioOutput,
  type MigrationStep,
  type MigrationToolOutput,
  type Scenario,
} from './efcoreMigrationsSupport.js';
import { expectOk } from './helpers.js';
import { titleWithReason } from './realToolSupport.js';

/**
 * Replays migrations that the real Entity Framework Core 8 generates. `test/tools/efcore-migrations-verify` does
 * what `dotnet ef migrations add` does for several models, each with a few versions: it asks EF Core's model
 * differ for the operations between two versions and has the C# generator write the migration, its Designer file
 * and the model snapshot. The tests replay the first k migrations (with and without the snapshot, for every k) and
 * compare the schema with the description of the model of version k that EF Core itself gives (its relational
 * model): the tables, columns with nullability and type, the primary key, unique keys, indexes and foreign keys.
 *
 * Set EFCORE_DIR to a scratch directory (the NuGet cache and the home of the dotnet CLI go there; see
 * test/tools/setup-verification-tools.sh) and, when `dotnet` is not on the PATH, DOTNET to the dotnet executable.
 * The tests are skipped, with the reason in their title, when the .NET SDK is missing. UPDATE_MIGRATION_FIXTURES=1
 * also rewrites the generated migrations in test/fixtures/efcore-migrations/<scenario>/ that the unit tests read.
 */

const probe: ReturnType<typeof probeDotnet> = probeDotnet();
const scenarios: Scenario[] = readScenarios();
let output: MigrationToolOutput = {};

beforeAll(() => {
  if (!probe.available) {
    return;
  }
  output = runMigrationsTool(probe);
  if (process.env.UPDATE_MIGRATION_FIXTURES === '1') {
    writeFixtures(output);
  }
}, 960_000);

/** Writes the migrations of every scenario, and the Designer file and snapshot of its last version. */
function writeFixtures(tool: MigrationToolOutput): void {
  for (const scenario of scenarios) {
    const steps: MigrationStep[] = tool[scenario.name]?.steps ?? [];
    const directory: string = join(MIGRATION_FIXTURES, scenario.name);
    rmSync(directory, { recursive: true, force: true });
    steps.forEach((step: MigrationStep, index: number) => {
      for (const [path, text] of Object.entries(step.files)) {
        const isLast: boolean = index === steps.length - 1;
        const keep: boolean =
          path.endsWith('ModelSnapshot.cs') || path.endsWith('.Designer.cs')
            ? isLast
            : true;
        if (keep) {
          mkdirSync(dirname(join(directory, path)), { recursive: true });
          writeFileSync(join(directory, path), text);
        }
      }
    });
  }
}

function result(name: string): MigrationScenarioOutput {
  const found: MigrationScenarioOutput | undefined = output[name];
  expect(found, `no output for the scenario ${name}`).toBeDefined();
  if (found?.__error !== undefined) {
    throw new Error(`EF Core rejected the scenario ${name}: ${found.__error}`);
  }
  return found ?? {};
}

describe(titleWithReason('efcore migrations: real EF Core', probe), () => {
  for (const scenario of scenarios) {
    describe(scenario.name, () => {
      it.skipIf(!probe.available)(
        'is generated by EF Core, one migration per version',
        () => {
          const steps: MigrationStep[] = result(scenario.name).steps ?? [];
          expect(steps).toHaveLength(scenario.contexts.length);
          for (const step of steps) {
            expect(
              Object.keys(step.files).filter(
                (path: string) =>
                  !path.endsWith('.Designer.cs') &&
                  !path.endsWith('ModelSnapshot.cs')
              )
            ).toHaveLength(1);
          }
        }
      );

      for (const [index] of scenario.contexts.entries()) {
        const count: number = index + 1;
        for (const withSnapshot of [true, false]) {
          it.skipIf(!probe.available)(
            `replaying the first ${count} migration${count === 1 ? '' : 's'} ${withSnapshot ? 'with' : 'without'} the model snapshot gives EF Core's model`,
            async () => {
              const steps: MigrationStep[] = result(scenario.name).steps ?? [];
              const schema: IrSchema = expectOk(
                await parseEfcore(filesUpTo(steps, count, withSnapshot), {
                  appLabel: 'app',
                })
              );
              expect(
                compareWithModel(schema, steps[index]?.model.tables ?? [])
              ).toEqual([]);
              // The migrations and the snapshot come from one model, so the snapshot must always agree.
              expect(
                schema.warnings.filter((warning: string) =>
                  /does not agree/.test(warning)
                )
              ).toEqual([]);
            }
          );
        }
      }
    });
  }
});
