describe('the neomodel format', () => {
  it('is registered as write only and claims no file extension', () => {
    const adapter = expectOk(getFormat('neomodel'));
    expect(adapter.parse).toBeUndefined();
    expect(adapter.emit).toBeDefined();
    expect(adapter.extensions).toEqual([]);
  });

  it('cannot be used as an input', async () => {
    const result = await convertText(loadCanonicalSources('prisma'), {
      ...DEFAULT_OPTIONS,
      from: 'neomodel',
      to: 'prisma',
    });
    expect(result.ok).toBe(false);
    if (!result.ok) {
      expect(result.error.code).toBe('UNSUPPORTED_CONVERSION');
      expect(result.error.message).toContain('can only be used as an output');
    }
  });

  it('writes one module, importable from neomodel', async () => {
    const result = await convertCanonicalPrisma();
    expect(result.files).toBeUndefined();
    expect(result.output).toMatch(/^# Generated by ormbridge\./);
    expect(result.output).toContain('from neomodel import (');
    expect(result.output).toContain('class Post(StructuredNode):');
  });

  it('is deterministic', async () => {
    const first: ConvertResult = await convertCanonicalPrisma();
    const second: ConvertResult = await convertCanonicalPrisma();
    expect(second.output).toBe(first.output);
    expect(second.warnings).toEqual(first.warnings);
  });

  it('writes nothing for an empty schema', () => {
    expect(emit(schemaOf([])).text).toBe('');
  });

  it('can leave the header out', () => {
    const { text } = emit(keysSchema(), { header: false });
    expect(text.startsWith('from neomodel import')).toBe(true);
    expect(text).not.toContain('Generated by ormbridge');
  });
});

describe('names', () => {
  it('writes snake_case attributes and repairs the names neomodel or Python reserve', () => {
    expect(attributeNameOf('createdAt')).toBe('created_at');
    expect(attributeNameOf('id')).toBe('id_');
    expect(attributeNameOf('element_id')).toBe('element_id_');
    expect(attributeNameOf('save')).toBe('save_');
    expect(attributeNameOf('class')).toBe('class_');
    expect(attributeNameOf('2fast')).toBe('_2fast');
    expect(attributeNameOf('???')).toBe('value');
    expect(classNameOf('Order')).toBe('Order');
    expect(classNameOf('3D')).toBe('_3D');
    expect(pyString('a "b"\n')).toBe('"a \\"b\\"\\n"');
  });

  it('keeps the stored name with db_property when the attribute differs', () => {
    const schema: IrSchema = schemaOf([
      model('Thing', {
        fields: [
          idField(),
          field('createdAt', { type: 'dateTime', isNullable: true }),
          field('class', { isNullable: true }),
          field('plain_name', { isNullable: true }),
        ],
      }),
    ]);
    const { text } = emit(schema);
    expect(text).toContain(
      'id_ = IntegerProperty(unique_index=True, required=True, db_property="id")'
    );
    expect(text).toContain(
      'created_at = DateTimeProperty(db_property="createdAt")'
    );
    expect(text).toContain('class_ = StringProperty(db_property="class")');
    expect(text).toContain('plain_name = StringProperty()');
  });

  it('renames a class that would hide an import and keeps the label', () => {
    const schema: IrSchema = schemaOf([
      model('StructuredNode', { fields: [idField()] }),
      model('One', { fields: [idField()] }),
    ]);
    const { text, warnings } = emit(schema);
    expect(text).toContain('class StructuredNodeNode(StructuredNode):');
    expect(text).toContain('__label__ = "StructuredNode"');
    expect(text).toContain('class OneNode(StructuredNode):');
    expect(warnings.join('\n')).toContain(
      'One: the class is named OneNode because One is a name the module uses or another class has; the label One is kept with __label__.'
    );
  });

  it('numbers an attribute that is taken and says so', () => {
    const schema: IrSchema = schemaOf([
      model('Thing', {
        fields: [
          idField(),
          field('first_name', { isNullable: true }),
          field('firstName', { columnName: 'firstName', isNullable: true }),
        ],
      }),
    ]);
    const { text, warnings } = emit(schema);
    expect(text).toContain('first_name = StringProperty()');
    expect(text).toContain(
      'first_name_2 = StringProperty(db_property="firstName")'
    );
    expect(warnings.join('\n')).toContain(
      'Thing.firstName: "first_name" is taken, so the attribute was named "first_name_2" (stored as "firstName").'
    );
  });
});

