describe('agreement with the Cypher writer', () => {
  it('uses the labels and relationship types of the graph model', async () => {
    const schema: IrSchema = await parseSource(
      EXTRA_SOURCES[0] as VerifySource
    );
    const graph = buildGraph(schema, { camelFields: false }, []);
    const edges = collectEdges(schema, graph, []);
    const { text } = emit(schema);
    for (const node of graph.nodes) {
      expect(
        text.includes(`class ${node.label}(StructuredNode):`) ||
          text.includes(`__label__ = "${node.label}"`),
        node.label
      ).toBe(true);
    }
    for (const edge of edges) {
      expect(text).toContain(`"${edge.type}"`);
    }
  });

  it('passes the structural check for the join and key fixtures', () => {
    for (const schema of [joinsSchema(), keysSchema()]) {
      expect(
        checkNeomodelOutput(schema, { neomodel: emit(schema).text })
      ).toEqual([]);
    }
  });

  it('fails the structural and the verification helpers when the output is wrong', () => {
    const schema: IrSchema = joinsSchema();
    expect(
      checkNeomodelOutput(schema, {
        neomodel: 'class Other(StructuredNode):\n    pass\n',
      }).length
    ).toBeGreaterThan(3);
    const graph = buildGraph(schema, { camelFields: false }, []);
    const edges = collectEdges(schema, graph, []);
    const empty: SchemaReport = {
      classes: {},
      relationshipClasses: {},
      constraints: [],
      indexes: [],
      version: '',
    };
    expect(compareCatalogWithSchema(graph, empty).length).toBeGreaterThan(0);
    expect(compareRelationships(graph, edges, empty).length).toBeGreaterThan(0);
    expect(compareProperties(graph, empty)).toEqual([]);
  });
});

