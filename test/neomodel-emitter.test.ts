function emit(
  schema: IrSchema,
  options: Partial<Parameters<typeof emitNeomodel>[1]> = {}
): { text: string; warnings: string[] } {
  const output = emitNeomodel(schema, { camelFields: false, ...options });
  return { text: output.text, warnings: output.warnings };
}

async function convertCanonicalPrisma(
  overrides: Partial<Parameters<typeof convertText>[1]> = {}
): Promise<ConvertResult> {
  return expectOk(
    await convertText(loadCanonicalSources('prisma'), {
      ...DEFAULT_OPTIONS,
      from: 'prisma',
      to: 'neomodel',
      ...overrides,
    })
  );
}

/** True when `python3` can parse the text (a syntax check; nothing is imported). */
function pythonParses(text: string): string | undefined {
  const directory: string = mkdtempSync(join(tmpdir(), 'ormbridge-py-'));
  try {
    const file: string = join(directory, 'models.py');
    writeFileSync(file, text);
    const run = spawnSync(
      'python3',
      ['-c', 'import ast, sys; ast.parse(open(sys.argv[1]).read())', file],
      { encoding: 'utf8' }
    );
    if (run.error !== undefined) {
      return undefined;
    }
    return run.status === 0 ? '' : run.stderr;
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}

