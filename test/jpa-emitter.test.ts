describe('jpa emitter: layout and options', () => {
  const schema: IrSchema = schemaOf(
    [
      model('User', { tableName: 'auth_user' }),
      model('Post', {
        tableName: 'blog_post',
        fields: [idField(), field('title', { maxLength: 100 })],
        relations: [relation('author', 'User', { relatedName: 'posts' })],
      }),
    ],
    [{ name: 'Mode', values: [{ name: 'A', dbValue: 'A' }] }]
  );

  it('writes a class per model and a file per enum, in the package folder', () => {
    const output: MultiFileEmitOutput = emit(schema);
    expect(Object.keys(output.files).sort()).toEqual([
      'app/models/Mode.java',
      'app/models/Post.java',
      'app/models/User.java',
    ]);
    expect(output.warnings).toEqual([]);
    const post: string = fileText(output, 'Post');
    expect(post).toContain('package app.models;');
    expect(post).toContain('import jakarta.persistence.Entity;');
    expect(post).toContain('@Entity\n@Table(name = "blog_post")');
    expect(post).toContain('public class Post {');
    const user: string = fileText(output, 'User');
    expect(user).toContain('@OneToMany(mappedBy = "author")');
    expect(user).toContain('private List<Post> posts = new ArrayList<>();');
  });

  it('writes no files for an empty schema', () => {
    expect(emit(schemaOf([])).files).toEqual({});
  });

  it('defaults to the jakarta style and writes javax imports for the javax style', () => {
    expect(emit(schema).files).toEqual(
      emit(schema, { style: 'jakarta' }).files
    );
    const javax: string = fileText(emit(schema, { style: 'javax' }), 'Post');
    expect(javax).toContain('import javax.persistence.Entity;');
    expect(javax).not.toContain('jakarta');
  });

  it('uses the package option for the declaration and the folder', () => {
    const output: MultiFileEmitOutput = emit(schema, {
      packageName: 'com.shop.data',
    });
    expect(Object.keys(output.files)).toContain('com/shop/data/Post.java');
    expect(output.files['com/shop/data/Post.java']).toContain(
      'package com.shop.data;'
    );
  });

  it('omits the auto-generated comment with header false', () => {
    expect(fileText(emit(schema), 'User')).toMatch(/^\/\/ <auto-generated>/);
    expect(fileText(emit(schema, { header: false }), 'User')).toMatch(
      /^package /
    );
  });

  it('validates styles and packages', () => {
    expect(JPA_STYLES).toEqual(['jakarta', 'javax']);
    expect(isJpaStyle('javax')).toBe(true);
    expect(isJpaStyle('fluent')).toBe(false);
    expect(DEFAULT_JPA_PACKAGE).toBe('app.models');
    expect(isValidJavaPackage('com.example.app_1')).toBe(true);
    for (const bad of ['', 'a..b', '1a', 'a.class', 'a-b', 'a.b.']) {
      expect(isValidJavaPackage(bad), bad).toBe(false);
    }
    const bad = checkStyle('jpa', 'fluent');
    expect(bad.ok).toBe(false);
    expect(!bad.ok && bad.error.message).toBe(
      'Invalid --style value "fluent" for the jpa format. Expected one of: jakarta, javax.'
    );
    expect(OUTPUT_STYLES).toContain('jakarta');
  });

  it('reports an unknown style and an invalid package through the adapter', () => {
    const adapter = expectOk(getFormat('jpa'));
    const options = { ...DEFAULT_OPTIONS };
    const badStyle = adapter.emit?.(schema, {
      ...options,
      style: 'annotations',
    });
    expect(badStyle?.ok).toBe(false);
    expect(!badStyle?.ok && badStyle?.error.message).toContain(
      'Expected one of: jakarta, javax.'
    );
    const badPackage = adapter.emit?.(schema, {
      ...options,
      namespace: 'App.Models.',
    });
    expect(badPackage?.ok).toBe(true);
    const keyword = adapter.emit?.(schema, { ...options, namespace: 'a.new' });
    expect(keyword?.ok).toBe(false);
    expect(!keyword?.ok && keyword?.error.message).toContain(
      'Java package name'
    );
  });
});

describe('jpa emitter: columns', () => {
  it('maps every scalar type and uses boxed types for nullable columns', () => {
    const output: MultiFileEmitOutput = emit(
      single([
        idField(),
        field('a', { type: 'int' }),
        field('b', { type: 'int', isNullable: true }),
        field('c', { type: 'bigInt' }),
        field('d', { type: 'float' }),
        field('e', { type: 'boolean' }),
        field('f', { type: 'decimal', maxDigits: 10, decimalPlaces: 2 }),
        field('g', { type: 'date' }),
        field('h', { type: 'time' }),
        field('i', { type: 'dateTime' }),
        field('j', { type: 'uuid' }),
        field('k', { type: 'bytes' }),
        field('l', { type: 'duration' }),
        field('m', { maxLength: 30 }),
      ])
    );
    const text: string = fileText(output, 'Thing');
    for (const line of [
      'private int a;',
      'private Integer b;',
      'private long c;',
      'private double d;',
      'private boolean e;',
      'private BigDecimal f;',
      'private LocalDate g;',
      'private LocalTime h;',
      'private LocalDateTime i;',
      'private UUID j;',
      'private byte[] k;',
      'private Duration l;',
      'private String m;',
      '@Column(name = "f", nullable = false, precision = 10, scale = 2)',
      '@Column(name = "m", nullable = false, length = 30)',
    ]) {
      expect(text, line).toContain(line);
    }
  });

  it('writes large text as a text column on PostgreSQL and @Lob elsewhere', () => {
    const schema: IrSchema = single([
      idField(),
      field('body', { type: 'text' }),
    ]);
    expect(fileText(emit(schema), 'Thing')).toContain(
      'columnDefinition = "text"'
    );
    const mysql: string = fileText(
      emit(schema, { provider: 'mysql' }),
      'Thing'
    );
    expect(mysql).toContain('@Lob');
    expect(mysql).not.toContain('columnDefinition');
  });

  it('maps JSON to @JdbcTypeCode on jakarta and to a String with a warning on javax', () => {
    const schema: IrSchema = single([
      idField(),
      field('meta', { type: 'json' }),
    ]);
    const jakarta: MultiFileEmitOutput = emit(schema);
    expect(fileText(jakarta, 'Thing')).toContain(
      '@JdbcTypeCode(SqlTypes.JSON)'
    );
    expect(fileText(jakarta, 'Thing')).toContain('Map<String, Object> meta;');
    const javax: MultiFileEmitOutput = emit(schema, { style: 'javax' });
    expect(fileText(javax, 'Thing')).toContain('columnDefinition = "jsonb"');
    expect(javax.warnings.join('\n')).toContain('Thing.meta: Hibernate 5');
  });

  it('writes arrays as Java arrays on PostgreSQL and warns elsewhere', () => {
    const schema: IrSchema = single([
      idField(),
      field('tags', { maxLength: 20, arrayDepth: 1 }),
    ]);
    expect(fileText(emit(schema), 'Thing')).toContain('String[] tags');
    const sqlite: MultiFileEmitOutput = emit(schema, { provider: 'sqlite' });
    expect(fileText(sqlite, 'Thing')).toContain('List<String> tags');
    expect(sqlite.warnings.join('\n')).toContain('Thing.tags:');
  });

  it('names a column that is not a Java identifier and keeps the column name', () => {
    const output: MultiFileEmitOutput = emit(
      single([
        idField(),
        field('class', { columnName: 'class' }),
        field('view_count', { type: 'int' }),
      ])
    );
    const text: string = fileText(output, 'Thing');
    expect(text).toContain('private String class_;');
    expect(text).toContain('@Column(name = "class", nullable = false');
    expect(text).toContain('@Column(name = "view_count", nullable = false)');
    expect(text).toContain('private int viewCount;');
  });

  it('warns for types and features JPA cannot express', () => {
    const output: MultiFileEmitOutput = emit(
      single([
        idField(),
        field('h', { type: 'hstore' }),
        field('r', { type: 'range', rangeOf: 'int' }),
        field('u', { type: 'unsupported', unsupportedType: 'circle' }),
        field('t', { type: 'int', isAutoUpdated: true }),
      ])
    );
    const warnings: string = output.warnings.join('\n');
    expect(warnings).toContain('Thing.h: Hibernate has no hstore mapping');
    expect(warnings).toContain('Thing.r: Hibernate has no range mapping');
    expect(warnings).toContain('Thing.u: the database type "circle"');
    expect(warnings).toContain('Thing.t: Hibernate can refresh a date-time');
    expect(fileText(output, 'Thing')).toContain('columnDefinition = "circle"');
  });
});

describe('jpa emitter: defaults and generated values', () => {
  it('writes a literal default as @ColumnDefault and as the initializer', () => {
    const text: string = fileText(
      emit(
        single([
          idField(),
          field('n', { type: 'int', default: { kind: 'literal', value: 3 } }),
          field('s', {
            default: { kind: 'literal', value: "it's" },
            maxLength: 9,
          }),
          field('b', {
            type: 'boolean',
            default: { kind: 'literal', value: false },
          }),
        ])
      ),
      'Thing'
    );
    expect(text).toContain('@ColumnDefault("3")\n  private int n = 3;');
    expect(text).toContain("@ColumnDefault(\"'it''s'\")");
    expect(text).toContain('private String s = "it\'s";');
    expect(text).toContain('private boolean b = false;');
    expect(text).not.toContain('@DynamicInsert');
  });

  it('uses the SQL of the provider for booleans and expressions', () => {
    const schema: IrSchema = single([
      idField(),
      field('b', {
        type: 'boolean',
        default: { kind: 'literal', value: true },
      }),
      field('e', {
        type: 'dateTime',
        default: { kind: 'dbExpression', expression: "datetime('now')" },
      }),
    ]);
    const mysql: string = fileText(
      emit(schema, { provider: 'mysql' }),
      'Thing'
    );
    expect(mysql).toContain('@ColumnDefault("1")');
    expect(mysql).toContain('@ColumnDefault("(datetime(\'now\'))")');
    expect(fileText(emit(schema), 'Thing')).toContain('@ColumnDefault("true")');
  });

  it('leaves a database expression to the database with @DynamicInsert', () => {
    const output: MultiFileEmitOutput = emit(
      single([
        idField(),
        field('e', {
          type: 'dateTime',
          default: { kind: 'dbExpression', expression: 'now()' },
        }),
      ])
    );
    expect(fileText(output, 'Thing')).toContain('@DynamicInsert');
  });

  it('writes now defaults, creation and update timestamps', () => {
    const text: string = fileText(
      emit(
        single([
          idField(),
          field('created_at', { type: 'dateTime', default: { kind: 'now' } }),
          field('seen_at', { type: 'dateTime', default: { kind: 'now' } }),
          field('updated_at', { type: 'dateTime', isAutoUpdated: true }),
        ])
      ),
      'Thing'
    );
    expect(text).toContain('@CreationTimestamp');
    expect(text).toContain('@UpdateTimestamp');
    expect(text).toContain(
      'private LocalDateTime seenAt = LocalDateTime.now();'
    );
    expect(text.match(/@CreationTimestamp/g)).toHaveLength(1);
  });

  it('generates identity keys and UUID keys, with the generator of Hibernate 5', () => {
    const schema: IrSchema = schemaOf([
      model('A', { tableName: 'a' }),
      model('B', {
        tableName: 'b',
        fields: [
          field('id', {
            type: 'uuid',
            isPrimaryKey: true,
            default: { kind: 'uuid' },
          }),
        ],
      }),
    ]);
    const jakarta: MultiFileEmitOutput = emit(schema);
    expect(fileText(jakarta, 'A')).toContain(
      '@GeneratedValue(strategy = GenerationType.IDENTITY)'
    );
    expect(fileText(jakarta, 'B')).toContain(
      '@GeneratedValue(strategy = GenerationType.UUID)'
    );
    const javax: string = fileText(emit(schema, { style: 'javax' }), 'B');
    expect(javax).toContain('@GeneratedValue(generator = "uuid2")');
    expect(javax).toContain(
      '@GenericGenerator(name = "uuid2", strategy = "uuid2")'
    );
  });

  it('uses @UuidGenerator for a UUID column that is not the key', () => {
    const text: string = fileText(
      emit(
        single([
          idField(),
          field('public_id', { type: 'uuid', default: { kind: 'uuid' } }),
        ])
      ),
      'Thing'
    );
    expect(text).toContain('@UuidGenerator');
  });

  it('warns about Prisma client defaults and about auto-increment outside the key', () => {
    const output: MultiFileEmitOutput = emit(
      single([
        idField(),
        field('c', { default: { kind: 'clientGenerated', generator: 'cuid' } }),
        field('n', { type: 'int', default: { kind: 'autoIncrement' } }),
      ])
    );
    const warnings: string = output.warnings.join('\n');
    expect(warnings).toContain(
      'Thing.c: the cuid() default is generated by Prisma Client'
    );
    expect(warnings).toContain('Thing.n: JPA generates identifiers only');
  });

  it('writes a generated column on jakarta only', () => {
    const schema: IrSchema = single([
      idField(),
      field('a', { type: 'int' }),
      field('b', {
        type: 'int',
        generated: { expression: 'a * 2', isStored: true },
      }),
    ]);
    const jakarta: string = fileText(emit(schema), 'Thing');
    expect(jakarta).toContain('@GeneratedColumn("a * 2")');
    expect(jakarta).toContain('insertable = false, updatable = false');
    const javax: MultiFileEmitOutput = emit(schema, { style: 'javax' });
    expect(fileText(javax, 'Thing')).not.toContain('GeneratedColumn');
    expect(javax.warnings.join('\n')).toContain('Thing.b: Hibernate 5');
  });
});

describe('jpa emitter: enums', () => {
  const enumSchema = (values: IrEnum['values'], fieldType: 'string' | 'int') =>
    schemaOf(
      [
        model('Thing', {
          tableName: 'things',
          fields: [
            idField(),
            field('status', {
              type: fieldType,
              enumName: 'Status',
              ...(fieldType === 'string' ? { maxLength: 12 } : {}),
              default: { kind: 'enumValue', value: 'DRAFT' },
            }),
          ],
        }),
      ],
      [{ name: 'Status', values }]
    );

  it('stores constants by name with @Enumerated(STRING) when the values match', () => {
    const output: MultiFileEmitOutput = emit(
      enumSchema(
        [
          { name: 'DRAFT', dbValue: 'DRAFT' },
          { name: 'LIVE', dbValue: 'LIVE' },
        ],
        'string'
      )
    );
    expect(fileText(output, 'Thing')).toContain('@Enumerated(EnumType.STRING)');
    expect(fileText(output, 'Thing')).toContain(
      '@Column(name = "status", nullable = false, length = 12)'
    );
    expect(fileText(output, 'Thing')).toContain('@ColumnDefault("\'DRAFT\'")');
    expect(fileText(output, 'Thing')).toContain(
      'private Status status = Status.DRAFT;'
    );
    expect(fileText(output, 'Status')).toContain(
      'public enum Status {\n  DRAFT,\n  LIVE\n}'
    );
  });

  it('writes an AttributeConverter when the stored values differ from the names', () => {
    const output: MultiFileEmitOutput = emit(
      enumSchema(STATUS.values, 'string')
    );
    expect(Object.keys(output.files)).toContain(
      'app/models/StatusConverter.java'
    );
    expect(fileText(output, 'Thing')).toContain(
      '@Convert(converter = StatusConverter.class)'
    );
    expect(fileText(output, 'Status')).toContain('DRAFT("draft"),');
    const converter: string = fileText(output, 'StatusConverter');
    expect(converter).toContain('@Converter');
    expect(converter).toContain(
      'implements AttributeConverter<Status, String>'
    );
  });

  it('uses the ordinal for numbers that are positions and a converter for other numbers', () => {
    const ordinal: MultiFileEmitOutput = emit(
      enumSchema(
        [
          { name: 'DRAFT', dbValue: '0' },
          { name: 'LIVE', dbValue: '1' },
        ],
        'int'
      )
    );
    expect(fileText(ordinal, 'Thing')).toContain(
      '@Enumerated(EnumType.ORDINAL)'
    );
    const other: MultiFileEmitOutput = emit(
      enumSchema(
        [
          { name: 'DRAFT', dbValue: '10' },
          { name: 'LIVE', dbValue: '20' },
        ],
        'int'
      )
    );
    expect(fileText(other, 'StatusConverter')).toContain(
      'AttributeConverter<Status, Integer>'
    );
    expect(fileText(other, 'Status')).toContain('DRAFT(10)');
  });

  it('renames members and classes that are Java keywords or imported types', () => {
    const output: MultiFileEmitOutput = emit(
      schemaOf(
        [model('Table', { tableName: 't' })],
        [{ name: 'E', values: [{ name: 'new', dbValue: 'new' }] }]
      )
    );
    expect(Object.keys(output.files)).toContain('app/models/TableEntity.java');
    expect(fileText(output, 'E')).toContain('new_');
    expect(output.warnings.join('\n')).toContain(
      'so the class was named "TableEntity"'
    );
  });
});

describe('jpa emitter: keys, relations and indexes', () => {
  it('writes a composite key as @IdClass with the relation as an id', () => {
    const output: MultiFileEmitOutput = emit(
      schemaOf([
        model('Order', { tableName: 'orders' }),
        model('Line', {
          tableName: 'lines',
          fields: [field('no', { type: 'int' })],
          relations: [relation('order', 'Order')],
          compositePrimaryKey: ['order', 'no'],
        }),
      ])
    );
    const line: string = fileText(output, 'Line');
    expect(line).toContain('@IdClass(LineId.class)');
    expect(line).toContain('@Id\n  @ManyToOne');
    const id: string = fileText(output, 'LineId');
    expect(id).toContain('implements Serializable');
    expect(id).toContain('private Integer order;');
    expect(id).toContain('private Integer no;');
    expect(id).toContain(
      'Objects.equals(order, that.order) && Objects.equals(no, that.no)'
    );
  });

  it('writes join columns, delete actions and constraint names on the owning side', () => {
    const schema: IrSchema = schemaOf([
      model('User', { tableName: 'users' }),
      model('Post', {
        tableName: 'posts',
        relations: [
          relation('author', 'User', {
            onDelete: 'cascade',
            constraintName: 'fk_author',
            relatedName: 'posts',
          }),
          relation('editor', 'User', { isNullable: true, onDelete: 'setNull' }),
        ],
      }),
    ]);
    const jakarta: string = fileText(emit(schema), 'Post');
    expect(jakarta).toContain(
      '@JoinColumn(\n      name = "author_id",\n      referencedColumnName = "id",\n      nullable = false,\n      foreignKey = @ForeignKey(name = "fk_author"))'
    );
    expect(jakarta).toContain('@OnDelete(action = OnDeleteAction.CASCADE)');
    expect(jakarta).toContain('@OnDelete(action = OnDeleteAction.SET_NULL)');
    expect(jakarta).toContain(
      '@ManyToOne(optional = false, fetch = FetchType.LAZY)'
    );
    const javax: MultiFileEmitOutput = emit(schema, { style: 'javax' });
    expect(fileText(javax, 'Post')).not.toContain('SET_NULL');
    expect(javax.warnings.join('\n')).toContain(
      'Post.editor: Hibernate 5 knows only ON DELETE CASCADE'
    );
  });

  it('writes a many-to-many with a join table and an inverse side', () => {
    const output: MultiFileEmitOutput = emit(
      schemaOf([
        model('Tag', { tableName: 'tags' }),
        model('Post', {
          tableName: 'posts',
          relations: [
            relation('tags', 'Tag', {
              kind: 'manyToMany',
              relatedName: 'posts',
            }),
          ],
        }),
      ])
    );
    const post: string = fileText(output, 'Post');
    expect(post).toContain('@ManyToMany');
    expect(post).toContain('name = "posts_tags"');
    expect(post).toContain(
      'joinColumns = @JoinColumn(name = "post_id", referencedColumnName = "id")'
    );
    expect(post).toContain('private Set<Tag> tags = new HashSet<>();');
    expect(fileText(output, 'Tag')).toContain('@ManyToMany(mappedBy = "tags")');
  });

  it('writes a composite foreign key with @JoinColumns', () => {
    const output: MultiFileEmitOutput = emit(
      schemaOf([
        model('Ship', {
          tableName: 'ships',
          fields: [field('a', { type: 'int' }), field('b', { type: 'int' })],
          compositePrimaryKey: ['a', 'b'],
        }),
        model('Parcel', {
          tableName: 'parcels',
          fields: [
            idField(),
            field('ship_a', { type: 'int' }),
            field('ship_b', { type: 'int' }),
          ],
          compositeForeignKeys: [
            {
              name: 'ship',
              targetModel: 'Ship',
              fields: ['ship_a', 'ship_b'],
              references: ['a', 'b'],
              kind: 'foreignKey',
              isNullable: false,
              onDelete: 'cascade',
            },
          ],
        }),
      ])
    );
    const parcel: string = fileText(output, 'Parcel');
    expect(parcel).toContain('@JoinColumns({');
    expect(parcel).toContain('@JoinColumns({\n    @JoinColumn(');
    expect(parcel).toContain('insertable = false');
    expect(output.warnings).toEqual([]);
  });

  it('writes unique constraints, indexes and a schema in @Table', () => {
    const text: string = fileText(
      emit(
        single(
          [
            idField(),
            field('a', { type: 'int' }),
            field('b', { type: 'int' }),
            field('code', { maxLength: 10, isUnique: true }),
          ],
          {
            schema: 'audit',
            indexes: [
              index(['a', 'b'], { isUnique: true, name: 'a_b' }),
              index(['a', 'b'], { fieldOptions: { b: { sort: 'desc' } } }),
            ],
          }
        )
      ),
      'Thing'
    );
    expect(text).toContain('schema = "audit"');
    expect(text).toContain(
      '@UniqueConstraint(name = "a_b", columnNames = {"a", "b"})'
    );
    expect(text).toContain('@Index(columnList = "a, b DESC")');
    expect(text).toContain('unique = true');
  });

  it('chooses an identifier for a model without a key and says so', () => {
    const output: MultiFileEmitOutput = emit(
      schemaOf([
        model('Log', {
          tableName: 'logs',
          fields: [
            field('text', { type: 'text' }),
            field('n', { type: 'int' }),
          ],
        }),
      ])
    );
    expect(fileText(output, 'Log')).toContain('@Id\n  @Column(name = "n")');
    expect(output.warnings.join('\n')).toContain(
      'Log: the table has no primary key'
    );
  });
});

describe('jpa emitter: reading the output back', () => {
  it('is read back by the JPA reader without warnings', async () => {
    const schema: IrSchema = schemaOf(
      [
        model('User', {
          tableName: 'users',
          fields: [idField(), field('name', { maxLength: 20, isUnique: true })],
        }),
        model('Post', {
          tableName: 'posts',
          fields: [
            idField(),
            field('status', {
              enumName: 'Status',
              maxLength: 10,
              default: { kind: 'enumValue', value: 'DRAFT' },
            }),
          ],
          relations: [relation('author', 'User', { relatedName: 'posts' })],
        }),
      ],
      [STATUS]
    );
    for (const style of JPA_STYLES) {
      const output: MultiFileEmitOutput = emit(schema, { style });
      const reread: IrSchema = expectOk(
        await parseJpa(
          Object.entries(output.files).map(([path, text]) => ({ path, text })),
          { appLabel: 'app' }
        )
      );
      expect(reread.warnings, style).toEqual([]);
      expect(reread.models.map((item) => item.name).sort()).toEqual([
        'Post',
        'User',
      ]);
      expect(reread.enums[0]?.values.map((value) => value.dbValue)).toEqual([
        'draft',
        'live',
      ]);
    }
  });

  it('converts through convertText in both styles', async () => {
    for (const style of JPA_STYLES) {
      const result: ConvertResult = expectOk(
        await convertText(loadCanonicalSources('prisma'), {
          ...DEFAULT_OPTIONS,
          from: 'prisma',
          to: 'jpa',
          style,
        })
      );
      expect(result.output).toBe('');
      const files: string[] = Object.keys(result.files ?? {});
      expect(files).toContain('app/models/Post.java');
      expect(files).toContain('app/models/PostStatusConverter.java');
    }
  });
});
