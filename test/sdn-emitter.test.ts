describe('sdn emitter: golden files', () => {
  const goldenRoot: string = fileURLToPath(
    new URL('./golden-extras/', import.meta.url)
  );
  const fixtures: [string, () => Promise<IrSchema>][] = [
    ['kitchen-sink', () => Promise.resolve(kitchenSinkSchema())],
    ['stress', () => Promise.resolve(stressSchema())],
    ['constructs', () => Promise.resolve(constructsSchema())],
    ['keys-and-types', () => Promise.resolve(keysSchema())],
    ['joins', () => Promise.resolve(joinsSchema())],
    ...EXTRA_SOURCES.map(
      (source: VerifySource): [string, () => Promise<IrSchema>] => [
        source.label,
        () => parseSource(source),
      ]
    ),
  ];
  describe.each(fixtures)('%s fixture', (label, build) => {
    it('matches the golden files and warnings in both naming modes', async () => {
      const schema: IrSchema = await build();
      const files: Record<string, string> = {};
      for (const naming of ['preserve', 'normalize'] as NamingMode[]) {
        const camelFields: boolean = naming === 'normalize';
        const output = emit(
          camelFields ? normalizeSchema(structuredClone(schema)) : schema,
          { camelFields }
        );
        for (const [path, text] of Object.entries(output.files)) {
          files[`${naming}/${path}`] = text;
        }
        files[`${naming}.warnings.txt`] = `${output.warnings.join('\n')}\n`;
      }
      expectFilesMatchGolden(`sdn-fixtures/${label}`, files, goldenRoot);
    });
  });
});
