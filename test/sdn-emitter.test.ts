function emit(
  schema: IrSchema,
  options: Partial<Parameters<typeof emitSdn>[1]> = {}
): MultiFileEmitOutput {
  return emitSdn(structuredClone(schema), { camelFields: false, ...options });
}

function file(output: MultiFileEmitOutput, name: string): string {
  const found: string | undefined = output.files[`app/models/${name}.java`];
  if (found === undefined) {
    throw new Error(
      `No ${name}.java in ${Object.keys(output.files).join(', ')}`
    );
  }
  return found;
}

async function convertCanonicalPrisma(
  overrides: Partial<Parameters<typeof convertText>[1]> = {}
): Promise<ConvertResult> {
  return expectOk(
    await convertText(loadCanonicalSources('prisma'), {
      ...DEFAULT_OPTIONS,
      from: 'prisma',
      to: 'sdn',
      ...overrides,
    })
  );
}

describe('the sdn format', () => {
  it('is registered as write only and claims no file extension', () => {
    const adapter = expectOk(getFormat('sdn'));
    expect(adapter.parse).toBeUndefined();
    expect(adapter.emit).toBeDefined();
    expect(adapter.extensions).toEqual([]);
  });

  it('cannot be used as an input', async () => {
    const result = await convertText(loadCanonicalSources('prisma'), {
      ...DEFAULT_OPTIONS,
      from: 'sdn',
      to: 'prisma',
    });
    expect(result.ok).toBe(false);
    if (!result.ok) {
      expect(result.error.code).toBe('UNSUPPORTED_CONVERSION');
    }
  });

  it('writes one file per class, enum and converter below the package folders', async () => {
    const result = await convertCanonicalPrisma();
    expect(Object.keys(result.files ?? {}).sort()).toEqual([
      'app/models/Category.java',
      'app/models/Post.java',
      'app/models/PostStatus.java',
      'app/models/PostStatusConverter.java',
      'app/models/Profile.java',
      'app/models/Tag.java',
      'app/models/User.java',
    ]);
  });

  it('uses the namespace as the Java package and rejects a bad one', async () => {
    const result = await convertCanonicalPrisma({
      namespace: 'com.acme.graph',
    });
    expect(Object.keys(result.files ?? {})[0]).toMatch(/^com\/acme\/graph\//);
    expect(Object.values(result.files ?? {})[0]).toContain(
      'package com.acme.graph;'
    );
    const bad = await convertText(loadCanonicalSources('prisma'), {
      ...DEFAULT_OPTIONS,
      from: 'prisma',
      to: 'sdn',
      namespace: 'not-a-package',
    });
    expect(bad.ok).toBe(false);
    expect(isValidJavaPackage('app.models')).toBe(true);
    expect(isValidJavaPackage('app.class')).toBe(false);
  });

  it('can leave the header out and uses no javax import', () => {
    const output = emit(keysSchema(), { header: false });
    for (const text of Object.values(output.files)) {
      expect(text.startsWith('package app.models;')).toBe(true);
      expect(text).not.toContain('javax.');
      expect(text).not.toContain('jakarta.persistence');
    }
    expect(Object.values(emit(keysSchema()).files)[0]).toContain(
      '// <auto-generated>'
    );
  });

  it('writes nothing for an empty schema and is deterministic', async () => {
    expect(emit(schemaOf([])).files).toEqual({});
    const first = await convertCanonicalPrisma();
    const second = await convertCanonicalPrisma();
    expect(second.files).toEqual(first.files);
    expect(second.warnings).toEqual(first.warnings);
  });
});

describe('identifiers', () => {
  it('uses the internal id for a generated integer key and warns', async () => {
    const result = await convertCanonicalPrisma();
    const post: string = result.files?.['app/models/Post.java'] ?? '';
    expect(post).toContain('  @Id\n  @GeneratedValue\n  private Long id;');
    expect(post).not.toContain('@Property("id")');
    expect(result.warnings.join('\n')).toContain(
      "Post.id: the generated integer key became Neo4j's internal node id (@Id @GeneratedValue Long); it is not stored as a property named id"
    );
  });

  it('uses UUIDStringGenerator for a generated UUID key and an assigned id otherwise', () => {
    const output = emit(
      schemaOf([
        model('Gen', {
          fields: [idField({ type: 'uuid', default: { kind: 'uuid' } })],
        }),
        model('Natural', {
          fields: [idField({ type: 'string', default: undefined })],
        }),
      ])
    );
    const generated: string = file(output, 'Gen');
    expect(generated).toContain('@GeneratedValue(UUIDStringGenerator.class)');
    expect(generated).toContain('private String id;');
    expect(generated).toContain(
      'import org.springframework.data.neo4j.core.support.UUIDStringGenerator;'
    );
    const natural: string = file(output, 'Natural');
    expect(natural).toContain('  @Id\n  private String id;');
    expect(natural).not.toContain('@GeneratedValue');
  });

  it('gives a composite or missing key a generated graphId and warns', () => {
    const output = emit(keysSchema());
    const ledger: string = file(output, 'Ledger');
    expect(ledger).toContain('@Id\n  @GeneratedValue\n  private Long graphId;');
    expect(ledger).toContain('private Integer year;');
    expect(output.warnings.join('\n')).toContain(
      'Ledger: Spring Data Neo4j has no composite identifier, so the composite primary key (year, number) was written as plain properties'
    );
  });
});

describe('properties', () => {
  it('names the graph key with @Property when it differs from the Java name', async () => {
    const preserve = await convertCanonicalPrisma();
    const normalize = await convertCanonicalPrisma({ naming: 'normalize' });
    expect(preserve.files?.['app/models/Post.java']).toContain(
      '@Property("view_count")\n  private Integer viewCount = 0;'
    );
    expect(normalize.files?.['app/models/Post.java']).toContain(
      '  private Integer viewCount = 0;'
    );
    expect(normalize.files?.['app/models/Post.java']).not.toContain(
      '@Property("viewCount")'
    );
  });

  it('chooses Java types from the Neo4j types', () => {
    const output = emit(keysSchema());
    const item: string = file(output, 'Item');
    expect(item).toContain('private String title;');
    expect(item).toContain('private Long big;');
    expect(item).toContain('private Double ratio;');
    expect(item).toContain('private BigDecimal price;');
    expect(item).toContain('private Boolean flag = true;');
    expect(item).toContain('private LocalDate born;');
    expect(item).toContain('private ZonedDateTime seenAt;');
    expect(item).toContain('private LocalDateTime localAt;');
    expect(item).toContain('private LocalTime opens;');
    expect(item).toContain('private OffsetTime opensTz;');
    expect(item).toContain('private Duration span;');
    expect(item).toContain('private byte[] cover;');
    expect(item).toContain(
      'private List<String> labels_;'.replace('labels_', 'labels')
    );
    expect(item).toContain('private List<Integer> numbers;');
    expect(item).toContain('private String grid;');
    expect(item).toContain('private String settings;');
    expect(item).toContain('private Kind kind = Kind.BOOK;');
  });

  it('stores an enum by name, or through a converter when the stored values differ', () => {
    const output = emit(keysSchema());
    expect(output.files['app/models/Kind.java']).toContain('BOOK("book")');
    expect(output.files['app/models/KindConverter.java']).toContain(
      'implements Neo4jPersistentPropertyConverter<Kind>'
    );
    expect(file(output, 'Item')).toContain(
      '@ConvertWith(converter = KindConverter.class)'
    );
    const same = emit(
      schemaOf(
        [
          model('Thing', {
            fields: [idField(), field('status', { enumName: 'Status' })],
          }),
        ],
        [
          {
            name: 'Status',
            values: [
              { name: 'DRAFT', dbValue: 'DRAFT' },
              { name: 'LIVE', dbValue: 'LIVE' },
            ],
          },
        ]
      )
    );
    expect(file(same, 'Thing')).toContain('private Status status;');
    expect(file(same, 'Thing')).not.toContain('ConvertWith');
    expect(Object.keys(same.files)).not.toContain(
      'app/models/StatusConverter.java'
    );
  });

  it('writes a numeric enum through a converter that stores the number', () => {
    const output = emit(
      schemaOf(
        [
          model('Thing', {
            fields: [
              idField(),
              field('level', { type: 'int', enumName: 'Level' }),
            ],
          }),
        ],
        [
          {
            name: 'Level',
            values: [
              { name: 'LOW', dbValue: '0' },
              { name: 'HIGH', dbValue: '1' },
            ],
          },
        ]
      )
    );
    expect(output.files['app/models/LevelConverter.java']).toContain(
      'source.asInt()'
    );
    expect(file(output, 'Thing')).toContain(
      '@ConvertWith(converter = LevelConverter.class)'
    );
  });

  it('drops the defaults it cannot hold and names the field', () => {
    const { warnings } = emit(
      schemaOf([
        model('Thing', {
          fields: [
            idField(),
            field('a', {
              default: { kind: 'dbExpression', expression: 'now()' },
            }),
            field('b', { type: 'dateTime', default: { kind: 'now' } }),
            field('c', {
              type: 'int',
              arrayDepth: 1,
              default: { kind: 'literal', value: 1 },
            }),
          ],
        }),
      ])
    );
    const joined: string = warnings.join('\n');
    expect(joined).toContain(
      'Thing.a: the database default now() has no Spring Data Neo4j equivalent and was dropped'
    );
    expect(joined).toContain(
      'Thing.b: the default of the current time has no Spring Data Neo4j equivalent'
    );
    expect(joined).toContain(
      'Thing.c: the default of an array has no Spring Data Neo4j equivalent'
    );
  });

  it('warns once per model that constraints and indexes are not created', () => {
    const { warnings, files } = emit(keysSchema());
    const joined: string = warnings.join('\n');
    expect(joined).toContain(
      'Ledger: Spring Data Neo4j creates no constraints or indexes, so the constraints and indexes of the source (unique ('
    );
    expect(joined).toContain('create them with --to neo4j.');
    expect(files['app/models/Ledger.java']).toContain(
      'creates no constraints or indexes'
    );
    expect(joined).not.toContain('Item.id: the default of a generated UUID');
    expect(joined).not.toContain('LineItem.id: auto-increment');
  });

  it('renames a class that would hide an import and keeps the label', () => {
    const output = emit(
      schemaOf([
        model('Node', { fields: [idField()] }),
        model('Relationship', { fields: [idField()] }),
      ])
    );
    expect(file(output, 'NodeEntity')).toContain(
      '@Node("Node")\npublic class NodeEntity {'
    );
    expect(output.warnings.join('\n')).toContain(
      'Node: "Node" is a name the generated code uses or another type has, so the class was named "NodeEntity"; @Node keeps the label Node.'
    );
  });
});

describe('relationships', () => {
  it('writes a single value on the owner and a list on the target', async () => {
    const result = await convertCanonicalPrisma();
    const post: string = result.files?.['app/models/Post.java'] ?? '';
    const user: string = result.files?.['app/models/User.java'] ?? '';
    expect(post).toContain(
      '@Relationship(type = "AUTHOR", direction = Relationship.Direction.OUTGOING)\n  private User author;'
    );
    expect(user).toContain(
      '@Relationship(type = "AUTHOR", direction = Relationship.Direction.INCOMING)\n  private List<Post> posts = new ArrayList<>();'
    );
    expect(user).toContain(
      'private List<Post> editedPosts = new ArrayList<>();'
    );
  });

  it('writes the reverse of a one-to-one key as a single value', async () => {
    const result = await convertCanonicalPrisma();
    expect(result.files?.['app/models/User.java']).toContain(
      '@Relationship(type = "USER", direction = Relationship.Direction.INCOMING)\n  private Profile profile;'
    );
  });

  it('writes a join table as one relationship with a properties class for each direction', () => {
    const output = emit(joinsSchema());
    const student: string = file(output, 'Student');
    expect(student).toContain(
      '@Relationship(type = "COURSES", direction = Relationship.Direction.OUTGOING)\n  private List<EnrollmentCourse> courses = new ArrayList<>();'
    );
    expect(student).toContain('private List<Club> club = new ArrayList<>();');
    const forward: string = file(output, 'EnrollmentCourse');
    expect(forward).toContain(
      '@RelationshipProperties\npublic class EnrollmentCourse {'
    );
    expect(forward).toContain('@RelationshipId\n  private Long id;');
    expect(forward).toContain('@TargetNode\n  private Course course;');
    expect(forward).toContain('private String ticket;');
    expect(file(output, 'EnrollmentStudent')).toContain(
      '@TargetNode\n  private Student student;'
    );
    expect(file(output, 'Course')).toContain(
      'private List<EnrollmentStudent> students = new ArrayList<>();'
    );
    expect(Object.keys(output.files)).not.toContain(
      'app/models/Enrollment.java'
    );
    expect(Object.keys(output.files)).not.toContain(
      'app/models/Membership.java'
    );
    const joined: string = output.warnings.join('\n');
    expect(joined).toContain(
      'Enrollment: the join table became a relationship, so its surrogate key id was dropped.'
    );
    expect(joined).toContain(
      'Enrollment: the join table became the relationship (:Student)-[:COURSES]->(:Course) instead of a node class.'
    );
  });

  it('writes a many-to-many pair once and a composite foreign key as one relationship', () => {
    const joins = emit(joinsSchema());
    expect(file(joins, 'Course')).toContain(
      'private List<Teacher> teachers = new ArrayList<>();'
    );
    expect(file(joins, 'Teacher')).toContain(
      'private List<Course> courses = new ArrayList<>();'
    );
    const keys = emit(keysSchema());
    expect(file(keys, 'LineItem')).toContain(
      '@Relationship(type = "LEDGER", direction = Relationship.Direction.OUTGOING)\n  private Ledger ledger;'
    );
    expect(keys.warnings.join('\n')).toContain(
      'LineItem.ledger: the foreign key to Ledger became the relationship (:LineItem)-[:LEDGER]->(:Ledger); Spring Data Neo4j does not enforce the on delete action (cascade), and ledger_year, ledger_number were kept as plain properties'
    );
  });

  it('numbers a reverse name that is taken and reports a missing target', () => {
    const { files, warnings } = emit(
      schemaOf([
        model('Author', { fields: [idField()] }),
        model('Story', {
          fields: [idField()],
          relations: [
            relation('writer', 'Author'),
            relation('proofreader', 'Author'),
            relation('ghost', 'Missing'),
          ],
        }),
      ])
    );
    expect(files['app/models/Author.java']).toContain(
      'private List<Story> stories = new ArrayList<>();'
    );
    expect(files['app/models/Author.java']).toContain(
      'private List<Story> stories2 = new ArrayList<>();'
    );
    expect(warnings.join('\n')).toContain(
      'Author.stories: "stories" is taken in Author, so the field was named "stories2".'
    );
    expect(warnings).toContain(
      'Story.ghost: the target model Missing is not in the schema, so the relationship was not written.'
    );
  });
});

describe('agreement with the other Neo4j writers', () => {
  it('passes the structural check', () => {
    for (const schema of [joinsSchema(), keysSchema()]) {
      expect(checkSdnOutput(schema, emit(schema).files)).toEqual([]);
    }
    expect(
      checkSdnOutput(joinsSchema(), { x: 'class X {}' }).length
    ).toBeGreaterThan(3);
  });
});

