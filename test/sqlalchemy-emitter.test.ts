describe('sqlalchemy emitter: enums', () => {
  const schema = (): IrSchema =>
    schemaOf(
      [
        model('Thing', {
          tableName: 'things',
          fields: [idField(), field('status', { enumName: 'Status' })],
        }),
      ],
      [STATUS]
    );

  it('writes an enum.Enum class and binds it with the stored values', () => {
    const output: EmitOutput = emit(schema());
    expect(output.text).toContain(
      'class Status(enum.Enum):\n    DRAFT = "draft"\n    LIVE = "live"\n'
    );
    expect(squash(output.text)).toContain(
      'status: Mapped[Status] = mapped_column(Enum(Status, name="Status", values_callable=lambda members: [member.value for member in members]))'
    );
    expect(output.text).toContain('import enum\n');
    expect(output.warnings).toEqual([]);
  });

  it('writes the enum with sa_type in SQLModel', () => {
    expect(code(schema(), 'sqlmodel')).toContain(
      'status: Status = Field(sa_type=Enum(Status, name="Status", values_callable=lambda members: [member.value for member in members]))'
    );
  });

  it('names the database type after dbName, snake_case when normalizing', () => {
    const named: IrSchema = schema();
    named.enums = [{ ...STATUS, dbName: 'StatusType' }];
    expect(code(named)).toContain('name="StatusType"');
    expect(code(named, 'sqlalchemy', 'normalize')).toContain(
      'name="status_type"'
    );
  });

  it('repairs member names that are not Python identifiers', () => {
    const odd: IrEnum = {
      name: 'Odd',
      values: [
        { name: 'class', dbValue: 'a' },
        { name: '1st', dbValue: 'b' },
        { name: 'two words', dbValue: 'c' },
        { name: 'name', dbValue: 'd' },
        { name: '_hidden_', dbValue: 'e' },
        { name: 'dup', dbValue: 'f' },
        { name: 'dup', dbValue: 'g' },
        { name: 'ok', dbValue: 'it"s' },
      ],
    };
    const output: EmitOutput = emit(
      schemaOf(
        [
          model('Thing', {
            tableName: 'things',
            fields: [idField(), field('odd', { enumName: 'Odd' })],
          }),
        ],
        [odd]
      )
    );
    expect(output.text).toContain(
      [
        'class Odd(enum.Enum):',
        '    class_ = "a"',
        '    v_1st = "b"',
        '    two_words = "c"',
        '    name_ = "d"',
        '    v_hidden_ = "e"',
        '    dup = "f"',
        '    dup2 = "g"',
        '    ok = "it\\"s"',
      ].join('\n')
    );
    expect(output.warnings).toContain(
      'enum Odd: the member "class" was written as class_.'
    );
    expect(output.warnings).toContain(
      'enum Odd: the member "dup" was written as dup2.'
    );
  });

  it('renames an enum that collides with a model or an import', () => {
    const output: EmitOutput = emit(
      schemaOf(
        [
          model('Other', { tableName: 'others' }),
          model('Thing', {
            tableName: 'things',
            fields: [
              idField(),
              field('a', { enumName: 'Other' }),
              field('b', { enumName: 'Enum' }),
              field('c', { enumName: 'my enum' }),
            ],
          }),
        ],
        [
          { name: 'Other', values: [{ name: 'A', dbValue: 'a' }] },
          { name: 'Enum', values: [{ name: 'A', dbValue: 'a' }] },
          { name: 'my enum', values: [{ name: 'A', dbValue: 'a' }] },
        ]
      )
    );
    expect(output.text).toContain('class OtherEnum(enum.Enum):');
    expect(output.text).toContain('class EnumEnum(enum.Enum):');
    expect(output.text).toContain('class MyEnum(enum.Enum):');
    expect(output.warnings).toContain(
      'enum Other: the Python class was named OtherEnum.'
    );
  });

  it('writes a field of an enum without values as a string and warns', () => {
    const output: EmitOutput = emit(
      schemaOf(
        [
          model('Thing', {
            tableName: 'things',
            fields: [idField(), field('kind', { enumName: 'Empty' })],
          }),
        ],
        [{ name: 'Empty', values: [] }]
      )
    );
    expect(output.text).toContain('kind: Mapped[str] = mapped_column(String)');
    expect(output.warnings).toEqual([
      'enum Empty: an enum without values cannot be written; fields that use it became plain strings.',
    ]);
  });

  it('writes an array of enums', () => {
    const text: string = code(
      schemaOf(
        [
          model('Thing', {
            tableName: 'things',
            fields: [
              idField(),
              field('statuses', { enumName: 'Status', arrayDepth: 1 }),
            ],
          }),
        ],
        [STATUS]
      )
    );
    expect(text).toContain(
      'statuses: Mapped[list[Status]] = mapped_column(ARRAY(Enum(Status'
    );
  });
});

describe('sqlalchemy emitter: identifiers', () => {
  it('turns names into snake_case attributes and keeps the column name', () => {
    const output: EmitOutput = emit(
      thing([
        idField(),
        field('firstName', { columnName: 'FirstName' }),
        field('HTTPCode', { columnName: 'http_code', type: 'int' }),
        field('first-name', { columnName: 'first name', isNullable: true }),
      ])
    );
    expect(output.text).toContain(
      'first_name: Mapped[str] = mapped_column("FirstName", String)'
    );
    expect(output.text).toContain(
      'http_code: Mapped[int] = mapped_column(Integer)'
    );
    expect(output.text).toContain(
      'first_name_: Mapped[Optional[str]] = mapped_column("first name", String)'
    );
    expect(output.warnings).toEqual([
      'Thing.first-name: the name "first-name" collides with another attribute of the class or a name used by the module; it was written as first_name_.',
    ]);
  });

  it.each([
    ['class', 'class_'],
    ['from', 'from_'],
    ['None', 'none'],
    ['metadata', 'metadata_'],
    ['registry', 'registry_'],
    ['text', 'text_'],
    ['datetime', 'datetime_'],
    ['uuid', 'uuid_'],
    ['func', 'func_'],
    ['list', 'list_'],
    ['str', 'str_'],
    ['Mapped', 'mapped'],
  ])(
    'does not let the attribute %s shadow a name of the class body',
    (name, written) => {
      const output: EmitOutput = emit(thing([idField(), field(name)]));
      expect(output.text).toContain(`    ${written}: Mapped[str]`);
    }
  );

  it('keeps the original column name when an attribute is renamed', () => {
    expect(emit(thing([idField(), field('class')])).text).toContain(
      'class_: Mapped[str] = mapped_column("class", String)'
    );
    expect(emit(thing([idField(), field('class')]), 'sqlmodel').text).toContain(
      'class_: str = Field(sa_column_kwargs={"name": "class"})'
    );
  });

  it('avoids the names pydantic and SQLModel reserve', () => {
    const text: string = emit(
      thing([idField(), field('json'), field('copy'), field('schema')]),
      'sqlmodel'
    ).text;
    expect(text).toContain('    json_: str');
    expect(text).toContain('    copy_: str');
    expect(text).toContain('    schema_: str');
    expect(emit(thing([idField(), field('json')])).text).toContain(
      '    json: Mapped[str]'
    );
  });

  it('gives a name that is empty or starts with a digit a usable attribute', () => {
    const text: string = emit(
      thing([idField(), field('2fa'), field('$'), field('__x__')])
    ).text;
    expect(text).toContain('    field_2fa: Mapped[str]');
    expect(text).toContain(
      '    field: Mapped[str] = mapped_column("$", String)'
    );
    expect(text).toContain(
      '    x: Mapped[str] = mapped_column("__x__", String)'
    );
  });

  it('repairs class names', () => {
    const output: EmitOutput = emit(
      schemaOf([
        model('Index', { tableName: 'indexes' }),
        model('String', { tableName: 'strings' }),
        model('Base', { tableName: 'bases' }),
        model('my model', { tableName: 'my_models' }),
        model('3d', { tableName: 'threed' }),
        model('list', { tableName: 'lists' }),
        model('legacy_order', { tableName: 'legacy' }),
      ])
    );
    for (const name of [
      'IndexModel',
      'StringModel',
      'BaseModel',
      'MyModel',
      'Model3d',
      'listModel',
      'legacy_order',
    ]) {
      expect(output.text).toContain(`class ${name}(Base):`);
    }
    expect(output.warnings).toContain(
      'Index: the name collides with a Python or SQLAlchemy name used by the module; the class was written as IndexModel.'
    );
    expect(output.warnings).toContain(
      'my model: not a valid Python class name; the class was written as MyModel.'
    );
  });

  it('refers to a renamed class in relationships', () => {
    const schema: IrSchema = schemaOf([
      model('Index', { tableName: 'indexes' }),
      model('Thing', {
        tableName: 'things',
        relations: [relation('index', 'Index', { relatedName: 'things' })],
      }),
    ]);
    const text: string = code(schema);
    expect(text).toContain(
      'index: Mapped["IndexModel"] = relationship(back_populates="things")'
    );
    expect(text).toContain(
      'things: Mapped[list["Thing"]] = relationship(back_populates="index", passive_deletes=True)'
    );
  });

  it('keeps a column attribute off the name of an enum class', () => {
    const output: EmitOutput = emit(
      schemaOf(
        [
          model('Thing', {
            tableName: 'things',
            fields: [idField(), field('color', { enumName: 'color' })],
          }),
        ],
        [{ name: 'color', values: [{ name: 'RED', dbValue: 'red' }] }]
      )
    );
    expect(squash(output.text)).toContain(
      '    color_: Mapped[color] = mapped_column("color", Enum(color'
    );
  });

  it('names the foreign-key column apart from a relationship of the same name', () => {
    const schema: IrSchema = schemaOf([
      model('Series', { tableName: 'series' }),
      model('Row', {
        tableName: 'rows',
        relations: [
          relation('table', 'Series', {
            columnName: 'table',
            relatedName: 'rows',
          }),
        ],
      }),
    ]);
    const row: string = classOf(code(schema), 'Row');
    expect(row).toContain(
      'table_id: Mapped[int] = mapped_column("table", Integer'
    );
    expect(row).toContain('table: Mapped["Series"] = relationship(');
  });

  it('keeps an association table variable off every attribute name', () => {
    const schema: IrSchema = schemaOf([
      model('Post', {
        tableName: 'posts',
        fields: [idField(), field('posts_tags')],
        relations: [relation('tags', 'Tag', { kind: 'manyToMany' })],
      }),
      model('Tag', { tableName: 'tags' }),
    ]);
    const text: string = code(schema);
    expect(text).toContain('posts_tags2 = Table("posts_tags"');
    expect(text).toContain('secondary=posts_tags2');
  });
});

describe('sqlalchemy emitter: ordering', () => {
  it('writes a class after the classes its foreign keys point at', () => {
    const schema: IrSchema = schemaOf([
      model('C', {
        tableName: 'c',
        relations: [relation('b', 'B', { relatedName: 'cs' })],
      }),
      model('B', {
        tableName: 'b',
        relations: [relation('a', 'A', { relatedName: 'bs' })],
      }),
      model('A', { tableName: 'a' }),
    ]);
    const text: string = emit(schema).text;
    const positions: number[] = ['A', 'B', 'C'].map((name: string) =>
      text.indexOf(`class ${name}(`)
    );
    expect(positions).toEqual([...positions].sort((x, y) => x - y));
    expect(positions.every((position: number) => position > 0)).toBe(true);
  });

  it('writes every class of a cycle once', () => {
    const schema: IrSchema = schemaOf([
      model('A', {
        tableName: 'a',
        relations: [
          relation('b', 'B', { isNullable: true, relatedName: 'as_' }),
        ],
      }),
      model('B', {
        tableName: 'b',
        relations: [
          relation('a', 'A', { isNullable: true, relatedName: 'bs' }),
        ],
      }),
    ]);
    const text: string = emit(schema).text;
    expect(text.match(/^class A\(/gm)).toHaveLength(1);
    expect(text.match(/^class B\(/gm)).toHaveLength(1);
  });

  it('writes enums, then association tables, then classes', () => {
    const text: string = emit(
      schemaOf(
        [
          model('Post', {
            tableName: 'posts',
            fields: [idField(), field('status', { enumName: 'Status' })],
            relations: [relation('tags', 'Tag', { kind: 'manyToMany' })],
          }),
          model('Tag', { tableName: 'tags' }),
        ],
        [STATUS]
      )
    ).text;
    expect(text.indexOf('class Base(')).toBeLessThan(
      text.indexOf('class Status(')
    );
    expect(text.indexOf('class Status(')).toBeLessThan(
      text.indexOf('posts_tags = Table(')
    );
    expect(text.indexOf('posts_tags = Table(')).toBeLessThan(
      text.indexOf('class Post(')
    );
  });
});

