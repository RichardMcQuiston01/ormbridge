describe('sqlalchemy emitter: the format adapter', () => {
  it('is registered for writing, without an extension', () => {
    const adapter = expectOk(getFormat('sqlalchemy'));
    expect(adapter.extensions).toEqual([]);
    expect(adapter.emit).toBeDefined();
    expect(adapter.description).toContain('SQLModel');
    expect(listFormats().map((format) => format.name)).toContain('sqlalchemy');
  });

  it('is listed by the formats command', () => {
    expect(describeFormats(listFormats())).toMatch(
      /sqlalchemy\s+extensions: \(none\)\s+(read \+ )?write\s+SQLAlchemy 2\.0/
    );
  });

  it('writes SQLAlchemy by default and SQLModel for the sqlmodel style', () => {
    const adapter = expectOk(getFormat('sqlalchemy'));
    const schema: IrSchema = thing([idField()]);
    const plain = expectOk(
      adapter.emit?.(schema, DEFAULT_OPTIONS) ?? {
        ok: false as const,
        error: { code: 'EMIT_FAILED' as const, message: 'no emit' },
      }
    );
    expect(plain.text).toContain('class Thing(Base):');
    const sqlmodel = expectOk(
      adapter.emit?.(schema, { ...DEFAULT_OPTIONS, style: 'sqlmodel' }) ?? {
        ok: false as const,
        error: { code: 'EMIT_FAILED' as const, message: 'no emit' },
      }
    );
    expect(sqlmodel.text).toContain('class Thing(SQLModel, table=True):');
  });

  it('rejects an unknown style with the valid values', () => {
    const adapter = expectOk(getFormat('sqlalchemy'));
    const result = adapter.emit?.(thing([idField()]), {
      ...DEFAULT_OPTIONS,
      style: 'peewee' as SqlAlchemyStyle,
    });
    expect(result?.ok).toBe(false);
    if (result !== undefined && !result.ok) {
      expect(result.error.code).toBe('INVALID_OPTION');
      expect(result.error.message).toBe(
        'Invalid style "peewee". Expected one of: sqlalchemy, sqlmodel.'
      );
    }
  });

  it('recognises the style names', () => {
    expect(SQLALCHEMY_STYLES).toEqual(['sqlalchemy', 'sqlmodel']);
    expect(isSqlAlchemyStyle('sqlmodel')).toBe(true);
    expect(isSqlAlchemyStyle('django')).toBe(false);
  });

  it('converts through convertText with and without --style', async () => {
    const source = {
      path: 'schema.prisma',
      text: 'model Note {\n  id Int @id @default(autoincrement())\n  body String\n}\n',
    };
    const plain = expectOk(
      await convertText([source], {
        ...DEFAULT_OPTIONS,
        from: 'prisma',
        to: 'sqlalchemy',
      })
    );
    expect(plain.output).toContain('class Note(Base):');
    const sqlmodel = expectOk(
      await convertText([source], {
        ...DEFAULT_OPTIONS,
        from: 'prisma',
        to: 'sqlalchemy',
        style: 'sqlmodel',
      })
    );
    expect(sqlmodel.output).toContain('class Note(SQLModel, table=True):');
    expect(sqlmodel.files).toBeUndefined();
  });
});

