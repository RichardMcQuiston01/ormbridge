function emit(
  schema: IrSchema,
  style: SqlAlchemyStyle = 'sqlalchemy',
  naming: NamingMode = 'preserve'
): EmitOutput {
  return emitSqlAlchemy(schema, { naming, style });
}

/** Joins the lines of wrapped calls, so assertions do not depend on where a line was broken. */
function squash(text: string): string {
  return text
    .replace(/\(\n\s+/g, '(')
    .replace(/\{\n\s+/g, '{')
    .replace(/\[\n\s+/g, '[')
    .replace(/,\n\s*\)/g, ')')
    .replace(/,\n\s+\}/g, '}')
    .replace(/,\n\s+\]/g, ']')
    .replace(/,\n\s+(?=[A-Za-z_"'{[(])/g, ', ');
}

function code(
  schema: IrSchema,
  style: SqlAlchemyStyle = 'sqlalchemy',
  naming: NamingMode = 'preserve'
): string {
  return squash(emit(schema, style, naming).text);
}

/** The squashed text of one class. */
function classOf(text: string, name: string): string {
  const match: RegExpExecArray | null = new RegExp(
    `^class ${name}\\([^\\n]*\\n(?:(?!\\n\\n\\nclass |\\n\\n\\n[a-z_]+ = ).)*`,
    'ms'
  ).exec(text);
  if (match === null) {
    throw new Error(`No class ${name} in:\n${text}`);
  }
  return match[0];
}

/** A one-model schema. */
function thing(fields: IrField[], extra: Partial<IrModel> = {}): IrSchema {
  return schemaOf([model('Thing', { tableName: 'things', fields, ...extra })]);
}

