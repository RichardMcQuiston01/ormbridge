import type { SqlDialect } from '../src/parsers/sqlSyntax.js';

/**
 * One case per statement form that changes a schema after it was created. Each case is a small script (the
 * setup, then the statements under test) that the replay test reads and writes as a summary of the schema
 * and its warnings. The summaries are the golden files in test/golden-extras/sql-migration-replay.
 */
export interface ReplayCase {
  name: string;
  sql: string;
}

export interface ReplayDialectCases {
  /** Name of the dialect for the golden file. */
  label: string;
  dialect: SqlDialect;
  cases: ReplayCase[];
}

